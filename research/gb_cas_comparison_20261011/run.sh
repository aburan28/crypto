#!/usr/bin/env bash
# Times this repository's F_p F4 and inherited-F4 decomposition oracle
# against msolve and Singular on identical exported systems, and writes
# the Magma scripts for the same systems (Magma is not installed here).
#
#   run.sh <bin_dir> <outdir> [rounds] [bool_timeout_s] [singular_bool_timeout_s]
#
# <bin_dir> holds release builds of gb_cas_export and f6_ic_probe.
# POLYBORI_PY: a Python with passagemath-brial, for polybori_gb.py
# (external reference standing in for Magma's Boolean F4); unset skips it.
# Writes <outdir>/inputs-fp, <outdir>/inputs-bool-n17, <outdir>/raw/*.
set -uo pipefail
BIN=$1
OUT=$2
ROUNDS=${3:-3}
BOOL_TIMEOUT=${4:-600}
SING_BOOL_TIMEOUT=${5:-120}
HERE=$(cd "$(dirname "$0")" && pwd)
mkdir -p "$OUT/raw" "$OUT/inputs-fp" "$OUT/inputs-bool-n17"

now_ms() { echo $(( $(date +%s%N) / 1000000 )); }
versions() {
  echo "msolve $(dpkg-query -W -f='${Version}' msolve 2>/dev/null)"
  echo "singular $(dpkg-query -W -f='${Version}' singular 2>/dev/null)"
  echo "host $(lscpu | sed -n 's/^Model name: *//p') nproc $(nproc)"
}
versions > "$OUT/raw/versions.txt"

CASES=$("$BIN/gb_cas_export" fp "$OUT/inputs-fp" 1 | sed -n 's/.*"case":"\([^"]*\)".*/\1/p')

# ── F_p: f4_fp vs msolve vs Singular, interleaved rounds ──
for r in $(seq 1 "$ROUNDS"); do
  for th in 1 4; do
    RAYON_NUM_THREADS=$th "$BIN/gb_cas_export" fp "$OUT/inputs-fp" 3 \
      > "$OUT/raw/fp_ours_t$th.round$r.jsonl"
  done
  : > "$OUT/raw/fp_external.round$r.tsv"
  for c in $CASES; do
    for th in 1 4; do
      a=$(now_ms)
      internal=$(msolve -v 2 -g 2 -t "$th" -f "$OUT/inputs-fp/$c.ms" -o "$OUT/raw/$c.msolve_t$th.out" 2>&1 \
        | sed -n 's/^overall(elapsed) *\([0-9.]*\) sec/\1/p')
      b=$(now_ms)
      printf '%s\tmsolve_t%s\twall_ms\t%s\tinternal_s\t%s\n' "$c" "$th" $((b - a)) "$internal" \
        >> "$OUT/raw/fp_external.round$r.tsv"
    done
    s=$(Singular -q "$OUT/inputs-fp/$c.sing" | tr '\n' ' ')
    printf '%s\tsingular_std\t%s\n' "$c" "$s" >> "$OUT/raw/fp_external.round$r.tsv"
  done
done

# ── Boolean: the n = 17 decomposition roots ──
DUMP="$OUT/raw/n17_node_dump.jsonl"
rm -f "$DUMP"
KIC_F4_NODE_DUMP="$DUMP" "$BIN/f6_ic_probe" --a 1 --n 17 --dim 6 --targets 8 --engines f4 --reps 1 > /dev/null
"$BIN/gb_cas_export" bool "$DUMP" "$OUT/inputs-bool-n17" > "$OUT/raw/bool_n17_roots.jsonl"
rm -f "$DUMP" # every node of the tree; regenerated by the line above
"$BIN/f6_ic_probe" --a 1 --n 17 --dim 6 --targets 8 --engines f4,f6p --reps 3 > "$OUT/raw/bool_n17_ours.jsonl"
: > "$OUT/raw/bool_n17_external.tsv"
for f in "$OUT"/inputs-bool-n17/root*.ms; do
  c=$(basename "$f" .ms)
  a=$(now_ms)
  if timeout "$BOOL_TIMEOUT" msolve -g 2 -t 1 -f "$f" -o "$OUT/raw/$c.msolve_t1.out" > /dev/null 2>&1; then st=ok; else st="exit$?"; fi
  b=$(now_ms)
  printf '%s\tmsolve_t1\twall_ms\t%s\tstatus\t%s\n' "$c" $((b - a)) "$st" >> "$OUT/raw/bool_n17_external.tsv"
  if [ -n "${POLYBORI_PY:-}" ]; then
    if s=$(timeout "$BOOL_TIMEOUT" "$POLYBORI_PY" "$HERE/polybori_gb.py" "$f" 2>&1 | tail -1); then st=ok; else st="exit$?"; fi
    printf '%s\tpolybori\tstatus\t%s\t%s\n' "$c" "$st" "$s" >> "$OUT/raw/bool_n17_external.tsv"
  fi
  a=$(now_ms)
  if s=$(timeout "$SING_BOOL_TIMEOUT" Singular -q "$OUT/inputs-bool-n17/$c.sing" | tr '\n' ' '); then st=ok; else st="exit$?"; fi
  b=$(now_ms)
  printf '%s\tsingular_std\twall_ms\t%s\tstatus\t%s\t%s\n' "$c" $((b - a)) "$st" "$s" >> "$OUT/raw/bool_n17_external.tsv"
done
