#!/usr/bin/env bash
# PS-0: baseline, host manifest, verdict corpus (research/pdp_oracle_speedup_20261011/protocols/PS-0.md).
# Run from anywhere in the repository on a QUIET machine: the timed runs go through
# tools/isolated_bench.py, which refuses to start when other processes are busy and
# marks a run "contended" when they were.  Contended runs are kept and counted.
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"
OUT=research/pdp_oracle_speedup_20261011/baseline_v1
BIN=target/release/examples/pdp_speedup
CNT=target/opcount/release/examples/pdp_speedup
SCR=${PS0_SCRATCH:-/tmp/ps0_bin}          # binaries are kept here, not committed; hashes are in manifest.json
CPU=${PS0_CPU:-3}
ROUNDS=${PS0_ROUNDS:-5}
mkdir -p "$OUT"/{corpus,raw,callgrind,opcount} "$SCR"

# The frozen timing plan: refuted targets taken in corpus order, passes over them.
declare -A TARGETS=( [8]=16 [9]=16 [10]=16 [11]=16 [12]=6 )
declare -A PASSES=(  [8]=40 [9]=10 [10]=3  [11]=1  [12]=1 )

STAGES=${PS0_STAGES:-all}      # "all", or "timing" to (re)run only the interleaved timing stage
if [ "$STAGES" = all ]; then
python3 tools/isolated_bench.py busy -- cargo build --release --example pdp_speedup
CARGO_TARGET_DIR=target/opcount python3 tools/isolated_bench.py busy -- \
  cargo build --release --example pdp_speedup --features pdp-opcount
cp "$BIN" "$SCR/pdp_speedup_A"; cp "$BIN" "$SCR/pdp_speedup_B"      # A/A: one build, two files
cp "$CNT" "$SCR/pdp_speedup_opcount"
"$OUT/manifest.sh" "$SCR/pdp_speedup_A" "$SCR/pdp_speedup_B" "$SCR/pdp_speedup_opcount" > "$OUT/manifest.json"

# 1. corpus: generate twice (determinism), commit one; replay the baseline three times.
: > "$OUT/raw/corpus_gen.log"; : > "$OUT/digests.txt"
for l in 8 9 10 11 12; do
  # The committed corpus was generated by an earlier run of the same code; this run
  # regenerates it and requires a byte-identical file (determinism across runs).
  [ -f "$OUT/corpus/corpus_l$l.txt" ] || "$SCR/pdp_speedup_A" corpus --l "$l" --out "$OUT/corpus/corpus_l$l.txt" --threads 3
  "$SCR/pdp_speedup_A" corpus --l "$l" --out "$SCR/regen_l$l.txt" --threads 3 | tee -a "$OUT/raw/corpus_gen.log"
  cmp "$OUT/corpus/corpus_l$l.txt" "$SCR/regen_l$l.txt" && echo "l=$l corpus regenerated byte-identical" | tee -a "$OUT/raw/corpus_gen.log"
  for run in 1 2 3; do
    echo -n "run=$run " >> "$OUT/digests.txt"
    "$SCR/pdp_speedup_A" verify --l "$l" --corpus "$OUT/corpus/corpus_l$l.txt" | tee -a "$OUT/digests.txt"
  done
done

# 2. independent brute-force cross-check of the root sets (general F2m evaluator, all sorted triples)
"$SCR/pdp_speedup_A" brute --l 8 --corpus "$OUT/corpus/corpus_l8.txt" --threads 3 | tee "$OUT/raw/brute_l8.log"
"$SCR/pdp_speedup_A" brute --l 9 --corpus "$OUT/corpus/corpus_l9.txt" --threads 3 --limit 16 | tee "$OUT/raw/brute_l9_first16.log"

# 3. counted field operations per pair (separate, instrumented build)
for l in 8 9 10 11 12; do
  "$SCR/pdp_speedup_opcount" count --l "$l" --corpus "$OUT/corpus/corpus_l$l.txt" --targets 2 | tee -a "$OUT/opcount/counts.jsonl"
done

# 4. instructions retired per pair under callgrind (one refuted target, inclusive of run_one)
for l in 8 9; do
  valgrind --tool=callgrind --callgrind-out-file="$OUT/callgrind/cg_l$l.out" --toggle-collect='*run_one*' \
    "$SCR/pdp_speedup_A" one --l "$l" --corpus "$OUT/corpus/corpus_l$l.txt" 2>&1 | tee "$OUT/callgrind/cg_l$l.log"
done
fi   # end of stages other than timing

# 5. A/A with ABAB interleaving: the same build under two names, alternating, ROUNDS rounds.
# isolated_bench.py refuses to start a run when other processes used CPU during its settle
# window; that is not a result, so the start is retried (and logged), and a run that did
# start but was contended is kept in iso.jsonl and counted by `summarize`.
[ -f "$OUT/raw/iso.jsonl" ] || : > "$OUT/raw/iso.jsonl"; [ -f "$OUT/raw/times.jsonl" ] || : > "$OUT/raw/times.jsonl"
timed_run() {   # side l round
  local side=$1 l=$2 r=$3 label="$1-l$2-r$3"
  grep -q "\"label\":\"$label\"" "$OUT/raw/times.jsonl" && return 0     # already recorded
  for try in $(seq 1 100); do
    if python3 tools/isolated_bench.py run --cpus "$CPU" --wait --out "$OUT/raw/iso.jsonl" --label "$label" -- \
         "$SCR/pdp_speedup_$side" time --l "$l" --corpus "$OUT/corpus/corpus_l$l.txt" --arm baseline \
         --targets "${TARGETS[$l]}" --passes "${PASSES[$l]}" --label "$label" --out "$OUT/raw/times.jsonl"; then
      return 0
    fi
    echo "$label attempt $try refused to start (machine busy)" >> "$OUT/raw/refused_starts.log"
    sleep 3
  done
  echo "$label never started" >&2; return 1
}
for l in 8 9 10 11 12; do
  for r in $(seq 1 "$ROUNDS"); do
    for side in A B; do timed_run "$side" "$l" "$r"; done
  done
done
"$SCR/pdp_speedup_A" summarize --times "$OUT/raw/times.jsonl" --iso "$OUT/raw/iso.jsonl" --a A --b B > "$OUT/aa_summary.md"
cat "$OUT/aa_summary.md"
