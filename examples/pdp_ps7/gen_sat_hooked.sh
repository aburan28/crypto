#!/usr/bin/env bash
# Regenerate examples/pdp_ps7/sat_hooked.rs from the library solver.
#
#   gen_sat_hooked.sh          write sat_hooked.rs
#   gen_sat_hooked.sh --check  fail if sat_hooked.rs is not what this script writes
#
# sat_hooked.rs = src/cryptanalysis/sat.rs
#   - cut before `#[cfg(test)] mod tests` (the tests stay in the library),
#   - plus `Solver::solve_with_hooks` (sat_hook_method.rs.in) inserted before `Solver::model`,
#   - plus the `ShellHooks` trait (sat_hook_trait.rs.in) appended.
# The library file is not edited; the copy exists because the library has no branching or
# learnt-clause hook and tracked files were off limits for PS-7.
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"
SRC=src/cryptanalysis/sat.rs
DIR=examples/pdp_ps7
OUT=${GEN_OUT:-$DIR/sat_hooked.rs}
cut=$(grep -n '^mod tests {' "$SRC" | head -1 | cut -d: -f1)
cut=$((cut - 1))                                   # the `#[cfg(test)]` line above it
anchor=$(grep -n 'Get the satisfying assignment after a successful' "$SRC" | head -1 | cut -d: -f1)
[ "$(sed -n "${cut}p" "$SRC")" = '#[cfg(test)]' ] || { echo "unexpected layout of $SRC" >&2; exit 1; }
{
  printf '//! GENERATED by gen_sat_hooked.sh from %s (git blob %s).  Do not edit.\n' "$SRC" "$(git hash-object "$SRC")"
  printf '//! Library solver plus `Solver::solve_with_hooks` and `ShellHooks` for PS-7; see the script.\n'
  sed -n "1,$((anchor - 1))p" "$SRC"
  cat "$DIR/sat_hook_method.rs.in"
  sed -n "${anchor},$((cut - 1))p" "$SRC"
  cat "$DIR/sat_hook_trait.rs.in"
} > "${OUT}.tmp"
if [ "${1:-}" = "--check" ]; then
  cmp -s "${OUT}.tmp" "$DIR/sat_hooked.rs" && { rm -f "${OUT}.tmp"; echo "sat_hooked.rs is current"; exit 0; }
  rm -f "${OUT}.tmp"; echo "sat_hooked.rs is stale" >&2; exit 1
fi
mv "${OUT}.tmp" "$OUT"
sha256sum "$OUT"
