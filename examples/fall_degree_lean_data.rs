//! Emit `research/fall_degree_bounds_20261008/lean/FallDegree/Data.lean`
//! from the E3, E4 and E6 run records, for the Lean scoring in
//! `FallDegree/Rule.lean` and `Verdict.lean`.
//!
//! Usage: `fall_degree_lean_data <study_dir> <out.lean>`
use serde_json::Value;
use std::collections::BTreeMap;

struct Row {
    kind: u32,
    m: u64,
    n: u64,
    ell: u64,
    shape: String,
    value: Option<u64>,
    cap: u64,
    dstar: Option<u64>,
    at_least: bool,
}

fn lines(path: &std::path::Path) -> Vec<Value> {
    std::fs::read_to_string(path)
        .unwrap_or_default()
        .lines()
        .filter(|l| l.trim_start().starts_with('{'))
        .map(|l| serde_json::from_str(l).unwrap())
        .collect()
}

fn files(dir: &std::path::Path, prefix: &str) -> Vec<std::path::PathBuf> {
    let mut v: Vec<_> = std::fs::read_dir(dir)
        .map(|r| r.filter_map(|e| e.ok().map(|e| e.path())).collect())
        .unwrap_or_default();
    v.retain(|p: &std::path::PathBuf| {
        let f = p.file_name().unwrap().to_string_lossy();
        f.starts_with(prefix) && f.ends_with(".jsonl")
    });
    v.sort();
    v
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let dir = std::path::Path::new(&args[1]);
    let mut rows = vec![];
    for f in files(&dir.join("e3"), "n") {
        for r in lines(&f) {
            rows.push(Row {
                kind: 0,
                m: 2,
                n: r["n"].as_u64().unwrap(),
                ell: r["nprime"].as_u64().unwrap(),
                shape: format!("n{}", r["n"]),
                value: r["d_last"].as_u64(),
                cap: 6,
                dstar: None,
                at_least: false,
            });
        }
    }
    let ladder = |r: &Value, rows: &mut Vec<Row>| {
        let cap = r["censored_above"]
            .as_u64()
            .or(r["d_f_at_least"].as_u64().map(|x| x - 1))
            .unwrap_or(6);
        let m = r["m"].as_u64().unwrap_or(3);
        let cell = r
            .get("cell")
            .and_then(|c| c.as_str().map(String::from))
            .unwrap_or_else(|| format!("n{}l{}m{}", r["n"], r["ell"], m));
        rows.push(Row {
            kind: 1,
            m,
            n: r["n"].as_u64().unwrap(),
            ell: r["ell"].as_u64().unwrap(),
            shape: cell,
            value: r["d_f"].as_u64(),
            cap,
            dstar: r.get("d_star").and_then(|d| d["degree"].as_u64()),
            at_least: r.get("d_star").is_some_and(|d| d["kind"] == "at_least"),
        });
    };
    for (sub, prefix) in [("e4", "m3_"), ("e4", "x_"), ("e6", "A_"), ("e6", "B_")] {
        for f in files(&dir.join(sub), prefix) {
            for r in lines(&f) {
                ladder(&r, &mut rows);
            }
        }
    }
    for f in files(&dir.join("e6"), "C_") {
        for r in lines(&f) {
            rows.push(Row {
                kind: 2,
                m: 3,
                n: r["n"].as_u64().unwrap(),
                ell: r["ell"].as_u64().unwrap(),
                shape: r["cell"].as_str().unwrap().to_string(),
                value: r["d_last"].as_u64(),
                cap: r["d_last_at_least"].as_u64().map_or(5, |x| x - 1),
                dstar: None,
                at_least: false,
            });
        }
    }
    // Part D′: a (shape, seed) re-run in a later file supersedes the earlier one
    let mut dp: BTreeMap<(String, u64), Value> = BTreeMap::new();
    for f in files(&dir.join("e6"), "Dp_") {
        for r in lines(&f) {
            dp.insert(
                (
                    r["shape"].as_str().unwrap().to_string(),
                    r["seed"].as_u64().unwrap(),
                ),
                r,
            );
        }
    }
    {
        for r in dp.into_values() {
            rows.push(Row {
                kind: 3,
                m: 0,
                n: r["n_vars"].as_u64().unwrap(),
                ell: 0,
                shape: r["shape"].as_str().unwrap().to_string(),
                value: r["d_last"].as_u64(),
                cap: r["d_last_at_least"].as_u64().map_or(6, |x| x - 1),
                dstar: None,
                at_least: false,
            });
        }
    }
    let mut ids: BTreeMap<(u32, String), usize> = BTreeMap::new();
    let mut s = String::from("import FallDegree.Rule\n\n/-! Generated by `examples/fall_degree_lean_data.rs` from the E3, E4 and E6\nrecords. Do not edit: regenerate. -/\n\nnamespace FallDegree\n\ndef rows : List Row := [\n");
    let total = rows.len();
    for (i, r) in rows.iter().enumerate() {
        let next = ids.len();
        let shape = *ids.entry((r.kind, r.shape.clone())).or_insert(next);
        let shape = if r.kind == 0 { r.n as usize } else { shape };
        s.push_str(&format!(
            "  {{ kind := {}, m := {}, n := {}, ell := {}, shape := {}, value := {}, cap := {}, dstar := {}, dstarAtLeast := {} }}{}  -- {}\n",
            r.kind,
            r.m,
            r.n,
            r.ell,
            shape,
            r.value.map_or("none".into(), |v| format!("some {v}")),
            r.cap,
            r.dstar.map_or("none".into(), |v| format!("some {v}")),
            r.at_least,
            if i + 1 < total { "," } else { "" },
            r.shape
        ));
    }
    s.push_str("]\n\nend FallDegree\n");
    std::fs::write(&args[2], s).unwrap();
}
