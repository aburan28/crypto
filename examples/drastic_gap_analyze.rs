//! Paired analysis for the drastic prime conductor-gap study
//! (research/drastic_prime_conductor_gap_20261012). Reads sealed ecbench
//! records; never launches a solver or prices wall time. Same statistical
//! core as the prior round (examples/conductor_gap_analyze.rs): 20 000
//! independent-workload bootstrap resamples and label permutations. The
//! ic-mitm arm is optional per pair: a pair without complete IC records is
//! reported with the arm marked inadmissible, never dropped.
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::Path;

use crypto_lib::cryptanalysis::ecbench::canonical::sha256_hex;
use crypto_lib::cryptanalysis::ecbench::runner::read_records;
use crypto_lib::cryptanalysis::ecbench::stats::{mean, quantile, Resampler};
use serde_json::{json, Value};

const SAMPLES: usize = 20_000;
const SEED: u64 = 20261012;

fn cross_curve(a: &[f64], b: &[f64]) -> Value {
    let ratio = mean(b).unwrap() / mean(a).unwrap();
    let mut rng = Resampler::new(SEED);
    let mut boot = Vec::with_capacity(SAMPLES);
    for _ in 0..SAMPLES {
        let sa: f64 = (0..a.len()).map(|_| a[rng.below(a.len())]).sum();
        let sb: f64 = (0..b.len()).map(|_| b[rng.below(b.len())]).sum();
        boot.push((sb / b.len() as f64) / (sa / a.len() as f64));
    }
    let mut pool = a.iter().chain(b.iter()).copied().collect::<Vec<_>>();
    let observed = ratio.ln().abs();
    let mut extreme = 0;
    for _ in 0..SAMPLES {
        for i in (1..pool.len()).rev() {
            let j = rng.below(i + 1);
            pool.swap(i, j);
        }
        let ra = mean(&pool[..a.len()]).unwrap();
        let rb = mean(&pool[a.len()..]).unwrap();
        if (rb / ra).ln().abs() + 1e-12 >= observed {
            extreme += 1;
        }
    }
    json!({
        "ratio_floor_over_crater": ratio,
        "ci95": [quantile(&boot, 0.025), quantile(&boot, 0.975)],
        "ci99": [quantile(&boot, 0.005), quantile(&boot, 0.995)],
        "permutation_p_two_sided": (extreme + 1) as f64 / (SAMPLES + 1) as f64,
        "resamples": SAMPLES, "seed": SEED,
        "method": "independent workload bootstrap on each fixed curve; label permutation",
        "cross_curve_targets_transported": false,
    })
}

fn arg(args: &[String], name: &str) -> String {
    let i = args
        .iter()
        .position(|s| s == name)
        .expect("required argument");
    args.get(i + 1).expect("argument value").clone()
}

fn identities(spec: &Value) -> Vec<Value> {
    spec["workloads"]["curves"]
        .as_array()
        .unwrap()
        .iter()
        .enumerate()
        .map(|(i, c)| {
            let field = json!({"characteristic":c["p"],"degree":1,
            "representation":"prime-residue","element_encoding":"lowercase hex with 0x prefix"});
            let curve = json!({"model":"short-weierstrass",
            "coefficients":{"a":format!("0x{:x}",c["a"].as_u64().unwrap()),"b":format!("0x{:x}",c["b"].as_u64().unwrap())},
            "group_order":c["group_order"].as_u64().unwrap().to_string(),
            "subgroup_order":c["r"].as_u64().unwrap().to_string(),"cofactor":"1",
            "generator":[format!("0x{:x}",c["gx"].as_u64().unwrap()),format!("0x{:x}",c["gy"].as_u64().unwrap())],
            "target_group":"prime-order cyclic subgroup generated by the recorded generator"});
            let preimage = json!({"field":field,"curve":curve});
            let hash = sha256_hex(&serde_json::to_vec(&preimage).unwrap());
            let tag = if i == 0 { "cmcrater" } else { "cmfloor" };
            let bits = 64 - c["p"].as_u64().unwrap().leading_zeros();
            json!({"field":preimage["field"],"curve":preimage["curve"],
            "curve_id":format!("EC1P{bits}C{tag}h{}",&hash[..12]),
            "curve_uid":format!("urn:ec-record:1:sha256:{hash}"),"curve_sha256":hash,
            "field_sha256":sha256_hex(&serde_json::to_vec(&preimage["field"]).unwrap()),
            "role":if i==0 {"crater"} else {"floor"},
            "status":"metadata identity of the exact frozen representation; not an additional mathematical certificate"})
        })
        .collect()
}

fn analyze(dir: &Path, cell: &str) -> Result<Value, String> {
    let spec: Value =
        serde_json::from_slice(&std::fs::read(dir.join("spec.json")).map_err(|e| e.to_string())?)
            .map_err(|e| e.to_string())?;
    let curves = spec["workloads"]["curves"].as_array().ok_or("curves")?;
    if curves.len() != 2 {
        return Err("the protocol requires exactly two fixed curves".into());
    }
    let records = read_records(dir)?;
    let measured = records.iter().filter(|r| !r.warmup).collect::<Vec<_>>();
    let failed = measured
        .iter()
        .filter(|r| r.outcome.status != "verified")
        .map(|r| json!({"run_id":r.run_id,"arm":r.arm,"status":r.outcome.status,"error":r.outcome.error}))
        .collect::<Vec<_>>();
    // arms present in this session
    let mut present: BTreeSet<String> = BTreeSet::new();
    for r in &records {
        present.insert(r.arm.clone());
    }
    let mut arms = BTreeMap::<String, Value>::new();
    let mut aa_pairs = 0;
    let mut aa_mismatch = Vec::new();
    let mut table = Vec::new();
    for arm in ["rho-neg", "rho-neg-aa", "ic-mitm"] {
        if !present.contains(arm) {
            arms.insert(
                arm.to_string(),
                json!({"status":"not run in this session (optional arm for this pair)"}),
            );
            continue;
        }
        let mut role_rows = Vec::new();
        let mut samples = Vec::<Vec<f64>>::new();
        for (ci, role) in ["crater", "floor"].iter().enumerate() {
            let selected = measured
                .iter()
                .filter(|r| {
                    r.arm == arm
                        && serde_json::to_value(&r.workload.curve_spec).unwrap() == curves[ci]
                })
                .copied()
                .collect::<Vec<_>>();
            let mut workloads = BTreeMap::<String, Vec<f64>>::new();
            let mut statuses = BTreeMap::<String, usize>::new();
            let mut phases = BTreeMap::<String, f64>::new();
            let mut unpriced = BTreeSet::new();
            let mut bounded = false;
            let mut ids = Vec::new();
            let mut levels = BTreeMap::<String, usize>::new();
            for r in &selected {
                *statuses.entry(r.outcome.status.clone()).or_default() += 1;
                *levels
                    .entry(r.isolation.level.name().to_string())
                    .or_default() += 1;
                ids.push(r.run_id.clone());
                bounded |= r.cost.lower_bound;
                unpriced.extend(r.cost.unpriced.clone());
                if r.outcome.status == "verified" {
                    let s = r.cost.s.ok_or("verified run has no S")?;
                    if !s.is_finite() || s <= 0.0 {
                        return Err("invalid S".into());
                    }
                    workloads
                        .entry(r.workload.workload_id.clone())
                        .or_default()
                        .push(s);
                    for p in &r.phases {
                        *phases.entry(p.name.clone()).or_default() += p.gae;
                    }
                }
                if arm == "rho-neg" {
                    let controls = selected_control(&measured, r);
                    aa_pairs += 1;
                    if controls.len() != 1
                        || controls[0].cost != r.cost
                        || controls[0].counters != r.counters
                        || controls[0].outcome.recovered != r.outcome.recovered
                    {
                        aa_mismatch.push(r.run_id.clone());
                    }
                }
            }
            let valid = selected.iter().all(|r| r.outcome.status == "verified")
                && selected.len() == 8
                && workloads.len() == 8;
            let values = workloads
                .values()
                .map(|v| mean(v).unwrap())
                .collect::<Vec<f64>>();
            samples.push(values.clone());
            let mean_s = valid.then(|| mean(&values)).flatten();
            let n = selected.len() as f64;
            let phase_means = phases
                .into_iter()
                .map(|(k, v)| (k, v / n.max(1.0)))
                .collect::<BTreeMap<_, _>>();
            let slug = selected.first().map(|r| r.workload.curve.slug.clone());
            let row = json!({
                "role": role, "slug": slug, "measured": selected.len(),
                "workloads": workloads.len(), "statuses": statuses, "valid": valid,
                "mean_s": mean_s,
                "min_s": values.iter().copied().reduce(f64::min),
                "max_s": values.iter().copied().reduce(f64::max),
                "lower_bound": bounded, "unpriced": unpriced, "isolation_levels": levels,
                "phase_mean_gae": phase_means, "run_ids": ids,
                "factor_base": selected.first().and_then(|r| r.factor_base.clone()),
                "floor_s": selected.first().map(|r| r.boundaries.floor_s),
            });
            table.push(json!({"arm": arm, "row": row.clone()}));
            role_rows.push(row);
        }
        let admissible = role_rows.iter().all(|r| r["valid"] == true);
        arms.insert(
            arm.to_string(),
            json!({"curves": role_rows,
            "cross_curve": if admissible { cross_curve(&samples[0], &samples[1]) } else { json!({"status":"inadmissible: measured failures or missing workloads"}) }}),
        );
    }
    let slugs = table
        .iter()
        .filter_map(|r| r["row"]["slug"].as_str())
        .collect::<BTreeSet<_>>();
    if slugs.len() != 2 {
        return Err("curve roles did not resolve uniquely".into());
    }
    let mut by_curve = BTreeMap::new();
    for role in ["crater", "floor"] {
        let rho = arms["rho-neg"]["curves"]
            .as_array()
            .unwrap()
            .iter()
            .find(|r| r["role"] == role)
            .unwrap();
        let ic = arms["ic-mitm"]["curves"].as_array();
        let ic_mean = ic.and_then(|c| {
            c.iter()
                .find(|r| r["role"] == role)
                .and_then(|r| r["mean_s"].as_f64())
        });
        by_curve.insert(
            role,
            json!({
                "ic_over_rho_count_diagnostic": ic_mean.zip(rho["mean_s"].as_f64()).map(|(i, r)| i / r),
                "ic_arm_present": ic.is_some(),
                "rho_mean_s": rho["mean_s"],
            }),
        );
    }
    let source = std::fs::read(dir.join("records.jsonl")).map_err(|e| e.to_string())?;
    Ok(
        json!({"cell":cell,"session":dir,"session_id":records.first().map(|r|&r.session_id),
    "curve_manifests":identities(&spec),
    "records":records.len(),"measured":measured.len(),"failed":failed,
    "records_sha256":sha256_hex(&source),"arms":arms,"ic_vs_rho":by_curve,
    "aa":{"pairs":aa_pairs,"mismatches":aa_mismatch},
    "status":"observations on two fixed curves; no population hardness or speedup claim"}),
    )
}

fn selected_control<'a>(
    measured: &[&'a crypto_lib::cryptanalysis::ecbench::record::Record],
    r: &'a crypto_lib::cryptanalysis::ecbench::record::Record,
) -> Vec<&'a crypto_lib::cryptanalysis::ecbench::record::Record> {
    measured
        .iter()
        .filter(|x| {
            x.arm == "rho-neg-aa"
                && x.workload.workload_id == r.workload.workload_id
                && x.round == r.round
        })
        .copied()
        .collect()
}

fn main() -> Result<(), String> {
    let args: Vec<String> = std::env::args().collect();
    let root = arg(&args, "--sessions");
    let out = arg(&args, "--out");
    let cells = [
        ("d19-ell508433", 19u64, 508433u64),
        ("d43-ell508433", 43, 508433),
        ("d19-ell1016839", 19, 1016839),
        ("d43-ell1016839", 43, 1016839),
        ("d19-ell2033609", 19, 2033609),
        ("d43-ell2033609", 43, 2033609),
    ];
    let mut sessions = Vec::new();
    for (cell, d, ell) in cells {
        sessions
            .push(analyze(&Path::new(&root).join(cell), cell).map_err(|e| format!("{cell}: {e}"))?);
        let _ = (d, ell);
    }
    let mut markdown = String::from(
        "# Drastic prime conductor-gap paired counts\n\n\
Independent target samples on each fixed curve. Ratios of lower bounds are diagnostics; no wall-time or intrinsic-hardness claim. `S = counted group-addition equivalents / sqrt(r)`.\n\n\
| cell | arm | floor/crater | 95% interval | 99% interval | permutation p | IC present |\n|---|---|---:|---|---|---:|---|\n",
    );
    for s in &sessions {
        for arm in ["rho-neg", "ic-mitm"] {
            let a = &s["arms"][arm];
            if a.get("curves").is_none() {
                continue;
            }
            let cc = &a["cross_curve"];
            if cc.get("ratio_floor_over_crater").is_none() {
                continue;
            }
            let _ = writeln!(
                markdown,
                "| {} | {} | {:.6} | {:.6} to {:.6} | {:.6} to {:.6} | {:.6} | {} |",
                s["cell"].as_str().unwrap_or_default(),
                arm,
                cc["ratio_floor_over_crater"].as_f64().unwrap(),
                cc["ci95"][0].as_f64().unwrap(),
                cc["ci95"][1].as_f64().unwrap(),
                cc["ci99"][0].as_f64().unwrap(),
                cc["ci99"][1].as_f64().unwrap(),
                cc["permutation_p_two_sided"].as_f64().unwrap(),
                s["ic_vs_rho"]["crater"]["ic_arm_present"]
                    .as_bool()
                    .unwrap(),
            );
        }
        let _ = writeln!(
            markdown,
            "| {} | aa-control | pairs {} mismatches {} | | | | | |",
            s["cell"].as_str().unwrap_or_default(),
            s["aa"]["pairs"],
            s["aa"]["mismatches"]
                .as_array()
                .map(|m| m.len())
                .unwrap_or(0),
        );
    }
    std::fs::create_dir_all(&out).unwrap();
    std::fs::write(
        Path::new(&out).join("analysis.json"),
        serde_json::to_vec_pretty(&json!({"schema":"drastic-prime-conductor-gap-analysis/v1",
            "seed":SEED,"resamples":SAMPLES,"sessions":sessions,
            "status":"count diagnostics on fixed pairs; repeated-lead rule as frozen in PROTOCOL.md"})).unwrap(),
    )
    .unwrap();
    std::fs::write(Path::new(&out).join("analysis.md"), markdown).unwrap();
    println!("wrote {}/analysis.json and analysis.md", out);
    Ok(())
}
