//! `isogeny-algos`: the crate's operations for prime-field curves, one JSON object per run.
//! See `docs/USAGE.md` for the commands, the record layout and the exit codes.
use isogeny_algos::api::{
    self, Check, CountMethod, IsogenyRecord, OrderCertificate, PrimeCurve, Status,
};
use isogeny_algos::bigint::Big;
use isogeny_algos::icv1;
use isogeny_algos::int::Int;
use isogeny_algos::json::Json;
use std::collections::HashMap;
use std::time::Instant;

const SCHEMA: &str = "isogeny-algos/v1";

const HELP: &str = "isogeny-algos <command> [options]; one JSON object on stdout

curve (count, isogenies, velu, chain, dual):
  --curve NAME            p192 | p224 | p256 | secp256k1
  --p P --a A --b B       y^2 = x^3 + a x + b over GF(p), decimal (a, b may be negative)

commands:
  count     [--order N]                  #E(F_p), trace, twist order, certificates, ICV1 identities
                                         (--order: certify a known order instead of counting)
  isogenies --ell L [--order N]          the F_p-rational l-isogenies (l prime): kernel polynomial,
                                         codomain, x-map, checks; --order adds ICV1 slugs
  isogenies --ell L --method M           ... with one BMSS variant for the kernel (odd l, j not 0, 1728):
                                         linear_algebra stark1972 atkin1992 atkin_modcomp elkies1992
                                         elkies1998 fast_elkies fast_elkies_prime
  velu      --ell L --kernel C0,C1,...,1 the isogeny with this monic kernel polynomial (low to high)
  velu      --ell L --kernel-x X         ... or with the kernel generated by a point with x(P) = X
  velu      --ell L --kernel-x X --method kohel|velu|xonly|sqrtvelu
                                         the codomain by one formula, checked against Kohel's
  chain     --ell L --n N [--kernel X,Y] [--order N] [--strategy naive|balanced|optimal]
                                         the l^n-isogeny with kernel <P> as n l-isogenies; without
                                         --kernel, P is found from #E (counted when --order is absent)
  dual      --ell L                      each rational l-isogeny and its dual from Phi_l
  csidh     --exps E1,E2,... [--primes L1,L2,... | --preset csidh512] [--a A]
                                         the CSIDH action on y^2 = x^3 + A x^2 + x, p = 4 prod(l_i) - 1
  path      --p P --j1 J1 --j2 J2 [--ells 2,3,5] [--method galbraith|ghs|gs] [--max-steps N]
                                         a path of l-isogenies between ordinary j-invariants
  klpt      --p P --norm N [--ell 2]     a random left O_0-ideal of norm N and its KLPT equivalent of
                                         l-power norm (p = 3 mod 4)
  richelot  --p P --roots R1,...,R6 [--lc C]
                                         the 15 Richelot (2,2)-isogenies of J(y^2 = C prod (x - Ri))
  modpoly   --ell L --p P [--j J]        Phi_l mod p (or Phi_l(X, J) and its roots in F_p)
  modpoly   --ell L --integer            Phi_l over Z
  modpoly   --method cm --ell L --modulus M  Phi_l modulo any positive integer
  modpoly   --method cm --ell L --p P [--j J]  CM/explicit CRT, prime-field output
  modpoly   --method cm --ell L --integer     signed integer coefficients via CM
  version                                the tool name and version (JSON)
  help

common: --seed S (default 1): the random choices; results do not depend on it.
exit: 0 every check PASS; 3 a check INDETERMINATE, none FAIL; 1 a check FAIL; 2 usage error";

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    if matches!(
        args.first().map(String::as_str),
        Some("version" | "--version" | "-V")
    ) {
        println!(
            "{}",
            Json::obj(vec![("schema", Json::str(SCHEMA)), ("tool", tool_json())]).dump()
        );
        return;
    }
    let t0 = Instant::now();
    let code = match run(&args) {
        Ok(mut record) => {
            let status = overall(&record);
            if let Json::Obj(kv) = &mut record {
                kv.push(("status".into(), Json::str(status.as_str())));
                kv.push((
                    "elapsed_ms".into(),
                    Json::Num(t0.elapsed().as_millis() as i64),
                ));
            }
            println!("{}", record.dump());
            match status {
                Status::Pass => 0,
                Status::Indeterminate | Status::NotRun => 3,
                Status::Fail => 1,
            }
        }
        Err(Usage(msg)) => {
            if msg == "help" {
                println!("{HELP}");
                0
            } else {
                let err = Json::obj(vec![
                    ("schema", Json::str(SCHEMA)),
                    ("error", Json::str(&msg)),
                    ("status", Json::str("USAGE")),
                ]);
                println!("{}", err.dump());
                eprintln!("{msg}\n\n{HELP}");
                2
            }
        }
    };
    std::process::exit(code);
}

struct Usage(String);
impl From<String> for Usage {
    fn from(s: String) -> Self {
        Usage(s)
    }
}
impl From<&str> for Usage {
    fn from(s: &str) -> Self {
        Usage(s.into())
    }
}

struct Opts(HashMap<String, String>);
impl Opts {
    fn parse(args: &[String]) -> Result<Opts, Usage> {
        let mut m = HashMap::new();
        let mut i = 0;
        while i < args.len() {
            let k = args[i]
                .strip_prefix("--")
                .ok_or_else(|| format!("unexpected argument {}", args[i]))?;
            if k == "integer" {
                m.insert(k.to_string(), String::new());
                i += 1;
                continue;
            }
            let v = args
                .get(i + 1)
                .ok_or_else(|| format!("--{k} needs a value"))?;
            m.insert(k.to_string(), v.clone());
            i += 2;
        }
        Ok(Opts(m))
    }
    fn get(&self, k: &str) -> Option<&str> {
        self.0.get(k).map(|s| s.as_str())
    }
    fn int(&self, k: &str) -> Result<Option<Int>, Usage> {
        self.get(k)
            .map(|s| parse_int(s).ok_or_else(|| Usage(format!("--{k}: not an integer: {s}"))))
            .transpose()
    }
    fn need_int(&self, k: &str) -> Result<Int, Usage> {
        self.int(k)?
            .ok_or_else(|| Usage(format!("--{k} is required")))
    }
    fn u64(&self, k: &str, default: Option<u64>) -> Result<u64, Usage> {
        match self.get(k) {
            Some(s) => s
                .parse()
                .map_err(|_| Usage(format!("--{k}: not a small integer: {s}"))),
            None => default.ok_or_else(|| Usage(format!("--{k} is required"))),
        }
    }
    fn curve(&self) -> Result<(PrimeCurve, Option<String>), Usage> {
        if let Some(name) = self.get("curve") {
            let c = PrimeCurve::preset(name)
                .ok_or_else(|| format!("unknown --curve {name} (p192, p224, p256, secp256k1)"))?;
            return Ok((c, Some(name.to_ascii_lowercase())));
        }
        let c = PrimeCurve::new(
            self.need_int("p")?,
            self.need_int("a")?,
            self.need_int("b")?,
        )?;
        Ok((c, None))
    }
}

fn parse_int(s: &str) -> Option<Int> {
    let (neg, digits) = match s.strip_prefix('-') {
        Some(d) => (true, d),
        None => (false, s),
    };
    if digits.is_empty() || !digits.bytes().all(|b| b.is_ascii_digit()) {
        return None;
    }
    let v = Int::from_big(&Big::from_dec(digits));
    Some(if neg { -v } else { v })
}

fn s(v: &Int) -> Json {
    Json::str(v)
}
fn ints(v: &[Int]) -> Json {
    Json::Arr(v.iter().map(s).collect())
}

fn checks_json(prefix: &str, cs: &[Check]) -> Vec<Json> {
    cs.iter()
        .map(|c| {
            Json::obj(vec![
                ("name", Json::str(format!("{prefix}{}", c.name))),
                ("status", Json::str(c.status.as_str())),
                ("detail", Json::str(&c.detail)),
            ])
        })
        .collect()
}

fn overall(record: &Json) -> Status {
    let mut st = Status::Pass;
    if let Json::Obj(kv) = record {
        if let Some((_, Json::Arr(cs))) = kv.iter().find(|(k, _)| k == "checks") {
            for c in cs {
                if let Json::Obj(f) = c {
                    match f.iter().find(|(k, _)| k == "status").map(|(_, v)| v) {
                        Some(Json::Str(x)) if x == "FAIL" => return Status::Fail,
                        Some(Json::Str(x)) if x != "PASS" => st = Status::Indeterminate,
                        _ => {}
                    }
                }
            }
        }
    }
    st
}

fn curve_json(c: &PrimeCurve, preset: Option<&str>) -> Json {
    Json::obj(vec![
        ("field", Json::str(format!("fp-{}", c.p))),
        ("form", Json::str("y^2=x^3+a*x+b")),
        ("p", s(&c.p)),
        ("a", s(&c.a)),
        ("b", s(&c.b)),
        ("j", s(&c.j())),
        ("preset", preset.map_or(Json::Null, Json::str)),
    ])
}

fn icv1_json(c: &PrimeCurve, order: &Int) -> Json {
    match icv1::prime(&c.p, &c.a, &c.b, order) {
        Some(id) => Json::obj(vec![
            ("icv1", Json::str(id.icv1)),
            ("slug", Json::str(id.slug)),
            ("model_json", Json::str(id.model_json)),
        ]),
        None => Json::Null,
    }
}

fn tool_json() -> Json {
    Json::obj(vec![
        ("name", Json::str("isogeny-algos")),
        ("version", Json::str(env!("CARGO_PKG_VERSION"))),
    ])
}

fn record(
    command: &str,
    c: &PrimeCurve,
    preset: Option<&str>,
    result: Json,
    checks: Vec<Json>,
) -> Json {
    Json::obj(vec![
        ("schema", Json::str(SCHEMA)),
        ("command", Json::str(command)),
        ("tool", tool_json()),
        ("curve", curve_json(c, preset)),
        ("result", result),
        ("checks", Json::Arr(checks)),
    ])
}

fn cert_json(cert: &OrderCertificate) -> Json {
    Json::obj(vec![
        ("certified", Json::Bool(cert.certified)),
        (
            "certified_by",
            if !cert.certified {
                Json::Null
            } else if cert.via_twist {
                Json::str("twist_order")
            } else {
                Json::str("point_orders")
            },
        ),
        ("point_order_divisor", s(&cert.divisor)),
        (
            "order_factors",
            Json::Arr(
                cert.factors
                    .iter()
                    .map(|(q, e)| Json::Arr(vec![s(q), Json::Num(*e as i64)]))
                    .collect(),
            ),
        ),
        ("order_unfactored", s(&cert.unfactored)),
        (
            "points",
            Json::Arr(
                cert.points
                    .iter()
                    .map(|(x, y)| Json::Arr(vec![s(x), s(y)]))
                    .collect(),
            ),
        ),
    ])
}

fn run(args: &[String]) -> Result<Json, Usage> {
    let Some(cmd) = args.first() else {
        return Err("help".into());
    };
    let o = Opts::parse(&args[1..])?;
    let seed = o.u64("seed", Some(1))?;
    match cmd.as_str() {
        "help" | "--help" | "-h" => Err("help".into()),
        "count" => {
            let (c, preset) = o.curve()?;
            let pc = match o.int("order")? {
                Some(n) => api::check_order(&c, &n, seed),
                None => api::count_points(&c, seed)?,
            };
            let method = match &pc.method {
                CountMethod::Bsgs => Json::obj(vec![("name", Json::str("bsgs"))]),
                CountMethod::Cm => Json::obj(vec![("name", Json::str("cm"))]),
                CountMethod::Given => Json::obj(vec![("name", Json::str("given"))]),
                CountMethod::Sea {
                    elkies,
                    atkin,
                    candidates,
                } => Json::obj(vec![
                    ("name", Json::str("sea")),
                    (
                        "elkies",
                        Json::Arr(
                            elkies
                                .iter()
                                .map(|&(m, t)| Json::Arr(vec![Json::str(m), Json::str(t)]))
                                .collect(),
                        ),
                    ),
                    (
                        "atkin",
                        Json::Arr(
                            atkin
                                .iter()
                                .map(|&(l, r, n)| {
                                    Json::Arr(vec![
                                        Json::Num(l as i64),
                                        Json::Num(r as i64),
                                        Json::Num(n as i64),
                                    ])
                                })
                                .collect(),
                        ),
                    ),
                    ("candidates", Json::str(candidates)),
                ]),
            };
            let tw = c.twist();
            let result = Json::obj(vec![
                ("order", s(&pc.order)),
                ("trace", s(&pc.trace)),
                ("twist_order", s(&pc.twist_order)),
                ("method", method),
                ("certificate", cert_json(&pc.certificate)),
                (
                    "twist",
                    Json::obj(vec![
                        ("a", s(&tw.a)),
                        ("b", s(&tw.b)),
                        ("certificate", cert_json(&pc.twist_certificate)),
                    ]),
                ),
                ("icv1", icv1_json(&c, &pc.order)),
                ("twist_icv1", icv1_json(&tw, &pc.twist_order)),
            ]);
            let mut checks = checks_json("order.", &pc.certificate.checks);
            checks.extend(checks_json("twist.", &pc.twist_certificate.checks));
            Ok(record("count", &c, preset.as_deref(), result, checks))
        }
        "isogenies" => {
            let (c, preset) = o.curve()?;
            let ell = o.u64("ell", None)?;
            let order = o.int("order")?;
            let method = match o.get("method") {
                None => None,
                Some(m) => Some(
                    api::BmssMethod::ALL
                        .into_iter()
                        .find(|x| x.name() == m)
                        .ok_or_else(|| format!("unknown --method {m}"))?,
                ),
            };
            let isos = match method {
                Some(m) => api::isogenies_by(&c, ell, m, seed)?,
                None => api::isogenies(&c, ell, seed)?,
            };
            let mut checks = vec![];
            let mut source_id = Json::Null;
            if let Some(n) = &order {
                let cert = api::certify_order(&c, n, seed);
                checks.extend(checks_json("order.", &cert.checks));
                source_id = icv1_json(&c, n);
            }
            let items: Vec<Json> = isos
                .iter()
                .enumerate()
                .map(|(i, r)| {
                    checks.extend(checks_json(&format!("isogeny[{i}]."), &r.checks));
                    iso_json(&c, r, order.as_ref())
                })
                .collect();
            let result = Json::obj(vec![
                ("ell", Json::Num(ell as i64)),
                ("method", method.map_or(Json::Null, |m| Json::str(m.name()))),
                ("count", Json::Num(items.len() as i64)),
                ("source_icv1", source_id),
                ("isogenies", Json::Arr(items)),
            ]);
            Ok(record("isogenies", &c, preset.as_deref(), result, checks))
        }
        "velu" if o.get("method").is_some() => {
            let (c, preset) = o.curve()?;
            let ell = o.u64("ell", None)?;
            let m = o.get("method").unwrap();
            let method = api::VeluMethod::from_name(m)
                .ok_or_else(|| format!("unknown --method {m} (kohel, velu, xonly, sqrtvelu)"))?;
            let x = o.int("kernel-x")?.ok_or("velu --method needs --kernel-x")?;
            let r = api::isogeny_from_x(&c, &x, ell, method, seed)?;
            let checks = checks_json("isogeny.", &r.checks);
            Ok(record("velu", &c, preset.as_deref(), map_json(&r), checks))
        }
        "chain" => {
            let (c, preset) = o.curve()?;
            let ell = o.u64("ell", None)?;
            let n = o.u64("n", None)? as usize;
            let kernel = match o.get("kernel") {
                None => None,
                Some(k) => {
                    let v: Vec<Int> = k
                        .split(',')
                        .map(|t| parse_int(t.trim()))
                        .collect::<Option<_>>()
                        .ok_or("--kernel: expected X,Y")?;
                    if v.len() != 2 {
                        return Err("--kernel: expected X,Y".into());
                    }
                    Some((v[0].clone(), v[1].clone()))
                }
            };
            let st = o.get("strategy").unwrap_or("optimal");
            let strategy = api::ChainStrategy::from_name(st)
                .ok_or_else(|| format!("unknown --strategy {st} (naive, balanced, optimal)"))?;
            let r = api::ell_power_chain(&c, ell, n, kernel, o.int("order")?, strategy, seed)?;
            let result = Json::obj(vec![
                ("ell", Json::Num(r.ell as i64)),
                ("n", Json::Num(r.n as i64)),
                ("degree", s(&Int::from(r.ell).pow(r.n as u32))),
                ("strategy", Json::str(st)),
                (
                    "kernel_point",
                    Json::Arr(vec![s(&r.kernel_point.0), s(&r.kernel_point.1)]),
                ),
                (
                    "codomain",
                    Json::obj(vec![
                        ("a", s(&r.codomain.0)),
                        ("b", s(&r.codomain.1)),
                        ("j", s(&r.j_codomain)),
                    ]),
                ),
                ("j_path", ints(&r.path)),
                (
                    "operations",
                    Json::obj(vec![
                        ("l_mults", Json::Num(r.stats.0 as i64)),
                        ("evals", Json::Num(r.stats.1 as i64)),
                        ("builds", Json::Num(r.stats.2 as i64)),
                    ]),
                ),
            ]);
            let checks = checks_json("chain.", &r.checks);
            Ok(record("chain", &c, preset.as_deref(), result, checks))
        }
        "dual" => {
            let (c, preset) = o.curve()?;
            let ell = o.u64("ell", None)?;
            let ds = api::duals(&c, ell, seed)?;
            let mut checks = vec![];
            let items: Vec<Json> = ds
                .iter()
                .enumerate()
                .map(|(i, d)| {
                    checks.extend(checks_json(&format!("isogeny[{i}]."), &d.isogeny.checks));
                    checks.extend(checks_json(&format!("dual[{i}]."), &d.checks));
                    Json::obj(vec![
                        ("isogeny", iso_json(&c, &d.isogeny, None)),
                        (
                            "dual",
                            Json::obj(vec![
                                ("kernel", ints(&d.dual_kernel)),
                                (
                                    "x_map",
                                    Json::obj(vec![
                                        ("num", ints(&d.dual_map_num)),
                                        ("den", ints(&d.dual_map_den)),
                                    ]),
                                ),
                            ]),
                        ),
                    ])
                })
                .collect();
            let result = Json::obj(vec![
                ("ell", Json::Num(ell as i64)),
                ("count", Json::Num(items.len() as i64)),
                ("pairs", Json::Arr(items)),
            ]);
            Ok(record("dual", &c, preset.as_deref(), result, checks))
        }
        "csidh" => {
            let primes = match (o.get("preset"), o.get("primes")) {
                (Some("csidh512"), None) => api::csidh512_primes(),
                (None, Some(ps)) => ps
                    .split(',')
                    .map(|t| t.trim().parse::<u64>())
                    .collect::<Result<_, _>>()
                    .map_err(|_| "--primes: expected L1,L2,...")?,
                _ => return Err("csidh needs exactly one of --preset csidh512 or --primes".into()),
            };
            let exps: Vec<i32> = o
                .get("exps")
                .ok_or("--exps is required")?
                .split(',')
                .map(|t| t.trim().parse::<i32>())
                .collect::<Result<_, _>>()
                .map_err(|_| "--exps: expected E1,E2,...")?;
            let a = o.int("a")?.unwrap_or_else(Int::zero);
            let r = api::csidh_action(&primes, &a, &exps, seed)?;
            let result = Json::obj(vec![
                ("p", s(&r.p)),
                ("form", Json::str("y^2=x^3+A*x^2+x")),
                (
                    "primes",
                    Json::Arr(r.primes.iter().map(|&l| Json::Num(l as i64)).collect()),
                ),
                (
                    "exponents",
                    Json::Arr(exps.iter().map(|&e| Json::Num(e as i64)).collect()),
                ),
                ("a_in", s(&r.a_in)),
                ("a_out", s(&r.a_out)),
            ]);
            Ok(Json::obj(vec![
                ("schema", Json::str(SCHEMA)),
                ("command", Json::str("csidh")),
                ("tool", tool_json()),
                ("result", result),
                ("checks", Json::Arr(checks_json("csidh.", &r.checks))),
            ]))
        }
        "path" => {
            let p = o.need_int("p")?;
            let (j1, j2) = (o.need_int("j1")?, o.need_int("j2")?);
            let ells: Vec<usize> = o
                .get("ells")
                .unwrap_or("2,3,5")
                .split(',')
                .map(|t| t.trim().parse::<usize>())
                .collect::<Result<_, _>>()
                .map_err(|_| "--ells: expected L1,L2,...")?;
            let m = o.get("method").unwrap_or("galbraith");
            let method = api::PathMethod::from_name(m)
                .ok_or_else(|| format!("unknown --method {m} (galbraith, ghs, gs)"))?;
            let max = o.u64("max-steps", Some(1_000_000))? as usize;
            let r = api::isogeny_path(&p, &j1, &j2, &ells, method, max, seed)?;
            let result = Json::obj(vec![
                ("p", s(&p)),
                ("method", Json::str(r.method.name())),
                ("length", Json::Num(r.ells.len() as i64)),
                ("j_path", ints(&r.js)),
                (
                    "degrees",
                    Json::Arr(r.ells.iter().map(|&l| Json::Num(l as i64)).collect()),
                ),
                ("work", Json::Num(r.work as i64)),
            ]);
            Ok(Json::obj(vec![
                ("schema", Json::str(SCHEMA)),
                ("command", Json::str("path")),
                ("tool", tool_json()),
                ("result", result),
                ("checks", Json::Arr(checks_json("path.", &r.checks))),
            ]))
        }
        "klpt" => {
            let p = o.need_int("p")?;
            let n = o.need_int("norm")?;
            let ell = o.u64("ell", Some(2))?;
            let r = api::klpt_random(&p, &n, ell, seed)?;
            let q = |x: &api::QuatInts| {
                let mut v: Vec<Json> = x.0.iter().map(s).collect();
                v.push(s(&x.1));
                Json::Arr(v)
            };
            let result = Json::obj(vec![
                ("p", s(&r.p)),
                (
                    "basis",
                    Json::str("(c0 + c1 i + c2 j + c3 k) / d, i^2 = -1, j^2 = -p"),
                ),
                ("norm_in", s(&r.norm_in)),
                ("ideal_in", Json::Arr(r.ideal_in.iter().map(q).collect())),
                ("ell", Json::Num(ell as i64)),
                ("e", Json::Num(r.e as i64)),
                ("ideal_out", Json::Arr(r.ideal_out.iter().map(q).collect())),
                ("xi", q(&r.xi)),
                ("attempts", Json::Num(r.attempts as i64)),
            ]);
            Ok(Json::obj(vec![
                ("schema", Json::str(SCHEMA)),
                ("command", Json::str("klpt")),
                ("tool", tool_json()),
                ("result", result),
                ("checks", Json::Arr(checks_json("klpt.", &r.checks))),
            ]))
        }
        "richelot" => {
            let p = o.need_int("p")?;
            let roots: Vec<Int> = o
                .get("roots")
                .ok_or("--roots is required")?
                .split(',')
                .map(|t| parse_int(t.trim()))
                .collect::<Option<_>>()
                .ok_or("--roots: expected six integers")?;
            let lc = o.int("lc")?.unwrap_or_else(Int::one);
            let rs = api::richelot_isogenies(&p, &roots, &lc, seed)?;
            let mut checks = vec![];
            let items: Vec<Json> = rs
                .iter()
                .enumerate()
                .map(|(i, r)| {
                    checks.extend(checks_json(&format!("richelot[{i}]."), &r.checks));
                    let pair = |(a, b): (usize, usize)| {
                        Json::Arr(vec![Json::Num(a as i64), Json::Num(b as i64)])
                    };
                    let (kind, cod) = match (&r.jacobian, &r.product) {
                        (Some(f), _) => ("jacobian", Json::obj(vec![("sextic", ints(f))])),
                        (None, Some((e1, e2))) => (
                            "product",
                            Json::obj(vec![("cubic1", ints(e1)), ("cubic2", ints(e2))]),
                        ),
                        _ => ("product_not_rational", Json::Null),
                    };
                    Json::obj(vec![
                        (
                            "matching",
                            Json::Arr(r.matching.iter().map(|&m| pair(m)).collect()),
                        ),
                        ("kind", Json::str(kind)),
                        ("codomain", cod),
                    ])
                })
                .collect();
            let result = Json::obj(vec![
                ("p", s(&p)),
                ("form", Json::str("y^2=lc*prod(x-r_i)")),
                ("roots", ints(&roots)),
                ("lc", s(&lc)),
                ("isogenies", Json::Arr(items)),
            ]);
            Ok(Json::obj(vec![
                ("schema", Json::str(SCHEMA)),
                ("command", Json::str("richelot")),
                ("tool", tool_json()),
                ("result", result),
                ("checks", Json::Arr(checks)),
            ]))
        }
        "velu" => {
            let (c, preset) = o.curve()?;
            let ell = o.u64("ell", None)?;
            let kernel = match (o.get("kernel"), o.int("kernel-x")?) {
                (Some(k), None) => k
                    .split(',')
                    .map(|t| {
                        parse_int(t.trim())
                            .ok_or_else(|| Usage(format!("--kernel: bad coefficient {t}")))
                    })
                    .collect::<Result<Vec<Int>, Usage>>()?,
                (None, Some(x)) => api::kernel_from_x(&c, &x, ell)
                    .ok_or("--kernel-x is not the x-coordinate of a point of order l (odd l)")?,
                _ => return Err("velu needs exactly one of --kernel or --kernel-x".into()),
            };
            let r = api::isogeny_from_kernel(&c, &kernel, ell, seed)?;
            let checks = checks_json("isogeny.", &r.checks);
            Ok(record(
                "velu",
                &c,
                preset.as_deref(),
                iso_json(&c, &r, None),
                checks,
            ))
        }
        "modpoly" => {
            let ell = o.u64("ell", None)? as usize;
            if !isogeny_algos::field::is_prime(ell as u64) {
                return Err(format!("--ell {ell} is not prime").into());
            }
            let method = o.get("method").unwrap_or("hecke");
            if method == "cm" {
                let integer = o.get("integer").is_some();
                if [integer, o.get("p").is_some(), o.get("modulus").is_some()]
                    .into_iter()
                    .filter(|&x| x)
                    .count()
                    != 1
                {
                    return Err("CM needs exactly one of --integer, --p, or --modulus".into());
                }
                let j = o.int("j")?;
                if j.is_some() && o.get("p").is_none() {
                    return Err("--j requires --p for prime-field root extraction".into());
                }
                let result = if integer {
                    let c = api::modular_polynomial_integer_cm(ell, seed)?;
                    Json::obj(vec![
                        ("ell", Json::Num(ell as i64)),
                        ("ring", Json::str("Z")),
                        ("coefficients", sparse(&c)),
                    ])
                } else {
                    let key = if o.get("p").is_some() { "p" } else { "modulus" };
                    let m = o.need_int(key)?;
                    if key == "p" && !m.is_probable_prime() {
                        return Err("--p must be prime".into());
                    }
                    if let Some(j) = j {
                        let (g, roots) = api::modular_polynomial_cm_at(&m, ell, &j, seed)?;
                        Json::obj(vec![
                            ("ell", Json::Num(ell as i64)),
                            ("p", s(&m)),
                            ("j", s(&j)),
                            ("phi_at_j", ints(&g)),
                            ("roots", ints(&roots)),
                        ])
                    } else {
                        let c = api::modular_polynomial_cm(&m, ell, seed)?;
                        Json::obj(vec![
                            ("ell", Json::Num(ell as i64)),
                            (key, s(&m)),
                            ("coefficients", sparse(&c)),
                        ])
                    }
                };
                let check = Check { name:"method".into(), status:Status::Pass,
                    detail:"CM class-group volcano walks; certified seed traces and torsion; interpolation checks; bounded explicit CRT".into() };
                return Ok(Json::obj(vec![
                    ("schema", Json::str(SCHEMA)),
                    ("command", Json::str("modpoly")),
                    ("tool", tool_json()),
                    ("method", Json::str("cm")),
                    ("result", result),
                    ("checks", Json::Arr(checks_json("", &[check]))),
                ]));
            }
            if method != "hecke" {
                return Err("--method must be hecke or cm".into());
            }
            if o.get("modulus").is_some() {
                return Err("--modulus requires --method cm".into());
            }
            if o.get("integer").is_some() {
                let (cm, check) = api::modular_polynomial_integer(ell);
                let result = Json::obj(vec![
                    ("ell", Json::Num(ell as i64)),
                    ("ring", Json::str("Z")),
                    ("coefficients", sparse(&cm)),
                ]);
                return Ok(Json::obj(vec![
                    ("schema", Json::str(SCHEMA)),
                    ("command", Json::str("modpoly")),
                    ("tool", tool_json()),
                    ("result", result),
                    ("checks", Json::Arr(checks_json("", &[check]))),
                ]));
            }
            let p = o.need_int("p")?;
            if !p.is_probable_prime() {
                return Err("--p must be prime".into());
            }
            let result = match o.int("j")? {
                Some(j) => {
                    let (g, roots) = api::modular_polynomial_at(&p, ell, &j, seed)?;
                    Json::obj(vec![
                        ("ell", Json::Num(ell as i64)),
                        ("p", s(&p)),
                        ("j", s(&j)),
                        ("phi_at_j", ints(&g)),
                        ("roots", ints(&roots)),
                    ])
                }
                None => {
                    let cm = api::modular_polynomial(&p, ell)?;
                    Json::obj(vec![
                        ("ell", Json::Num(ell as i64)),
                        ("p", s(&p)),
                        ("coefficients", sparse(&cm)),
                    ])
                }
            };
            let check = Check {
                name: "method".into(),
                status: Status::Pass,
                detail: "Hecke/Newton q-expansions; equal to the linear-algebra and CRT Phi_l in the crate's tests".into(),
            };
            Ok(Json::obj(vec![
                ("schema", Json::str(SCHEMA)),
                ("command", Json::str("modpoly")),
                ("tool", tool_json()),
                ("result", result),
                ("checks", Json::Arr(checks_json("", &[check]))),
            ]))
        }
        other => Err(format!("unknown command {other}").into()),
    }
}

/// Nonzero coefficients as [i, j, c] (X^i Y^j); Phi_l is symmetric, so i <= j only.
fn sparse(c: &[Vec<Int>]) -> Json {
    let mut out = vec![];
    for (i, row) in c.iter().enumerate() {
        for (j, v) in row.iter().enumerate() {
            if j >= i && !v.is_zero() {
                out.push(Json::Arr(vec![
                    Json::Num(i as i64),
                    Json::Num(j as i64),
                    s(v),
                ]));
            }
        }
    }
    Json::Arr(out)
}

fn map_json(r: &api::MapRecord) -> Json {
    Json::obj(vec![
        ("method", Json::str(&r.method)),
        ("degree", s(&r.degree)),
        (
            "codomain",
            Json::obj(vec![
                ("a", s(&r.codomain.0)),
                ("b", s(&r.codomain.1)),
                ("j", s(&r.j_codomain)),
            ]),
        ),
    ])
}

fn iso_json(c: &PrimeCurve, r: &IsogenyRecord, order: Option<&Int>) -> Json {
    let cod = PrimeCurve {
        p: c.p.clone(),
        a: r.codomain.0.clone(),
        b: r.codomain.1.clone(),
    };
    Json::obj(vec![
        ("degree", Json::Num(r.degree as i64)),
        (
            "codomain",
            Json::obj(vec![
                ("a", s(&cod.a)),
                ("b", s(&cod.b)),
                ("j", s(&r.j_codomain)),
                ("icv1", order.map_or(Json::Null, |n| icv1_json(&cod, n))),
            ]),
        ),
        ("kernel", ints(&r.kernel)),
        (
            "x_map",
            Json::obj(vec![("num", ints(&r.map_num)), ("den", ints(&r.map_den))]),
        ),
        ("verified", Json::Bool(r.verified())),
    ])
}
