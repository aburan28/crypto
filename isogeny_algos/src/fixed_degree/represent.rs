/// Fincke–Pohst enumeration of the lattice vectors x (integer rows `rb`, norm form qf) with
/// qf(x) <= bound, calling `visit(x, qf(x))` until it returns true (early exit). Leaves are
/// evaluated exactly in i128 (callers have entries well below 2^40). One of each +-x.
fn enumerate_i128(
    rb: &[[i128; 4]],
    p: i128,
    bound: f64,
    visit: &mut dyn FnMut(&[i128; 4], i128) -> bool,
) -> bool {
    let bil = |u: &[i128; 4], v: &[i128; 4]| {
        (u[0] * v[0] + u[1] * v[1] + p * (u[2] * v[2] + u[3] * v[3])) as f64
    };
    let n = 4;
    let mut q = vec![vec![0f64; n]; n];
    let mut a: Vec<Vec<f64>> = (0..n)
        .map(|r| (0..n).map(|c| bil(&rb[r], &rb[c])).collect())
        .collect();
    for i in 0..n {
        q[i][i] = a[i][i];
        for j in i + 1..n {
            q[i][j] = a[i][j] / a[i][i];
        }
        for k in i + 1..n {
            for l in k..n {
                a[k][l] -= q[i][k] * q[i][l] * q[i][i];
            }
        }
    }
    let bound = bound * (1.0 + 1e-9) + 1.0;
    let mut x = [0i64; 4];
    struct Ctx<'a> {
        q: &'a Vec<Vec<f64>>,
        rb: &'a [[i128; 4]],
        p: i128,
        bound: f64,
    }
    fn rec(
        i: isize,
        x: &mut [i64; 4],
        rem: f64,
        cx: &Ctx,
        visit: &mut dyn FnMut(&[i128; 4], i128) -> bool,
    ) -> bool {
        if i < 0 {
            if x.iter().all(|&v| v == 0) {
                return false;
            }
            let v: [i128; 4] =
                std::array::from_fn(|t| (0..4).map(|k| x[k] as i128 * cx.rb[k][t]).sum());
            let nv = v[0] * v[0] + v[1] * v[1] + cx.p * (v[2] * v[2] + v[3] * v[3]);
            if (nv as f64) <= cx.bound {
                return visit(&v, nv);
            }
            return false;
        }
        let iu = i as usize;
        let q = cx.q;
        let mut c = 0f64;
        for j in iu + 1..4 {
            c += q[iu][j] * x[j] as f64;
        }
        let r = (rem / q[iu][iu]).max(0.0).sqrt();
        let mut lo = (-c - r).ceil() as i64;
        if x[iu + 1..].iter().all(|&v| v == 0) {
            lo = lo.max(0);
        }
        let hi = (-c + r).floor() as i64;
        for v in lo..=hi {
            x[iu] = v;
            let t = v as f64 + c;
            let nrem = rem - q[iu][iu] * t * t;
            if nrem < -1e-6 * rem.abs().max(1.0) {
                continue;
            }
            if rec(i - 1, x, nrem, cx, visit) {
                return true;
            }
        }
        x[iu] = 0;
        false
    }
    let cx = Ctx {
        q: &q,
        rb,
        p,
        bound,
    };
    rec(3, &mut x, bound, &cx, visit)
}

/// An equivalent ideal I xi of norm dividing t_odd and coprime to `avoid` (the search of
/// `Deuring::smooth_equivalent`, with a coprimality filter, exact i128 leaves and early exit:
/// the bound grows by factors of 8 from 8 min Nrd, and the first pass with an admissible norm
/// returns the smallest of up to 32 admissible norms found). Returns (I xi, xi, delta), delta
/// in I with xi = conj(delta) / N(I).
pub fn smooth_equivalent_coprime(
    dg: &Deuring,
    i: &Lattice,
    avoid: &Int,
) -> Option<(Lattice, Quat, Quat)> {
    let alg = &dg.alg;
    let (ni, _) = i.norm(&dg.o0);
    let d2 = &i.den * &i.den;
    let scale = (&d2 * &ni).to_i128()?;
    let t = dg.t_odd as i128;
    let av = avoid.abs().to_i128().unwrap_or(1).max(1);
    let gcd = |mut a: i128, mut b: i128| {
        while b != 0 {
            let r = a % b;
            a = b;
            b = r;
        }
        a.abs()
    };
    let rbi = i.reduced_basis(alg);
    let rb: Vec<[i128; 4]> = rbi
        .iter()
        .map(|v| std::array::from_fn(|k| v[k].to_i128().expect("small lattice")))
        .collect();
    let p = alg.p.to_i128()?;
    let minn = rbi.iter().map(|v| alg.qf(v)).min().unwrap().to_f64();
    let exact = (t as f64) * (scale as f64);
    let mut bound = minn * 8.0;
    // total enumeration budget: an equivalent ideal with an admissible norm normally appears
    // after a few thousand vectors; past the budget the search reports failure instead of
    // enumerating up to t_odd N(I)
    let mut visited: u64 = 0;
    const BUDGET: u64 = 4_000_000;
    loop {
        let b = bound.min(exact);
        let mut best: Option<([i128; 4], i128)> = None;
        let mut found = 0;
        enumerate_i128(&rb, p, b, &mut |v, nv| {
            visited += 1;
            if visited > BUDGET {
                return true;
            }
            if nv % scale == 0 {
                let q = nv / scale;
                if q != 0 && t % q == 0 && gcd(q, av) == 1 {
                    if best.is_none_or(|(_, bn)| nv < bn) {
                        best = Some((*v, nv));
                    }
                    found += 1;
                }
            }
            found >= 32
        });
        if let Some((v, _)) = best {
            let delta = Quat::new(v.map(Int::from), i.den.clone());
            let xi = delta.conj().scale(&Int::one(), &ni);
            return Some((i.rmul(alg, &xi), xi, delta));
        }
        if b >= exact || visited > BUDGET {
            trace(&format!(
                "smooth equivalent: none within budget (visited {visited})"
            ));
            return None;
        }
        bound *= 8.0;
    }
}

/// Deuring image j(E_I) of a left O_0-ideal (as `Deuring::ideal_to_j`, with the faster
/// equivalent-ideal search above).
pub fn fast_ideal_to_j(dg: &Deuring, i: &Lattice) -> Option<(u64, u64)> {
    let (j, _, _) = smooth_equivalent_coprime(dg, i, &Int::one())?;
    let ks = dg.kernel_of_ideal(&j)?;
    let c = dg.isogeny_from_kernels(&ks);
    dg.f2.project(jinv(&dg.f2, &c))
}

/// The largest m with 2^m | p + 1.
pub fn two_adic(p: u64) -> u32 {
    (p + 1).trailing_zeros()
}

/// Can every prime power of d be handled by `Deuring::kernel_of_ideal`?
pub fn is_deuring_smooth(dg: &Deuring, d: &Int) -> bool {
    let Some(dv) = d.to_i128() else { return false };
    if dv <= 0 || dv > u64::MAX as i128 {
        return false;
    }
    factor_u64(dv as u64)
        .iter()
        .all(|&(l, e)| dg.tors.iter().any(|t| t.ell == l && t.e >= e))
}

#[derive(Clone, Debug, Default)]
pub struct ReprOptions {
    /// force the torsion representation even when d is smooth
    pub force_torsion: bool,
    /// 2-power level a for the torsion representation (default: two_adic(p) - 3)
    pub a: Option<u32>,
}

/// Step 6: the isogeny of the left O_R(I_1)-ideal J (norm d, odd). `targets` are the caller's
/// curve models (E_1, E_2) if any; the result is transported to them by isomorphisms.
fn trace(msg: &str) {
    if std::env::var_os("FD_TRACE").is_some() {
        eprintln!("[fixed_degree] {msg}");
    }
}

pub fn ideal_to_isogeny(
    dg: &Deuring,
    i1: &Lattice,
    jdl: &Lattice,
    targets: Option<(&Curve<E4>, &Curve<E4>)>,
    opts: &ReprOptions,
    rng: &mut Rng,
) -> Option<IsogenyRep> {
    let alg = &dg.alg;
    let o0 = &dg.o0;
    let f = &dg.f2;
    let o1 = i1.right_order(alg, o0);
    let d = jdl.norm_int(&o1);
    assert!(!d.is_even(), "ideal_to_isogeny: d must be odd");
    // E_1' and phi_1 : E_0 -> E_1'
    trace(&format!(
        "ideal_to_isogeny: d = {d}, N(I1) = {}",
        i1.norm_int(o0)
    ));
    let (i1s, xi, _) = smooth_equivalent_coprime(dg, i1, &(&d * &Int::from(2i64)))?;
    let n1 = i1s.norm_int(o0);
    trace(&format!("smooth equivalent of I1: N = {n1}"));
    let k_ideal = i1.mul(alg, jdl).rmul(alg, &xi);
    debug_assert!(i1s.contains_lattice(&k_ideal));
    let gens1 = dg.kernel_of_ideal(&i1s)?;
    let p = dg.p;
    let use_kernel = !opts.force_torsion && is_deuring_smooth(dg, &d);
    let a = opts.a.unwrap_or(two_adic(p).saturating_sub(3));
    let m = a + 3;
    let mut lifts = vec![];
    let mut push = vec![];
    if !use_kernel {
        assert!(m <= two_adic(p), "not enough 2-power torsion");
        let full = (p as u128 + 1) * (p as u128 - 1);
        let (pp, qq) = basis_2power(f, &dg.e0, m, full >> m, rng);
        lifts = vec![pp, qq];
        push = vec![pmul(f, &dg.e0, &pp, 2), pmul(f, &dg.e0, &qq, 2)];
    }
    // the d-part kernel E_0[K + d O_0], if used, is pushed through phi_1 as well
    let mut dpart = vec![];
    if use_kernel {
        let mut gl = k_ideal.basis();
        gl.extend(o0.basis().iter().map(|g| g.scale(&d, &Int::one())));
        let l_ideal = Lattice::from_gens(&gl);
        assert!(l_ideal.norm_int(o0) == d);
        dpart = dg.kernel_of_ideal(&l_ideal)?;
    }
    let mut all_pts = push.clone();
    all_pts.extend(dpart.iter().map(|g| g.2));
    let (e1p, imgs1) = push_chain(f, &dg.e0, &gens1, &all_pts);
    let (s_pts, dgens_e1) = imgs1.split_at(push.len());

    let mut rep = if use_kernel {
        let gens: Vec<(u64, u32, Pt4)> = dpart
            .iter()
            .zip(dgens_e1)
            .map(|(g, img)| (g.0, g.1, *img))
            .collect();
        let (cod, _) = push_chain(f, &e1p, &gens, &[]);
        IsogenyRep {
            d: d.clone(),
            domain: e1p,
            codomain: cod,
            repr: Repr::Kernel { gens },
            j_ok: false,
            pairing_ok: None,
            n1: n1.clone(),
        }
    } else {
        // chi(S_i) = phi_K(R_i), through K' = K conj(theta) / N(K)
        let (cod, images) = eval_ideal_on_lifts(dg, &k_ideal, &lifts, m)?;
        trace("chi images done");
        let s = [s_pts[0], s_pts[1]];
        let chi = [images[0], images[1]];
        // Kani certificate with an auxiliary isogeny g : E_1' -> X of degree c = 2^a - d, the
        // isogeny of a random left O_R(I_1)-ideal J_aux of norm c, evaluated the same way
        // (g(S_i) = phi_{K_aux}(R_i), K_aux = I_1 J_aux xi); gcd(c, d) = gcd(2^a, d) = 1.
        let two_a = Int::from(1i64 << a);
        let mut kani_status = KaniCheck::None;
        if d < two_a {
            let c = &two_a - &d;
            if let Some(fac) = super::factor::factor_bounded(&c, 1 << 22) {
                let mut qs = vec![];
                for (q, e) in &fac {
                    for _ in 0..*e {
                        qs.push(q.clone());
                    }
                }
                trace(&format!("aux degree c = {c} = {fac:?}"));
                let jaux = super::pipeline::plant_ideal(alg, o0, i1, &qs, rng);
                trace("aux ideal planted");
                let kaux = i1.mul(alg, &jaux).rmul(alg, &xi);
                if let Some((xcur, gimg)) = eval_ideal_on_lifts(dg, &kaux, &lifts, m) {
                    trace("aux images done");
                    let ok = kani_check(f, &xcur, &cod, &chi, &[gimg[0], gimg[1]], a);
                    trace(&format!("Kani check {ok:?}"));
                    kani_status = KaniCheck::Kani2 { n: a, c, ok };
                }
            }
        }
        let pairing_ok = weil_2k(f, &e1p, &s[0], &s[1], a + 2)
            .zip(weil_2k(f, &cod, &chi[0], &chi[1], a + 2))
            .map(|(w1, w2)| {
                let ord = 1i128 << (a + 2);
                let dd = d.modulo(&Int::from(ord)).to_i128().unwrap() as u128;
                f.pow(w1, dd) == w2
            });
        IsogenyRep {
            d: d.clone(),
            domain: e1p,
            codomain: cod,
            repr: Repr::Torsion {
                a,
                basis: s,
                images: chi,
                kani: kani_status,
            },
            j_ok: false,
            pairing_ok,
            n1: n1.clone(),
        }
    };
    // expected codomain j: Deuring image of K (equivalently of I_1 J)
    let jk = fast_ideal_to_j(dg, &k_ideal)?;
    let jc = f.project(jinv(f, &rep.codomain))?;
    rep.j_ok = jk == jc;
    if let Some((t1, t2)) = targets {
        transport(f, &mut rep, t1, t2)?;
    }
    Some(rep)
}

/// Move the representation to the caller's models E_1, E_2 (same j-invariants). For the kernel
/// representation the Vélu chain is recomputed from the caller's E_1 and its codomain j checked
/// against j(E_2).
fn transport(f: &Fp4, rep: &mut IsogenyRep, t1: &Curve<E4>, t2: &Curve<E4>) -> Option<()> {
    let u1 = curve_iso(f, &rep.domain, t1)?;
    let u2 = curve_iso(f, &rep.codomain, t2)?;
    match &mut rep.repr {
        Repr::Kernel { gens } => {
            for g in gens.iter_mut() {
                g.2 = apply_iso(f, u1, &g.2);
            }
            let (cod, _) = push_chain(f, t1, gens, &[]);
            rep.j_ok = rep.j_ok && jinv(f, &cod) == jinv(f, t2);
        }
        Repr::Torsion { basis, images, .. } => {
            for b in basis.iter_mut() {
                *b = apply_iso(f, u1, b);
            }
            for q in images.iter_mut() {
                *q = apply_iso(f, u2, q);
            }
        }
    }
    rep.domain = *t1;
    rep.codomain = *t2;
    Some(())
}
