#[derive(Clone, Debug)]
#[allow(clippy::large_enum_variant)]
pub enum Repr {
    /// chi = Vélu chain from E_1 with these kernel generators (orders l^a)
    Kernel { gens: Vec<(u64, u32, Pt4)> },
    /// chi(S_i) for a basis S_1, S_2 of E_1[2^(a+2)]
    Torsion {
        a: u32,
        basis: [Pt4; 2],
        images: [Pt4; 2],
        kani: KaniCheck,
    },
}

/// Kani certificate of a torsion representation. `ok`: Some(true) if the (2^n, 2^n)-isogeny
/// of X x E_2 with kernel {(g(S), chi(S)) : S in E_1[2^n]} splits and the twisted control
/// (chi S_2 -> chi S_2 + 2 chi S_1) does not; None if a chain step could not be evaluated.
#[derive(Clone, Debug)]
pub enum KaniCheck {
    /// no certificate (d >= 2^a, or the auxiliary degree could not be factored)
    None,
    /// dimension 2 with an auxiliary isogeny g : E_1 -> X of degree c = 2^n - d
    Kani2 { n: u32, c: Int, ok: Option<bool> },
}

impl KaniCheck {
    pub fn passed(&self) -> bool {
        matches!(self, KaniCheck::Kani2 { ok: Some(true), .. })
    }
}

/// phi_K on the points [2] P_i of 2-power order, for any left O_0-ideal K of odd norm: with
/// theta in K and K' = K conj(theta) / N(K) of odd smooth norm, phi_K = [N(K')^{-1}] phi_K' o
/// theta (theta = conj(phi_K') phi_K). `lifts` are points of order 2^m; returns the codomain of
/// phi_K' (the model of E_K this identity fixes) and the images of [2] lifts (order 2^(m-1)).
pub fn eval_ideal_on_lifts(
    dg: &Deuring,
    k: &Lattice,
    lifts: &[Pt4],
    m: u32,
) -> Option<(Curve<E4>, Vec<Pt4>)> {
    let f = &dg.f2;
    let ord_lift = 1u128 << m;
    let ord = 1u128 << (m - 1);
    let (kp, _, theta) = smooth_equivalent_coprime(dg, k, &Int::from(2i64))?;
    let nkp = kp.norm_int(&dg.o0);
    trace(&format!(
        "eval_ideal_on_lifts: N(K) = {}, N(K') = {nkp}",
        k.norm_int(&dg.o0)
    ));
    let th_r: Vec<Pt4> = lifts
        .iter()
        .map(|l| act_on_double(f, &dg.e0, &theta, l, ord_lift))
        .collect();
    let gk = dg.kernel_of_ideal(&kp)?;
    let (cod, im) = push_chain(f, &dg.e0, &gk, &th_r);
    let inv = nkp.inv_mod(&Int::from(ord as i128))?;
    Some((
        cod,
        im.iter().map(|q| smul_int(f, &cod, q, &inv, ord)).collect(),
    ))
}

/// c = u^2 + w^2 (u, w >= 0), by factoring c and Cornacchia.
pub fn two_squares(c: &Int) -> Option<(Int, Int)> {
    if c.is_neg() {
        return None;
    }
    let fac = super::factor::factor_bounded(c, 1 << 20)?;
    let sols = super::cornacchia::cornacchia_all(&Int::one(), c, &fac);
    sols.into_iter().next()
}

/// Kani certificate over F_{p^2}: the (2^a, 2^a)-isogeny of X x E_2 with kernel generated by
/// [4](g S_i, chi S_i) splits, and the twisted kernel (chi S_2 -> chi S_2 + 2 chi S_1) does
/// not. Some(true) only if both hold.
pub fn kani_check(
    f: &Fp4,
    x: &Curve<E4>,
    e2: &Curve<E4>,
    chi: &[Pt4; 2],
    aux: &[Pt4; 2],
    a: u32,
) -> Option<bool> {
    let z = Zp2::new(f.p());
    let pc = |c: &Curve<E4>| -> Option<Curve<(u64, u64)>> {
        Some(Curve::new(f.project(c.a)?, f.project(c.b)?))
    };
    let pp = |q: &Pt4| -> Option<Pt<(u64, u64)>> {
        match *q {
            Pt::Inf => Some(Pt::Inf),
            Pt::Aff(x, y) => Some(Pt::Aff(f.project(x)?, f.project(y)?)),
        }
    };
    let (c1, c2) = (pc(x)?, pc(e2)?);
    let k = [(pp(&aux[0])?, pp(&chi[0])?), (pp(&aux[1])?, pp(&chi[1])?)];
    let split = crate::theta::chain(&z, &c1, &c2, k, a, &[])?
        .split
        .is_some();
    let tw = padd(f, e2, &chi[1], &pmul(f, e2, &chi[0], 2));
    let kt = [(pp(&aux[0])?, pp(&chi[0])?), (pp(&aux[1])?, pp(&tw)?)];
    let split_tw = crate::theta::chain(&z, &c1, &c2, kt, a, &[])
        .map(|r| r.split.is_some())
        .unwrap_or(false);
    Some(split && !split_tw)
}

/// Is the point of exact order 2^k?
pub fn has_order_2k(f: &Fp4, e: &Curve<E4>, p: &Pt4, k: u32) -> bool {
    pmul(f, e, p, 1u128 << (k - 1)) != Pt::Inf && pmul(f, e, p, 1u128 << k) == Pt::Inf
}

