/// Miller function f_{n,P}(Q) for n = 2^k (divisor n(P) - n(O)), by doubling.
fn miller_2k(f: &Fp4, e: &Curve<E4>, p: &Pt4, q: &Pt4, k: u32) -> Option<E4> {
    let (xq, yq) = match *q {
        Pt::Aff(x, y) => (x, y),
        Pt::Inf => return None,
    };
    let mut t = *p;
    let mut acc = f.one();
    for _ in 0..k {
        let (xt, yt) = match t {
            Pt::Aff(x, y) => (x, y),
            Pt::Inf => return None,
        };
        let t2 = padd(f, e, &t, &t);
        // tangent line at T: y - yt - lam (x - xt) (vertical x - xt if yt = 0), over v_{2T}
        let (num, den) = if f.is_zero(yt) {
            (f.sub(xq, xt), f.one())
        } else {
            let lam = f.div(f.add(f.mul(f.from_u64(3), f.sq(xt)), e.a), f.add(yt, yt));
            let num = f.sub(f.sub(yq, yt), f.mul(lam, f.sub(xq, xt)));
            let den = match t2 {
                Pt::Aff(x2, _) => f.sub(xq, x2),
                Pt::Inf => f.one(),
            };
            (num, den)
        };
        if f.is_zero(num) || f.is_zero(den) {
            return None;
        }
        acc = f.mul(f.sq(acc), f.div(num, den));
        t = t2;
    }
    if t != Pt::Inf {
        return None;
    }
    Some(acc)
}

/// Weil pairing e_{2^k}(P, Q) = f_P(Q) / f_Q(P) (n even, so the sign (-1)^n is 1); None in the
/// degenerate cases of this simple Miller loop.
pub fn weil_2k(f: &Fp4, e: &Curve<E4>, p: &Pt4, q: &Pt4, k: u32) -> Option<E4> {
    let a = miller_2k(f, e, p, q, k)?;
    let b = miller_2k(f, e, q, p, k)?;
    Some(f.div(a, b))
}

