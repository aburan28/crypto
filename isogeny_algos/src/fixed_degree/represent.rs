pub type E4 = ((u64, u64), (u64, u64));
type Pt4 = Pt<E4>;

// ------------------------------------------------------------------ helpers

fn i_map(f: &Fp4, p: &Pt4) -> Pt4 {
    match *p {
        Pt::Inf => Pt::Inf,
        Pt::Aff(x, y) => Pt::Aff(f.neg(x), f.mul(f.embed((0, 1)), y)),
    }
}

fn frob(f: &Fp4, p: &Pt4) -> Pt4 {
    match *p {
        Pt::Inf => Pt::Inf,
        Pt::Aff(x, y) => Pt::Aff(f.frob(x), f.frob(y)),
    }
}

/// [k] P for a signed big k, reduced modulo the point order `n`.
fn smul_int(f: &Fp4, e: &Curve<E4>, p: &Pt4, k: &Int, n: u128) -> Pt4 {
    let r = k.modulo(&Int::from(n as i128)).to_i128().unwrap() as u128;
    pmul(f, e, p, r)
}

/// alpha(P) on E_0 for alpha with integer coordinates c (alpha = c0 + c1 i + c2 j + c3 k) and P
/// of order dividing n.
pub fn act_integral(f: &Fp4, e0: &Curve<E4>, c: &[Int; 4], p: &Pt4, n: u128) -> Pt4 {
    let pi = frob(f, p);
    let imgs = [*p, i_map(f, p), pi, i_map(f, &pi)];
    let mut s = Pt::Inf;
    for t in 0..4 {
        s = padd(f, e0, &s, &smul_int(f, e0, &imgs[t], &c[t], n));
    }
    s
}

/// alpha([2] P) = (2 alpha)(P) for alpha in O_0 (denominator dividing 2) and P of order n.
pub fn act_on_double(f: &Fp4, e0: &Curve<E4>, alpha: &Quat, p_lift: &Pt4, n: u128) -> Pt4 {
    let two = Int::from(2i64);
    let (q, r) = two.divrem_trunc(&alpha.d);
    assert!(r.is_zero(), "act_on_double: denominator must divide 2");
    let c: [Int; 4] = std::array::from_fn(|t| &alpha.c[t] * &q);
    act_integral(f, e0, &c, p_lift, n)
}

/// Vélu chain with kernel generated by the given points (orders l^a), pushing `pts` through.
pub fn push_chain(
    f: &Fp4,
    e: &Curve<E4>,
    ks: &[(u64, u32, Pt4)],
    pts: &[Pt4],
) -> (Curve<E4>, Vec<Pt4>) {
    let mut cur = *e;
    let mut pend: Vec<(u64, u32, Pt4)> = ks.to_vec();
    let mut pts = pts.to_vec();
    while let Some((ell, a, k)) = pend.first().cloned() {
        if a == 0 {
            pend.remove(0);
            continue;
        }
        let k1 = pmul(f, &cur, &k, ell.pow(a - 1) as u128);
        let iso = velu_cyclic(f, &cur, &k1, ell);
        for item in pend.iter_mut() {
            item.2 = iso.eval(f, &item.2);
        }
        for q in pts.iter_mut() {
            *q = iso.eval(f, q);
        }
        pend[0].1 -= 1;
        cur = iso.cod;
    }
    (cur, pts)
}

/// u with E_to = (u^4 a, u^6 b) (so (x, y) -> (u^2 x, u^3 y) maps E_from -> E_to), for curves
/// with j != 0, 1728.
pub fn curve_iso(f: &Fp4, from: &Curve<E4>, to: &Curve<E4>) -> Option<E4> {
    if f.is_zero(from.a) || f.is_zero(from.b) || f.is_zero(to.a) || f.is_zero(to.b) {
        return None;
    }
    let u2 = f.div(f.mul(to.b, from.a), f.mul(from.b, to.a));
    let u = f.sqrt(u2)?;
    let u4 = f.sq(u2);
    let u6 = f.mul(u4, u2);
    if f.mul(u4, from.a) == to.a && f.mul(u6, from.b) == to.b {
        Some(u)
    } else {
        None
    }
}

pub fn apply_iso(f: &Fp4, u: E4, p: &Pt4) -> Pt4 {
    match *p {
        Pt::Inf => Pt::Inf,
        Pt::Aff(x, y) => {
            let u2 = f.sq(u);
            Pt::Aff(f.mul(u2, x), f.mul(f.mul(u2, u), y))
        }
    }
}

/// Basis of E[2^m] (two points of order 2^m with distinct halves of order 2) from random points
/// times the cofactor `cof` = #E(F_{p^4})-part / 2^m.
pub fn basis_2power(f: &Fp4, e: &Curve<E4>, m: u32, cof: u128, rng: &mut Rng) -> (Pt4, Pt4) {
    let half = 1u128 << (m - 1);
    let pt = |rng: &mut Rng| loop {
        let r = pmul(f, e, &crate::curve::random_point_f(f, e, rng), cof);
        if pmul(f, e, &r, half) != Pt::Inf {
            return r;
        }
    };
    let p = pt(rng);
    let ph = pmul(f, e, &p, half);
    loop {
        let q = pt(rng);
        if pmul(f, e, &q, half) != ph {
            return (p, q);
        }
    }
}

