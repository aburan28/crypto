//! Step 6 of the fixed-degree algorithm: from an ideal of norm d to an isogeny of degree d.
//!
//! Input: a left O_0-ideal I_1 (O_R(I_1) = End(E_1)) and a left O_R(I_1)-ideal J of norm d, odd.
//! Write I_1' = I_1 xi for an equivalent ideal of odd smooth norm N_1 coprime to d (its isogeny
//! phi_1 : E_0 -> E_1' is a Vélu chain, E_1' isomorphic to E_1) and K = I_1 J xi (a left
//! O_0-ideal of norm N_1 d contained in I_1'). The isogeny phi_K factors as chi o phi_1 with
//! chi : E_1' -> E_2' of degree d; chi is the isogeny we output, in one of two representations:
//!
//! * **Kernel** (smooth d, every prime power of d has rational torsion over F_{p^4}): the
//!   d-part L = K + d O_0 has kernel E_0[L] (discrete logarithms in a torsion basis), and
//!   ker chi = phi_1(E_0[L]); chi is the Vélu chain from E_1' with those generators ("a sequence
//!   of rational maps" on the slides).
//! * **Torsion images** (any odd d; Robert's representation, Robert 2022 / the HD representation
//!   of SQIsign2D): chi on a basis (S_1, S_2) of E_1'[2^(a+2)], computed through the quaternions
//!   without knowing chi: for theta in K with K' = K conj(theta) / N(K) of odd smooth norm,
//!   theta = conj(phi_K') phi_K, hence phi_K = [N(K')^{-1}] phi_K' o theta on points of 2-power
//!   order (`eval_ideal_on_lifts`). With S_i = phi_1(R_i), chi(S_i) = phi_K(R_i).
//!   The representation is certified by Kani's lemma in dimension 2: with c = 2^a - d (so
//!   gcd(c, d) = 1), take a random left O_R(I_1)-ideal J_aux of norm c and its isogeny
//!   g : E_1' -> X, evaluated on the S_i the same way; for f : A -> B, g : A -> C of coprime
//!   degrees summing to N, {(f(P), g(P)) : P in A[N]} is the kernel of an (N, N)-isogeny
//!   B x C -> A x D, so the (2^a, 2^a)-isogeny of X x E_2' with kernel {(g(S), chi(S))} splits
//!   (theta-model chain, `theta::chain`). The twisted kernel with chi(S_2) replaced by
//!   chi(S_2) + 2 chi(S_1) must not split (negative control). The Weil pairing check
//!   e(chi S_1, chi S_2) = e(S_1, S_2)^d is reported as well.
//!   (An endomorphism of E_1' of degree 2^a - d, or Robert's dimension-4 integer matrix
//!   [[u, -w], [w, u]], are the textbook auxiliaries; the first does not exist when
//!   2^a - d < sqrt(p) (only integers have such small norm), and with the second the first
//!   (2,2,2,2)-step is a product of two gluings, which `theta_g::chain_g` does not handle.)
//!
//! Elements of O_0 = <1, i, (i+j)/2, (1+k)/2> have denominator 2, so on 2-power torsion they are
//! applied to a lift: alpha([2] P) = (2 alpha)(P) with P in E_0[2^(a+3)] (2 alpha is integral).
//! All 2-power torsion here is F_{p^2}-rational (the curves have Frobenius -p over F_{p^2}).
use crate::curve::{jinv, padd, pmul, Curve, Isogeny, Pt};
use crate::ext::Fp4;
use crate::field::{factor_u64, Field, Rng, Zp2};
