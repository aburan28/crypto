/* ---------------------------------------------------------------- BigInt -- */

const mod = (a, m) => ((a % m) + m) % m;

function egcd(a, b) {
  let [old_r, r] = [a, b], [old_s, s] = [1n, 0n];
  while (r !== 0n) {
    const q = old_r / r;
    [old_r, r] = [r, old_r - q * r];
    [old_s, s] = [s, old_s - q * s];
  }
  return [old_r, old_s];
}

function invMod(a, m) {
  const [g, s] = egcd(mod(a, m), m);
  if (g !== 1n) throw new Error("not invertible");
  return mod(s, m);
}

/* Affine short-Weierstrass arithmetic; null is the point at infinity. */
function makeCurve(p, a) {
  const C = {
    p, a,
    neg: (P) => (P === null ? null : [P[0], mod(-P[1], p)]),
    add(P, Q) {
      if (P === null) return Q;
      if (Q === null) return P;
      let lam;
      if (P[0] === Q[0]) {
        if (mod(P[1] + Q[1], p) === 0n) return null;
        lam = mod((3n * P[0] * P[0] + a) * invMod(2n * P[1], p), p);
      } else {
        lam = mod((Q[1] - P[1]) * invMod(Q[0] - P[0], p), p);
      }
      const x3 = mod(lam * lam - P[0] - Q[0], p);
      return [x3, mod(lam * (P[0] - x3) - P[1], p)];
    },
    mul(k, P) {
      let R = null, D = P;
      for (let e = k; e > 0n; e >>= 1n) {
        if (e & 1n) R = C.add(R, D);
        D = C.add(D, D);
      }
      return R;
    },
  };
  return C;
}

/* splitmix64: the walk's only randomness. Deterministic from the job seed, so
 * a trail is reproducible from its (slot, restart) pair alone -- which is what
 * lets a distinguished point be reported as four words instead of a point plus
 * its coefficients. */
const M64 = (1n << 64n) - 1n;
function splitmix(stateRef) {
  stateRef.s = (stateRef.s + 0x9e3779b97f4a7c15n) & M64;
  let z = stateRef.s;
  z = ((z ^ (z >> 30n)) * 0xbf58476d1ce4e5b9n) & M64;
  z = ((z ^ (z >> 27n)) * 0x94d049bb133111ebn) & M64;
  return (z ^ (z >> 31n)) & M64;
}

/* A 256-bit draw in [1, n): four splitmix words, reduced. The bias is below
 * 2^-160 for every n here, which is far below anything a walk can notice. */
function draw(seed, label, i, j, n) {
  const st = { s: (seed ^ BigInt(label) * 0x2545f4914f6cdd1dn ^ (BigInt(i) << 32n) ^ BigInt(j)) & M64 };
  let v = 0n;
  for (let k = 0; k < 4; k++) v = (v << 64n) | splitmix(st);
  return mod(v, n - 1n) + 1n;
}

/* --------------------------------------------------------- limb plumbing -- */

const LIMB_BITS = 16n, LIMB_MASK = 0xffffn;

function limbs(x, L) {
  const out = new Uint32Array(L);
  let v = x;
  for (let i = 0; i < L; i++) { out[i] = Number(v & LIMB_MASK); v >>= LIMB_BITS; }
  if (v !== 0n) throw new Error("value does not fit in " + L + " limbs");
  return out;
}

const fromLimbs = (arr, off, L) => {
  let v = 0n;
  for (let i = L - 1; i >= 0; i--) v = (v << LIMB_BITS) | BigInt(arr[off + i]);
  return v;
};

function n0inv16(p) {
  /* -p^-1 mod 2^16 */
  return Number(mod(-invMod(mod(p, 1n << 16n), 1n << 16n), 1n << 16n));
}

/* ----------------------------------------------------------------- state -- */

const WG_SIZE = 64;          // threads per workgroup
const BATCH = 8;             // walks per thread; also the batched-inverse width
const R_BITS = 6;            // jump-table size, 2^6 = 64 entries
const R = 1 << R_BITS;
const DP_TABLE_CAP = 1 << 19;  // distinguished points held in memory at once
const TARGET_MS = 40;        // per-dispatch budget: long enough to amortise the
                             // submit, short enough to stay interruptible

/* ------------------------------------------------------------------ host -- */

/* Everything derived from a job: the curve, the jump table in both
 * representations, and the two predicates the shader implements. The host
 * copies of `partition` and `isDp` read the MONTGOMERY form, exactly as the
 * device does -- if they read the canonical form instead, every replay would
 * diverge on its first step. */
function prepare(job) {
  const p = BigInt(job.p), n = BigInt(job.n);
  /* One limb more than p needs: fe_add_raw_p adds p without reducing, so the
   * representation has to hold 2p, i.e. p < 2^(16*L - 1). */
  const L = Math.ceil((p.toString(2).length + 1) / 16);
  const Rmont = (1n << (BigInt(L) * LIMB_BITS));
  const toMont = (x) => mod(x * Rmont, p);
  const E = makeCurve(p, BigInt(job.a));
  const G = [BigInt(job.Gx), BigInt(job.Gy)];
  const Q = [BigInt(job.Qx), BigInt(job.Qy)];
  const seed = BigInt(job.seed);

  const coef = [], table = [];
  for (let j = 0; j < R; j++) {
    const c = draw(seed, 1, j, 0, n), d = draw(seed, 2, j, 0, n);
    coef.push([c, d]);
    const Mj = E.add(E.mul(c, G), E.mul(d, Q));
    if (Mj === null) throw new Error("degenerate jump table entry");
    table.push(Mj);
  }

  const dpMask = (job.dp_bits >= 32) ? 0xffffffff : ((1 << job.dp_bits) - 1) >>> 0;

  const st = {
    job, p, n, L, Rmont, toMont, E, G, Q, seed, coef, table, dpMask,
    partition: (P) => Number(toMont(P[0]) & BigInt(R - 1)),
    isDp: (P) => (((Number(toMont(P[0]) & 0xffffffffn) >>> 8) & dpMask) === 0),
    /* Trails are keyed by the Montgomery form, which is what the device
     * reports; it is a bijection on field elements, so it keys collisions
     * exactly as the canonical form would, with no conversion per report. */
    keyOf: (P) => toMont(P[0]).toString(16),
    /* Start of trail (slot, restart) = aG + bQ, with (a, b) drawn from the
     * job seed so the host can rebuild the trail from those two indices. */
    seedTrail(slot, restart) {
      const a = draw(seed, 3, slot, restart, n), b = draw(seed, 4, slot, restart, n);
      const P = E.add(E.mul(a, G), E.mul(b, Q));
      return { a, b, P };
    },
  };
  return st;
}

/* Replay a trail on the host, tracking its coefficients: the device reports
 * only (slot, restart, steps, x), so this is where a distinguished point gets
 * its (a, b) back. Returns null if the replay does not land on the reported x,
 * which would mean host and device disagree and no collision may be trusted. */
function replay(st, slot, restart, steps, xHex) {
  let { a, b, P } = st.seedTrail(slot, restart);
  for (let i = 0; i < steps; i++) {
    const j = st.partition(P);
    const [c, d] = st.coef[j];
    P = st.E.add(P, st.table[j]);
    if (P === null) return null;
    a = mod(a + c, st.n); b = mod(b + d, st.n);
  }
  if (st.keyOf(P) !== xHex) return null;
  return { a, b, P };
}

/* A collision on x is a collision on the point up to sign, so both signs are
 * tried; only the one that verifies is reported. */
async function solveCollision(st, first, second, xHex) {
  const A = replay(st, first.slot, first.restart, first.steps, xHex);
  const B = replay(st, second.slot, second.restart, second.steps, xHex);
  if (!A || !B) return null;
  for (const sign of [1n, -1n]) {
    const num = mod(A.a - sign * B.a, st.n);
    const den = mod(sign * B.b - A.b, st.n);
    if (den === 0n) continue;
    let k;
    try { k = mod(num * invMod(den, st.n), st.n); } catch (e) { continue; }
    const check = st.E.mul(k, st.G);
    if (check && check[0] === st.Q[0] && check[1] === st.Q[1]) {
      return { k: k.toString(), verified: true, x: xHex, trails: [first.steps, second.steps] };
    }
  }
  return null;
}

