const {chromium} = require('playwright');
const assert = require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.setContent(require('node:fs').readFileSync(require('node:path').join(process.argv[2]||process.cwd(),'docs/backend-leaderboard/index.html'),'utf8'));
 await page.waitForSelector('#rows tr');
 assert.equal(await page.locator('#rows tr').count(),626);
 assert.equal(await page.getByRole('link',{name:'Reproduction criteria',exact:true}).getAttribute('href'),'REPRODUCING.md');
 assert.equal(await page.getByRole('link',{name:'Rerun command cards',exact:true}).getAttribute('href'),'REPLAY_PLAN.json');
 assert.equal(await page.getByRole('link',{name:'Pinned hashes',exact:true}).getAttribute('href'),'reproduction.lock.json');
 await page.selectOption('#backend','SAT');
 assert.match(await page.locator('#rows').innerText(),/SAT conflicts/);
 assert.match(await page.locator('#rows').innerText(),/learned clauses/);
 await page.locator('#rows details').first().locator('summary').click();
 assert.match(await page.locator('#rows pre').first().innerText(),/solver_origin/);
 await page.click('#reset');
 await page.selectOption('#degree','51');
 assert.match(await page.locator('#rows').innerText(),/No imported observations/);
 await page.click('#reset');
 await page.selectOption('#degree','83');
 assert.match(await page.locator('#rows').innerText(),/No imported observations/);
 assert.doesNotMatch(await page.locator('#rows').innerText(),/F6-IC/);
 await page.click('#reset');
 await page.evaluate(()=>scrollTo(0,0)); await page.screenshot({path:'/tmp/crypto-board-desktop.png'});
 await page.setViewportSize({width:390,height:844});
 await page.evaluate(()=>scrollTo(0,0)); await page.screenshot({path:'/tmp/crypto-board-mobile.png'});
 const width=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,viewport:innerWidth}));
 assert.ok(width.scroll<=width.viewport+1,JSON.stringify(width));
 assert.deepEqual(errors,[]);
 console.log('Passed: 626 rows; SAT counters and provenance; degree-51 gap; degree-83 gap; reset; desktop/mobile; no script errors.');
 await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1;});
