//! # Signature-based F4 over the tower quotient ring.
//!
//! [`f4_fp_tower`](super::f4_fp_tower) spends most of a large run on rows
//! that reduce to zero: in round 3's `m = 4`, `N = 16` system, 88% of the
//! last step's rows (`research/notes/index-calculus/RESEARCH_PKM_TOWER_ORACLE.md`
//! §12.7). Signature-based algorithms (F5, GVW, Roune–Stillman's signature
//! bases) predict most such rows from syzygies and never build them. This
//! is that algorithm on the same ring `R = F_p[y, u] / (towers)`, in the
//! matrix (F4) form.
//!
//! ## Signatures live in the polynomial ring
//!
//! The boolean engine's note (`matrix_f5_f2.rs`) shows why the textbook
//! criterion is unsound in a quotient ring: multiplying by a monomial is not
//! order-compatible there (`y·(y + …)` rewrites to a smaller monomial). This
//! engine never multiplies signatures in `R`. The module is `P^k` over the
//! polynomial ring `P = F_p[y, u]`, generated by the inputs `f_1, …, f_k`,
//! and the tower relations `T_j = y_j² − rule_j` are generators of lower
//! index, a Gröbner basis already (Lemma 1 of the note).
//! - A signature is a `P`-monomial times `e_i`. The principal syzygy of
//!   `f_i` with `T_j` has signature `y_j²·e_i`, so every signature with a
//!   squared tower variable is a syzygy signature and is never processed.
//!   Live signatures are therefore square-free in the tower variables.
//! - Reducing by `T_j` never changes a signature (its component is lower),
//!   so polynomials stay in normal form in `R`.
//! - A *tower pair* `(g, y_j)`, `y_j | LM(g)`, is the S-pair of `g` with
//!   `T_j`: the row `NF(y_j·g)` with signature `y_j·sig(g)`, dropped when
//!   `y_j` already divides `sig(g)`.
//!
//! ## The algorithm
//! - **Module order** ([`ModuleOrder`]): by default position over term
//!   (every signature of `e_i` before any of `e_{i+1}`, F5's incremental
//!   order), then signature degree `deg t + deg f_i` (the sugar), then
//!   grevlex on `t`; or signature degree first, then the index. Both are
//!   compatible with multiplication by monomials of `P`, which is all the
//!   theory asks.
//! - **Steps** take every pair of the lowest signature degree. The rows (the
//!   larger half of each critical pair, each tower row, and each generator
//!   the first time) are joined by one reducer per monomial with a divisor:
//!   among the basis elements whose leading monomial divides it, the one
//!   whose multiple has the smallest signature.
//! - **Elimination** takes the rows in increasing signature. A row is
//!   top-reduced only by rows of strictly smaller signature (regular
//!   reduction); one whose leading monomial meets a row of equal signature
//!   is singular and dropped. A row reduced to zero gives a syzygy
//!   signature.
//! - **New elements** are the S-rows that survive, and the reducer rows
//!   whose leading monomial moved, with square-free signatures.
//! - **Criteria**, applied when a step takes its pairs:
//!   - *syzygy*: the signature is divisible by a known syzygy signature:
//!     those of zero reductions, the Koszul signatures
//!     `max(LM(f_j)·sig(h), LM(h)·e_j)` of every element `h` against every
//!     input `f_j`, and the Koszul signature of a pair with coprime leading
//!     monomials, which is the pair's own (such pairs are never stored);
//!   - *rewrite*: one row per signature, built from the element that
//!     stands for it among those whose signature divides it ([`Rewrite`]:
//!     the largest `sig/LM` by default, or the latest), whichever pairs
//!     produced the signature (Roune–Stillman).
//!
//! A signature equal to an element's own is not skipped: the element is
//! rebuilt as a row and reduced again. A row becomes an element with only
//! the reducers its step had, so an element found earlier in the same step,
//! of smaller signature, may still reduce its lead. The pair between the two
//! has the later element's signature, and skipping it lost those reductions
//! (a build that did returned bases without them).
//!
//! Correctness does not rest on this text: the tests compare the basis with
//! `f4_fp_tower`'s on random systems and refutations with exhaustive
//! search, and the example checks every row with `verify.py`.
//!
//! ## What it measures
//! - `solving_degree_max`: the highest degree of a row that yielded a new
//!   element. A row's degree is its nominal one, `deg t + deg LM(g)`, which
//!   for an S-row is the lcm degree `f4_fp_tower` reports.
//! - The signature degree of each step, the rows reduced to zero, the rows
//!   the criteria skipped, and `F_p` multiply-adds, the same unit.
//!
//! Steps take pairs by signature degree, and a step's new elements can
//! create pairs of the same degree with smaller signatures than rows the
//! step already reduced ("late" pairs). They are processed in the next
//! step and counted: the theory asks for increasing signatures, so the
//! tests are what vouches for a run that has them.

