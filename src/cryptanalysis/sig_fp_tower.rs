// ── Signatures ───────────────────────────────────────────────────────

/// A module term `t·e_i`, `t` a monomial of `P` whose tower exponents are
/// at most 2: `ones` holds the tower variables of exponent ≥ 1, `twos`
/// those of exponent 2. `sugar = deg t + deg f_i`.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
struct PSig {
    sugar: u32,
    idx: u32,
    ones: u64,
    twos: u64,
    free: [u8; MAX_FREE],
}

impl PSig {
    fn square_free(self) -> bool {
        self.twos == 0
    }

    /// The monomial `t` as a key of `R`, when it is square-free.
    fn mono(self) -> Mono {
        debug_assert!(self.square_free());
        mono(self.ones, self.free)
    }

    fn of(m: Mono, idx: u32, d: u32) -> PSig {
        PSig {
            sugar: degree_of(m) + d,
            idx,
            ones: mask_of(m),
            twos: 0,
            free: free_of(m),
        }
    }

    /// `u · self`, for a monomial `u` of `R` and a square-free `self`.
    fn times(self, u: Mono) -> PSig {
        debug_assert!(self.square_free());
        let um = mask_of(u);
        let uf = free_of(u);
        let mut free = self.free;
        for (a, b) in free.iter_mut().zip(uf) {
            *a += b;
        }
        PSig {
            sugar: self.sugar + degree_of(u),
            idx: self.idx,
            ones: self.ones | um,
            twos: self.ones & um,
            free,
        }
    }
}

impl Ord for PSig {
    /// The module order: sugar, then index, then grevlex on `t` with tower
    /// variable 0 largest and the free variables smallest (the order of
    /// [`Mono`] keys, extended to exponent 2).
    fn cmp(&self, o: &Self) -> Ordering {
        self.sugar
            .cmp(&o.sugar)
            .then(self.idx.cmp(&o.idx))
            .then_with(|| {
                // Same sugar and index, hence the same degree of `t`: the
                // last differing variable decides, the smaller exponent
                // making the larger monomial.
                for k in (0..MAX_FREE).rev() {
                    if self.free[k] != o.free[k] {
                        return o.free[k].cmp(&self.free[k]);
                    }
                }
                let diff = (self.ones ^ o.ones) | (self.twos ^ o.twos);
                if diff == 0 {
                    return Ordering::Equal;
                }
                let j = 63 - diff.leading_zeros();
                let e = |s: &PSig| ((s.ones >> j) & 1) + ((s.twos >> j) & 1);
                e(o).cmp(&e(self))
            })
    }
}

impl PartialOrd for PSig {
    fn partial_cmp(&self, o: &Self) -> Option<Ordering> {
        Some(self.cmp(o))
    }
}

/// Every divisor of `m` (tower submasks times free vectors below `m`'s),
/// passed to `f` until it returns `true`; returns whether one did.
fn any_divisor(m: Mono, mut f: impl FnMut(Mono) -> bool) -> bool {
    let mask = mask_of(m);
    let fm = free_of(m);
    let mut s = mask;
    loop {
        let mut fv = [0u8; MAX_FREE];
        loop {
            if f(mono(s, fv)) {
                return true;
            }
            let mut k = 0;
            while k < MAX_FREE {
                if fv[k] < fm[k] {
                    fv[k] += 1;
                    break;
                }
                fv[k] = 0;
                k += 1;
            }
            if k == MAX_FREE {
                break;
            }
        }
        if s == 0 {
            return false;
        }
        s = (s - 1) & mask;
    }
}

// ── Elements and pairs ───────────────────────────────────────────────

/// A basis element: its signature `sig_m · e_idx`, square-free, and its
/// terms, the columns `pos` of a column list it may share with others.
struct SElem {
    sig: PSig,
    lm: Mono,
    cols: Arc<[Mono]>,
    pos: Vec<u32>,
    vals: Vec<u32>,
}

impl SElem {
    fn terms(&self) -> impl Iterator<Item = (Mono, u32)> + '_ {
        self.pos
            .iter()
            .zip(&self.vals)
            .map(|(&c, &v)| (self.cols[c as usize], v))
    }

    fn to_rpoly(&self) -> RPoly {
        let (monos, coefs) = self.terms().unzip();
        RPoly { monos, coefs }
    }
}

#[derive(Clone, Copy, Debug)]
enum Source {
    /// Input `i`, signature `e_i`.
    Gen(u32),
    /// The larger half `t·g` of a critical pair.
    Crit(Mono, u32),
    /// `y_v·g`, the pair of `g` with `T_v`.
    Tower(u32, u8),
}

#[derive(Clone, Copy, Debug)]
struct Pair {
    sig: PSig,
    src: Source,
    /// `deg t + deg LM(g)`: the lcm degree of a critical pair, `deg LM + 1`
    /// for a tower pair, the input's degree for a generator.
    nominal: u32,
}

