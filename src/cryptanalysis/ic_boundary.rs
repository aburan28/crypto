/// What building a table cost, folded into the factor-base phase of
/// every variant that probes it.
#[derive(Clone, Debug, Default)]
pub struct TableCost {
    pub kind: &'static str,
    pub entries: u64,
    pub group_ops: GroupOps,
    pub wall_ns: u64,
    /// Native counters of the build besides additions.
    pub native: Vec<(&'static str, u64)>,
}

/// A table of all pair sums of a base, keyed by the sum's abscissa so
/// `S` and `−S` share one entry; the probe checks which it found.
pub struct PairTable {
    map: FastMap<(u32, u32)>,
    /// `full` (every `i ≤ j`) or `negation_folded` (one pair per orbit
    /// under negation).
    pub kind: &'static str,
    pub entries: u64,
    pub build_ops: GroupOps,
    pub build_wall_ns: u64,
}

impl PairTable {
    pub fn build<G: CountedGroup>(g: &G, fb: &FactorBase<G::Elt>) -> Self {
        let start = Instant::now();
        let n = fb.points.len();
        let mut ops = GroupOps::default();
        let mut map: FastMap<(u32, u32)> = fast_map(n * (n + 1) / 4 + 1);
        for i in 0..n {
            for j in i..n {
                let s = g.add(&mut ops, fb.points[i], fb.points[j]);
                if g.is_identity(&s) {
                    continue;
                }
                map.entry(g.key(&s) >> 1).or_insert((i as u32, j as u32));
            }
        }
        Self {
            kind: "full",
            entries: map.len() as u64,
            map,
            build_ops: ops,
            build_wall_ns: start.elapsed().as_nanos() as u64,
        }
    }

    /// **The same table with the negation folded out of the build.**  The
    /// key is the abscissa of the sum, which `{P, Q}` and `{−P, −Q}` share,
    /// so half of the full build's additions made entries the map already
    /// held.  One pair per orbit under negation: the first point above
    /// each abscissa against every signed point above a later abscissa,
    /// plus its own double.  About `|F|²/4` additions instead of
    /// `|F|²/2`; the probe is unchanged.
    pub fn build_negation_folded<G: CountedGroup>(g: &G, fb: &FactorBase<G::Elt>) -> Self {
        let start = Instant::now();
        let mut ops = GroupOps::default();
        let groups: Vec<&Vec<usize>> = fb
            .abscissa_list
            .iter()
            .map(|x| fb.x_index.get(x).expect("every listed abscissa is indexed"))
            .collect();
        let a = groups.len();
        let mut map: FastMap<(u32, u32)> = fast_map(a * a + 1);
        for ai in 0..a {
            let i = groups[ai][0];
            for group in groups.iter().skip(ai) {
                for &j in group.iter() {
                    let s = g.add(&mut ops, fb.points[i], fb.points[j]);
                    if g.is_identity(&s) {
                        continue;
                    }
                    map.entry(g.key(&s) >> 1).or_insert((i as u32, j as u32));
                }
            }
        }
        Self {
            kind: "negation_folded",
            entries: map.len() as u64,
            map,
            build_ops: ops,
            build_wall_ns: start.elapsed().as_nanos() as u64,
        }
    }

    pub fn cost(&self) -> TableCost {
        TableCost {
            kind: self.kind,
            entries: self.entries,
            group_ops: self.build_ops,
            wall_ns: self.build_wall_ns,
            native: Vec::new(),
        }
    }

    /// Indices `(i, j)` with `P_i + P_j = target`, if the table holds a
    /// pair summing to `±target`; one probe, at most one addition.
    pub fn probe<G: CountedGroup>(
        &self,
        g: &G,
        fb: &FactorBase<G::Elt>,
        ops: &mut GroupOps,
        lookups: &mut u64,
        target: G::Elt,
    ) -> Option<(usize, usize)> {
        *lookups += 1;
        let &(i, j) = self.map.get(&(g.key(&target) >> 1))?;
        let (i, j) = (i as usize, j as usize);
        let s = g.add(ops, fb.points[i], fb.points[j]);
        if s == target {
            Some((i, j))
        } else if s == g.neg(target) {
            Some((fb.neg_index[i], fb.neg_index[j]))
        } else {
            None
        }
    }

    pub fn calibrate_lookup(&self, samples: u64) -> f64 {
        let mut rng = StdRng::seed_from_u64(7);
        let keys: Vec<u64> = (0..1024).map(|_| rng.gen::<u64>() >> 1).collect();
        let start = Instant::now();
        let mut hits = 0u64;
        for i in 0..samples {
            if self.map.contains_key(&keys[(i % 1024) as usize]) {
                hits += 1;
            }
        }
        let ns = start.elapsed().as_nanos() as f64 / samples as f64;
        std::hint::black_box(hits);
        ns
    }
}

/// Bits of a table entry that hold the second index; the rotation that
/// canonicalised the entry's sum sits above them.
const FROB_INDEX_BITS: u32 = 26;

/// **A pair table folded by the Frobenius as well as by negation**
/// (Koblitz).  One entry per pair `{P, Q}` up to the group generated by
/// `σ` and `−1`, keyed by the normal-basis canonical form of the sum's
/// abscissa ([`FrobeniusCanon`]): `σ^t(P) + σ^t(Q) = σ^t(P + Q)` for
/// every `t`, and `±` share an abscissa, so all `2n` images of a pair
/// share one entry.  About `|F|²/(4n)` additions and entries instead of
/// the full table's `|F|²/2`.
///
/// A probe canonicalises the target's abscissa once; the entry's shift
/// and the target's give the rotation `t` outright; the summands
/// `σ^t(P)`, `σ^t(Q)` are read from a per-point orbit index built once;
/// one addition confirms `±R`.  The canonicalisations are counted in
/// their own unit and converted at a measured factor, like every other
/// non-addition.
pub struct FrobeniusPairTable {
    map: FastMap<(u32, u32)>,
    canon: FrobeniusCanon,
    /// `member_of[i·n + t]`: the base index of `σ^t(P_i)`.
    member_of: Vec<u32>,
    n: u32,
    pub entries: u64,
    pub representatives: u64,
    pub build_ops: GroupOps,
    pub build_wall_ns: u64,
    pub build_canonicalisations: u64,
    pub build_frobenius_maps: u64,
    pub build_lookups: u64,
}

impl FrobeniusPairTable {
    /// `None` when the base is not closed under the Frobenius, has more
    /// than `2^26` points, or the field yields no normal basis.
    pub fn build(inst: &BinaryInstance, fb: &FactorBase<FastPoint>) -> Option<Self> {
        let start = Instant::now();
        let g = BinaryGroup(&inst.fast);
        let n = inst.n as usize;
        let f = fb.points.len();
        if f >= (1usize << FROB_INDEX_BITS) {
            return None;
        }
        let canon = FrobeniusCanon::new(&inst.gf, inst.n)?;
        let mut member_of = vec![0u32; f * n];
        let (mut frob, mut lookups) = (0u64, 0u64);
        for i in 0..f {
            let mut p = fb.points[i];
            member_of[i * n] = i as u32;
            for t in 1..n {
                p = inst.fast.frobenius_k(p, 1);
                frob += 1;
                lookups += 1;
                let idx = *fb.point_index.get(&p.pack())?;
                member_of[i * n + t] = idx as u32;
            }
        }
        // One representative per column, the first point of it: any
        // member of a signed orbit serves, the orbit being its own
        // ⟨σ, −1⟩-image.
        let mut rep_of_col = vec![usize::MAX; fb.columns];
        for i in 0..f {
            let c = fb.col_of[i];
            if rep_of_col[c] == usize::MAX {
                rep_of_col[c] = i;
            }
        }
        let mut ops = GroupOps::default();
        let mut canons = 0u64;
        let mut map: FastMap<(u32, u32)> = fast_map(f * f / (4 * n) + 1);
        for (col, &rep) in rep_of_col.iter().enumerate() {
            if rep == usize::MAX {
                continue;
            }
            for j in 0..f {
                if fb.col_of[j] < col {
                    continue;
                }
                let u = g.add(&mut ops, fb.points[rep], fb.points[j]);
                if g.is_identity(&u) {
                    continue;
                }
                canons += 1;
                let (key, t_u) = canon.canon_with_shift(u.x);
                map.entry(key)
                    .or_insert((rep as u32, (j as u32) | (t_u << FROB_INDEX_BITS)));
            }
        }
        Some(Self {
            entries: map.len() as u64,
            representatives: rep_of_col.iter().filter(|&&r| r != usize::MAX).count() as u64,
            map,
            canon,
            member_of,
            n: inst.n,
            build_ops: ops,
            build_wall_ns: start.elapsed().as_nanos() as u64,
            build_canonicalisations: canons,
            build_frobenius_maps: frob,
            build_lookups: lookups,
        })
    }

    /// Indices `(i, j)` with `P_i + P_j = target`, if some `⟨σ, −1⟩`-image
    /// of a stored pair sums to `±target`: one canonicalisation, one
    /// probe, one addition.
    pub fn probe(
        &self,
        g: &BinaryGroup,
        fb: &FactorBase<FastPoint>,
        ops: &mut GroupOps,
        ctr: &mut OracleCounters,
        target: FastPoint,
    ) -> Option<(usize, usize)> {
        ctr.canonicalisations += 1;
        let (key, t_r) = self.canon.canon_with_shift(target.x);
        ctr.lookups += 1;
        let &(i, packed) = self.map.get(&key)?;
        let n = self.n;
        let j = (packed & ((1u32 << FROB_INDEX_BITS) - 1)) as usize;
        let t_u = packed >> FROB_INDEX_BITS;
        // canon = rotl^{t_u}(coords(x_u)) = rotl^{t_r}(coords(x_R)) and the
        // Frobenius is rotl by one, so x_R = σ^t(x_u) with t = t_u − t_r.
        let t = ((t_u + n - t_r) % n) as usize;
        let i2 = self.member_of[i as usize * n as usize + t] as usize;
        let j2 = self.member_of[j * n as usize + t] as usize;
        let s = g.add(ops, fb.points[i2], fb.points[j2]);
        if s == target {
            Some((i2, j2))
        } else if s == g.neg(target) {
            Some((fb.neg_index[i2], fb.neg_index[j2]))
        } else {
            ctr.frobfold_mismatches += 1;
            None
        }
    }

    pub fn calibrate_lookup(&self, samples: u64) -> f64 {
        let mut rng = StdRng::seed_from_u64(7);
        let mask = (1u64 << self.n) - 1;
        let keys: Vec<u64> = (0..1024).map(|_| rng.gen::<u64>() & mask).collect();
        let start = Instant::now();
        let mut hits = 0u64;
        for i in 0..samples {
            if self.map.contains_key(&keys[(i % 1024) as usize]) {
                hits += 1;
            }
        }
        let ns = start.elapsed().as_nanos() as f64 / samples as f64;
        std::hint::black_box(hits);
        ns
    }

    /// Nanoseconds per canonicalisation with shift, on random abscissae.
    pub fn calibrate_canon(&self, samples: u64) -> f64 {
        let mut rng = StdRng::seed_from_u64(9);
        let mask = (1u64 << self.n) - 1;
        let xs: Vec<u64> = (0..1024).map(|_| rng.gen::<u64>() & mask).collect();
        let start = Instant::now();
        let mut acc = 0u64;
        for i in 0..samples {
            let (c, t) = self.canon.canon_with_shift(xs[(i % 1024) as usize]);
            acc ^= c.wrapping_add(t as u64);
        }
        let ns = start.elapsed().as_nanos() as f64 / samples as f64;
        std::hint::black_box(acc);
        ns
    }

    pub fn cost(&self) -> TableCost {
        TableCost {
            kind: "frobenius_folded",
            entries: self.entries,
            group_ops: self.build_ops,
            wall_ns: self.build_wall_ns,
            native: vec![
                ("canonicalisations", self.build_canonicalisations),
                ("frobenius_maps", self.build_frobenius_maps),
                ("lookups", self.build_lookups),
                ("pair_table_representatives", self.representatives),
            ],
        }
    }
}

/// Which decomposition oracle a variant uses.
pub enum Oracle<'a> {
    /// Semaev `S₃` as a quadratic in the second abscissa: one square
    /// root per base abscissa per target (`m = 2`, prime).
    SemaevS3Roots,
    /// `R − P_i ∈ F` for every signed base point (`m = 2`).
    Subtract,
    /// Meet in the middle: a pair table probed once per target (`m = 2`)
    /// or once per `R − P_i` (`m = 3`).
    Mitm { table: &'a PairTable, m: u32 },
    /// Meet in the middle on the Frobenius-folded table (Koblitz).
    MitmFrobenius { table: &'a FrobeniusPairTable, m: u32 },
    /// Semaev `S₄` pairs-and-solve over a subspace (`m = 3`, binary).
    SemaevS4 { oracle: &'a SubspaceOracle },
}

impl Oracle<'_> {
    pub fn name(&self) -> String {
        match self {
            Oracle::SemaevS3Roots => "semaev_s3_roots".into(),
            Oracle::Subtract => "direct_subtraction".into(),
            Oracle::Mitm { m, .. } => format!("meet_in_the_middle_m{m}"),
            Oracle::MitmFrobenius { m, .. } => format!("meet_in_the_middle_m{m}_frobenius_folded"),
            Oracle::SemaevS4 { .. } => "semaev_s4_pairs_and_solve".into(),
        }
    }
    pub fn summands(&self) -> u32 {
        match self {
            Oracle::SemaevS3Roots | Oracle::Subtract => 2,
            Oracle::Mitm { m, .. } | Oracle::MitmFrobenius { m, .. } => *m,
            Oracle::SemaevS4 { .. } => 3,
        }
    }
    /// The table this oracle probes, as a cost to fold into the
    /// factor-base phase.
    pub fn table_cost(&self) -> Option<TableCost> {
        match self {
            Oracle::Mitm { table, .. } => Some(table.cost()),
            Oracle::MitmFrobenius { table, .. } => Some(table.cost()),
            _ => None,
        }
    }
}

/// Native counters of the oracle, per phase.
#[derive(Clone, Copy, Debug, Default)]
pub struct OracleCounters {
    pub lookups: u64,
    pub sqrt_solves: u64,
    pub inversions: u64,
    pub s4_pairs: u64,
    pub s4_hits: u64,
    pub lift_failures: u64,
    /// Frobenius-orbit canonicalisations of a target abscissa.
    pub canonicalisations: u64,
    /// Folded-table hits whose recovered pair summed to neither `±R`;
    /// a rotation-direction bug would show here, so it must stay zero.
    pub frobfold_mismatches: u64,
}

/// Resolve the signs of a witness of abscissae: which points above them
/// sum to the target.  Costs at most `2·2^m` additions.  `None` when no
/// choice of signs sums to the target, or when an abscissa has no point
/// in the base: the witness does not lift, and a pipeline must not turn
/// it into a relation.
pub(crate) fn lift_abscissae<G: CountedGroup>(
    g: &G,
    fb: &FactorBase<G::Elt>,
    ops: &mut GroupOps,
    xs: &[u64],
    target: G::Elt,
) -> Option<Vec<usize>> {
    let mut choices: Vec<&Vec<usize>> = Vec::with_capacity(xs.len());
    for x in xs {
        choices.push(fb.x_index.get(x)?);
    }
    let mut current = vec![0usize; xs.len()];
    loop {
        let mut acc = g.identity();
        for (k, &c) in current.iter().enumerate() {
            acc = g.add(ops, acc, fb.points[choices[k][c]]);
        }
        if acc == target {
            return Some(current.iter().enumerate().map(|(k, &c)| choices[k][c]).collect());
        }
        // Next combination.
        let mut k = 0;
        loop {
            if k == current.len() {
                return None;
            }
            current[k] += 1;
            if current[k] < choices[k].len() {
                break;
            }
            current[k] = 0;
            k += 1;
        }
    }
}

/// Run one oracle on one target: indices of a decomposition, or `None`.
fn decompose_prime(
    curve: &PrimeCurve,
    fb: &FactorBase<PrimePoint>,
    oracle: &Oracle,
    ops: &mut GroupOps,
    ctr: &mut OracleCounters,
    target: PrimePoint,
) -> Option<Vec<usize>> {
    match oracle {
        Oracle::SemaevS3Roots => {
            let p = curve.p;
            let xr = target.x;
            for &xi in &fb.abscissa_list {
                let (qa, qb, qc) = semaev_s3_quadratic(curve, xr, xi);
                let mut candidates: [u64; 2] = [u64::MAX; 2];
                if qa == 0 {
                    if qb == 0 {
                        continue;
                    }
                    ctr.inversions += 1;
                    let Some(inv) = invmod(qb, p) else {
                        continue;
                    };
                    candidates[0] = mulmod(submod(0, qc, p), inv, p);
                } else {
                    let disc = submod(
                        mulmod(qb, qb, p),
                        mulmod(4, mulmod(qa, qc, p), p),
                        p,
                    );
                    ctr.sqrt_solves += 1;
                    let Some(s) = curve.sqrt(disc) else {
                        continue;
                    };
                    ctr.inversions += 1;
                    let Some(inv) = invmod(mulmod(2, qa, p), p) else {
                        continue;
                    };
                    candidates[0] = mulmod(addmod(submod(0, qb, p), s, p), inv, p);
                    candidates[1] = mulmod(submod(submod(0, qb, p), s, p), inv, p);
                }
                for xj in candidates {
                    if xj == u64::MAX {
                        continue;
                    }
                    if !fb.x_index.contains_key(&xj) {
                        continue;
                    }
                    ctr.lookups += 1;
                    if let Some(w) = lift_abscissae(curve, fb, ops, &[xi, xj], target) {
                        return Some(w);
                    }
                    ctr.lift_failures += 1;
                }
            }
            None
        }
        Oracle::Subtract => {
            for i in 0..fb.points.len() {
                let s = curve.add(ops, target, curve.neg(fb.points[i]));
                ctr.lookups += 1;
                if let Some(&j) = fb.point_index.get(&curve.key(&s)) {
                    return Some(vec![i, j]);
                }
            }
            None
        }
        Oracle::Mitm { table, m } => decompose_mitm(curve, fb, table, *m, ops, ctr, target),
        Oracle::MitmFrobenius { .. } | Oracle::SemaevS4 { .. } => None,
    }
}

/// Meet in the middle on a built pair table: one probe for `m = 2`,
/// one `R − P_i` and probe per signed base point for `m = 3`.
pub fn decompose_mitm<G: CountedGroup>(
    g: &G,
    fb: &FactorBase<G::Elt>,
    table: &PairTable,
    m: u32,
    ops: &mut GroupOps,
    ctr: &mut OracleCounters,
    target: G::Elt,
) -> Option<Vec<usize>> {
    match m {
        2 => table
            .probe(g, fb, ops, &mut ctr.lookups, target)
            .map(|(i, j)| vec![i, j]),
        3 => {
            for i in 0..fb.points.len() {
                let s = g.add(ops, target, g.neg(fb.points[i]));
                if g.is_identity(&s) {
                    continue;
                }
                if let Some((j, k)) = table.probe(g, fb, ops, &mut ctr.lookups, s) {
                    return Some(vec![i, j, k]);
                }
            }
            None
        }
        _ => None,
    }
}

/// Meet in the middle on the Frobenius-folded table: the same loop as
/// [`decompose_mitm`] with the folded probe.
pub fn decompose_mitm_frobenius(
    g: &BinaryGroup,
    fb: &FactorBase<FastPoint>,
    table: &FrobeniusPairTable,
    m: u32,
    ops: &mut GroupOps,
    ctr: &mut OracleCounters,
    target: FastPoint,
) -> Option<Vec<usize>> {
    match m {
        2 => table.probe(g, fb, ops, ctr, target).map(|(i, j)| vec![i, j]),
        3 => {
            for i in 0..fb.points.len() {
                let s = g.add(ops, target, g.neg(fb.points[i]));
                if g.is_identity(&s) {
                    continue;
                }
                if let Some((j, k)) = table.probe(g, fb, ops, ctr, s) {
                    return Some(vec![i, j, k]);
                }
            }
            None
        }
        _ => None,
    }
}

fn decompose_binary(
    inst: &BinaryInstance,
    fb: &FactorBase<FastPoint>,
    oracle: &Oracle,
    ops: &mut GroupOps,
    ctr: &mut OracleCounters,
    target: FastPoint,
) -> Option<Vec<usize>> {
    let g = BinaryGroup(&inst.fast);
    match oracle {
        Oracle::Mitm { table, m } => decompose_mitm(&g, fb, table, *m, ops, ctr, target),
        Oracle::MitmFrobenius { table, m } => {
            decompose_mitm_frobenius(&g, fb, table, *m, ops, ctr, target)
        }
        Oracle::Subtract => {
            for i in 0..fb.points.len() {
                let s = g.add(ops, target, g.neg(fb.points[i]));
                ctr.lookups += 1;
                if let Some(&j) = fb.point_index.get(&s.pack()) {
                    return Some(vec![i, j]);
                }
            }
            None
        }
        Oracle::SemaevS4 { oracle } => {
            let (witness, pairs) = oracle.decompose(target.x, &inst.gf);
            ctr.s4_pairs += pairs;
            let xs = witness?;
            ctr.s4_hits += 1;
            match lift_abscissae(&g, fb, ops, &xs, target) {
                Some(w) => Some(w),
                None => {
                    ctr.lift_failures += 1;
                    None
                }
            }
        }
        Oracle::SemaevS3Roots => None,
    }
}

// ── The relation loop ──────────────────────────────────────────────

/// What the shared loop returns.
pub struct PipelineOutcome {
    pub relations: PhaseCost,
    pub linear_algebra: PhaseCost,
    pub verify: PhaseCost,
    pub trials: u64,
    pub relations_found: u64,
    pub independent: u64,
    pub dependent: u64,
    pub rank: u64,
    pub recovered: Option<u64>,
    pub verified: bool,
    pub counters: OracleCounters,
}

/// How the relation loop draws its targets.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum TargetSource {
    /// `R = [a]G + [b]Q` with fresh random `a, b` every trial: two
    /// scalar multiplications and one addition per target.
    Random,
    /// An r-adding walk `R ← R + J_{h(R)}` over 16 jumps
    /// `J_j = [a_j]G + [b_j]Q` with the coefficients tracked modulo `r`:
    /// one addition per target after the jumps are set up.  A segment
    /// guard (one hash insert per step, counted and priced as a lookup)
    /// restarts the walk from a fresh random point when it meets itself,
    /// and after `4√r + 2^16` steps regardless, so a target is never
    /// presented twice within a segment.
    Walk,
}

impl TargetSource {
    pub fn name(&self) -> &'static str {
        match self {
            TargetSource::Random => "random",
            TargetSource::Walk => "walk",
        }
    }
}

/// Draw the targets (`[a]G + [b]Q` per trial, or a walk), ask the
/// oracle, turn a decomposition into a row, and stop the moment the
/// elimination pins the logarithm.
#[allow(clippy::too_many_arguments)]
fn collect_and_solve<G: CountedGroup>(
    g: &G,
    generator: G::Elt,
    target: G::Elt,
    r: u64,
    h: u64,
    fb: &FactorBase<G::Elt>,
    seed: u64,
    max_trials: u64,
    targets: TargetSource,
    mut oracle: impl FnMut(&mut GroupOps, &mut OracleCounters, G::Elt) -> Option<Vec<usize>>,
) -> PipelineOutcome {
    let mut rng = StdRng::seed_from_u64(seed ^ 0x5245_4C41_5449_4F4E);
    let mut rel = PhaseCost::default();
    let mut la = PhaseCost::default();
    let mut ver = PhaseCost::default();
    let mut ctr = OracleCounters::default();
    let cols = fb.columns + 1;
    let d_col = fb.columns;
    let mut gauss = IncrementalGauss::new(cols, r);
    let mut trials = 0u64;
    let mut found = 0u64;
    let mut recovered = None;
    let mut verified = false;
    let rel_start = Instant::now();
    let mut la_ns = 0u64;
    let h_mod = h % r;
    let mut direct_skipped = 0u64;

    // The walk: jumps with known coefficients, the current point with
    // its coefficients, and the segment guard.
    let jump_count = 16usize;
    let mut jumps: Vec<(G::Elt, u64, u64)> = Vec::new();
    let mut walk_point = g.identity();
    let (mut wa, mut wb) = (0u64, 0u64);
    let mut walk_fresh = true;
    let segment_cap = ((r as f64).sqrt() * 4.0) as usize + 65_536;
    let mut seen: FastMap<()> = fast_map(0);
    let (mut walk_steps, mut walk_restarts, mut walk_cycles, mut guard_probes) = (0u64, 0u64, 0u64, 0u64);
    if targets == TargetSource::Walk {
        for _ in 0..jump_count {
            let aj = rng.gen_range(1..r);
            let bj = rng.gen_range(1..r);
            let ag = g.mul(&mut rel.group_ops, generator, aj);
            let bq = g.mul(&mut rel.group_ops, target, bj);
            jumps.push((g.add(&mut rel.group_ops, ag, bq), aj, bj));
        }
        seen = fast_map(segment_cap.min(1 << 22));
    }

    while trials < max_trials {
        let (point, a, b) = match targets {
            TargetSource::Random => {
                trials += 1;
                let a = rng.gen_range(1..r);
                let b = rng.gen_range(1..r);
                let ag = g.mul(&mut rel.group_ops, generator, a);
                let bq = g.mul(&mut rel.group_ops, target, b);
                let point = g.add(&mut rel.group_ops, ag, bq);
                if g.is_identity(&point) {
                    direct_skipped += 1;
                    continue;
                }
                (point, a, b)
            }
            TargetSource::Walk => {
                if walk_fresh || seen.len() >= segment_cap {
                    wa = rng.gen_range(1..r);
                    wb = rng.gen_range(1..r);
                    let ag = g.mul(&mut rel.group_ops, generator, wa);
                    let bq = g.mul(&mut rel.group_ops, target, wb);
                    walk_point = g.add(&mut rel.group_ops, ag, bq);
                    walk_fresh = false;
                    walk_restarts += 1;
                    seen.clear();
                } else {
                    let hsh = mix(g.key(&walk_point));
                    let j = ((hsh >> 24) % jump_count as u64) as usize;
                    let (jp, aj, bj) = jumps[j];
                    walk_point = g.add(&mut rel.group_ops, walk_point, jp);
                    wa = addmod(wa, aj, r);
                    wb = addmod(wb, bj, r);
                    walk_steps += 1;
                }
                if g.is_identity(&walk_point) {
                    walk_fresh = true;
                    direct_skipped += 1;
                    continue;
                }
                guard_probes += 1;
                if seen.insert(g.key(&walk_point), ()).is_some() {
                    walk_cycles += 1;
                    walk_fresh = true;
                    continue;
                }
                trials += 1;
                (walk_point, wa, wb)
            }
        };
        let Some(summands) = oracle(&mut rel.group_ops, &mut ctr, point) else {
            continue;
        };
        found += 1;
        let la_start = Instant::now();
        let mut row = vec![0u64; cols];
        for &i in &summands {
            let c = fb.col_of[i];
            row[c] = addmod(row[c], fb.coef_of[i], r);
        }
        // h·a + h·b·d = Σ coef·x  ⇒  Σ coef·x − h·b·d = h·a
        row[d_col] = submod(0, mulmod(h_mod, b, r), r);
        let rhs = mulmod(h_mod, a, r);
        match gauss.add_row(row, rhs) {
            RowStatus::Inconsistent => {
                la_ns += la_start.elapsed().as_nanos() as u64;
                la.count("inconsistent", 1);
                break;
            }
            RowStatus::Dependent => {}
            RowStatus::Independent => {}
        }
        if let Some(d) = gauss.pinned(d_col) {
            la_ns += la_start.elapsed().as_nanos() as u64;
            let v_start = Instant::now();
            let check = g.mul(&mut ver.group_ops, generator, d);
            ver.wall_ns = v_start.elapsed().as_nanos() as u64;
            if check == target {
                recovered = Some(d);
                verified = true;
                break;
            }
            ver.count("verification_failures", 1);
            break;
        }
        la_ns += la_start.elapsed().as_nanos() as u64;
    }
    rel.wall_ns = rel_start.elapsed().as_nanos() as u64 - la_ns - ver.wall_ns;
    rel.count("trials", trials);
    rel.count("relations", found);
    rel.count("lookups", ctr.lookups);
    rel.count("sqrt_solves", ctr.sqrt_solves);
    rel.count("inversions", ctr.inversions);
    rel.count("s4_pairs", ctr.s4_pairs);
    rel.count("s4_hits", ctr.s4_hits);
    rel.count("lift_failures", ctr.lift_failures);
    rel.count("canonicalisations", ctr.canonicalisations);
    rel.count("frobfold_mismatches", ctr.frobfold_mismatches);
    rel.count("direct_relations_skipped", direct_skipped);
    if targets == TargetSource::Walk {
        rel.count("walk_jumps", jump_count as u64);
        rel.count("walk_steps", walk_steps);
        rel.count("walk_restarts", walk_restarts);
        rel.count("walk_cycles", walk_cycles);
        rel.count("walk_guard_probes", guard_probes);
    }
    la.wall_ns = la_ns;
    la.count("row_ops", gauss.row_ops);
    la.count("rows", found);
    la.count("columns", cols as u64);
    la.count("rank", gauss.rank() as u64);
    PipelineOutcome {
        relations: rel,
        linear_algebra: la,
        verify: ver,
        trials,
        relations_found: found,
        independent: gauss.rank() as u64,
        dependent: gauss.dependent,
        rank: gauss.rank() as u64,
        recovered,
        verified,
        counters: ctr,
    }
}

// ── Calibration ────────────────────────────────────────────────────

fn calibrate_group<G: CountedGroup>(g: &G, points: &[G::Elt], calib: &mut Calibration) {
    let mut ops = GroupOps::default();
    let n = points.len();
    let samples = 200_000u64;
    let mut acc = points[0];
    let start = Instant::now();
    for i in 0..samples {
        acc = g.add(&mut ops, acc, points[(i as usize * 7 + 1) % n]);
        if g.is_identity(&acc) {
            acc = points[(i as usize + 3) % n];
        }
    }
    calib.ns_per_add = start.elapsed().as_nanos() as f64 / samples as f64;
    std::hint::black_box(acc);
    let mut acc = points[1];
    let start = Instant::now();
    for i in 0..samples {
        acc = g.double(&mut ops, acc);
        if g.is_identity(&acc) {
            acc = points[(i as usize + 5) % n];
        }
    }
    calib.ns_per_double = start.elapsed().as_nanos() as f64 / samples as f64;
    std::hint::black_box(acc);
}

fn calibrate_row_ops(modulus: u64, calib: &mut Calibration) {
    let mut rng = StdRng::seed_from_u64(11);
    let cols = 2048usize;
    let pivot: Vec<u64> = (0..cols).map(|_| rng.gen_range(0..modulus)).collect();
    let mut row: Vec<u64> = (0..cols).map(|_| rng.gen_range(0..modulus)).collect();
    let reps = 500u64;
    let start = Instant::now();
    for k in 0..reps {
        let f = (k + 3) % modulus;
        for j in 0..cols {
            row[j] = submod(row[j], mulmod(f, pivot[j], modulus), modulus);
        }
    }
    calib.ns_per_row_op = start.elapsed().as_nanos() as f64 / (reps * cols as u64) as f64;
    std::hint::black_box(&row);
}

/// A 64-bit word XOR of one row into another, the unit of the Boolean
/// Macaulay elimination.
pub fn calibrate_word_xor() -> f64 {
    let words = 4096usize;
    let mut a: Vec<u64> = (0..words as u64).map(mix).collect();
    let b: Vec<u64> = (0..words as u64).map(|i| mix(i + 77)).collect();
    let reps = 2000u64;
    let start = Instant::now();
    for k in 0..reps {
        let shift = (k % 7) as usize;
        for j in 0..words {
            a[j] ^= b[(j + shift) % words];
        }
    }
    let ns = start.elapsed().as_nanos() as f64 / (reps * words as u64) as f64;
    std::hint::black_box(&a);
    ns
}

// ── Pricing a run ──────────────────────────────────────────────────

fn price_phase(phase: &mut PhaseCost, calib: &Calibration) {
    let mut gae = phase.group_ops.gae();
    let conv = |name: &str, ns: Option<f64>| -> f64 {
        match ns {
            Some(ns) => calib.gae(phase.get(name), ns),
            None => 0.0,
        }
    };
    gae += conv("sqrt_solves", calib.ns_per_sqrt);
    gae += conv("as_solves", calib.ns_per_as_solve);
    gae += conv("s4_pairs", calib.ns_per_s4_pair);
    gae += conv("lookups", Some(calib.ns_per_lookup));
    gae += conv("row_ops", Some(calib.ns_per_row_op));
    gae += conv("legendre_symbols", calib.ns_per_legendre);
    gae += conv("inversions", calib.ns_per_inversion);
    gae += conv("frobenius_maps", calib.ns_per_frobenius);
    gae += conv("canonicalisations", calib.ns_per_canon);
    gae += conv("walk_guard_probes", Some(calib.ns_per_lookup));
    phase.gae = gae;
}

/// The exact ceiling for one base and summand count, computed once and
/// handed to every variant on that base: `(classes, ceiling)`, or
/// `None` when the classes could not be enumerated.
pub type ExactCeiling = Option<(u64, f64)>;

#[allow(clippy::too_many_arguments)]
fn assemble_variant(
    name: &str,
    oracle_name: String,
    summands: u32,
    targets: TargetSource,
    fb_cost: &PhaseCost,
    signed_points: u64,
    abscissae: u64,
    columns: u64,
    dimension: Option<u32>,
    table: Option<TableCost>,
    exact: ExactCeiling,
    outcome: PipelineOutcome,
    r: u64,
    space: f64,
    calib: &Calibration,
    rho_s: f64,
    floor_s: f64,
) -> VariantResult {
    let mut fb_phase = fb_cost.clone();
    let table_kind = match &table {
        Some(t) => t.kind,
        None => "none",
    };
    if let Some(t) = table {
        fb_phase.group_ops.merge(t.group_ops);
        fb_phase.wall_ns += t.wall_ns;
        fb_phase.count("pair_table_entries", t.entries);
        for (name, by) in t.native {
            fb_phase.count(name, by);
        }
    }
    price_phase(&mut fb_phase, calib);
    let mut rel = outcome.relations;
    price_phase(&mut rel, calib);
    let mut la = outcome.linear_algebra;
    price_phase(&mut la, calib);
    let mut ver = outcome.verify;
    price_phase(&mut ver, calib);
    let total_gae = fb_phase.gae + rel.gae + la.gae + ver.gae;
    let total_wall = fb_phase.wall_ns + rel.wall_ns + la.wall_ns + ver.wall_ns;
    let sqrt_r = (r as f64).sqrt();
    let s = total_gae / sqrt_r;
    let s_wall = if calib.ns_per_add > 0.0 {
        total_wall as f64 / calib.ns_per_add / sqrt_r
    } else {
        f64::NAN
    };
    let tf = trials_floor(columns, signed_points, summands, space);
    let p_ceiling = decomposition_probability_ceiling(signed_points, summands, space);
    let measured_yield = outcome.relations_found as f64 / outcome.trials.max(1) as f64;
    let (classes, p_exact) = exact.unwrap_or((0, p_ceiling));
    let tf_exact = (columns as f64 + 1.0) / p_exact;
    VariantResult {
        name: name.to_string(),
        oracle: oracle_name,
        summands,
        table: table_kind.to_string(),
        targets: targets.name().to_string(),
        factor_base: fb_phase,
        signed_points,
        abscissae,
        columns,
        dimension,
        relations: rel,
        linear_algebra: la,
        verify: ver,
        trials: outcome.trials,
        relations_found: outcome.relations_found,
        independent: outcome.independent,
        dependent: outcome.dependent,
        rank: outcome.rank,
        trials_floor: tf,
        trials_over_floor: outcome.trials as f64 / tf,
        decomposition_probability_ceiling: p_ceiling,
        yield_over_ceiling: measured_yield / p_ceiling,
        cofactor_classes: classes,
        decomposition_probability_ceiling_exact: p_exact,
        yield_over_ceiling_exact: measured_yield / p_exact,
        trials_floor_exact: tf_exact,
        trials_over_floor_exact: outcome.trials as f64 / tf_exact,
        total_gae,
        total_wall_ns: total_wall,
        s,
        s_wall,
        ratio_to_rho: s / rho_s,
        ratio_to_floor: s / floor_s,
        recovered: outcome.recovered,
        verified: outcome.verified,
    }
}

// ── Configuration ──────────────────────────────────────────────────

/// What to run.
#[derive(Clone, Debug, Serialize)]
pub struct BoundaryConfig {
    pub seed: u64,
    /// Repeats per instance (fresh target each; rho and every variant
    /// see the same target within a repeat).
    pub repeats: usize,
    /// Rho walks per repeat on that target (different walk seeds).  The
    /// reference is cheap and its single-run spread is about half its
    /// mean, so it gets more samples than the variants.
    pub rho_repeats: usize,
    pub prime_bits: Vec<u32>,
    pub char2_degrees: Vec<u32>,
    pub koblitz_degrees: Vec<u32>,
    /// Cap on targets drawn per variant run.
    pub max_trials: u64,
    /// A run also stops after this multiple of the counting floor's
    /// trial count (never fewer than 4096 trials), so a base that cannot
    /// yield relations fails in bounded time instead of at the cap.
    pub trial_floor_multiple: f64,
    /// Largest Koblitz degree at which the un-folded control (one column
    /// per abscissa) is run; it needs `2n` times the relations.
    pub koblitz_no_fold_max_degree: u32,
    /// Largest degree at which the `S₄` pairs-and-solve oracle is run.
    pub s4_max_degree: u32,
    /// Largest base the pair table may hold (signed points).
    pub max_table_points: usize,
    /// Rho step cap as a multiple of the expected count.
    pub rho_cap_multiple: f64,
    /// Largest Frobenius-folded table (entries) the balanced Koblitz base
    /// may need; the base is sized to `1.2·(4#E)^{1/3}` signed points
    /// within it, and run only where that is at least half again the
    /// first-round base.
    pub max_folded_table_pairs: u64,
    /// Run a two-summand row on a binary base when it is admissible and
    /// its exact trials floor is at most `max_trials` over this divisor.
    pub m2_floor_divisor: u64,
}

impl Default for BoundaryConfig {
    fn default() -> Self {
        Self {
            seed: 0x1C_B0_0B_DA_7A,
            repeats: 3,
            rho_repeats: 8,
            prime_bits: vec![10, 12, 14, 16, 18, 20, 22, 24],
            char2_degrees: vec![15, 18, 21, 24, 27],
            // The degrees whose K_a has a usable prime-order subgroup
            // (largest prime factor above the cofactor, squarefree);
            // 21, 25, 27, 33 and 35 have none.
            koblitz_degrees: vec![11, 13, 15, 17, 19, 23, 29, 31, 37, 39, 41],
            max_trials: 50_000_000,
            trial_floor_multiple: 64.0,
            koblitz_no_fold_max_degree: 31,
            s4_max_degree: 31,
            max_table_points: 6000,
            rho_cap_multiple: 64.0,
            max_folded_table_pairs: 1 << 23,
            m2_floor_divisor: 4,
        }
    }
}

impl BoundaryConfig {
    /// A configuration small enough for a unit test.
    pub fn quick() -> Self {
        Self {
            repeats: 1,
            rho_repeats: 2,
            prime_bits: vec![10, 12],
            char2_degrees: vec![12],
            koblitz_degrees: vec![11, 15],
            koblitz_no_fold_max_degree: 15,
            s4_max_degree: 15,
            ..Self::default()
        }
    }
}

impl TableCost {
    /// Group-addition equivalents of the build alone, for comparing
    /// tables on one base.
    pub fn gae(&self, calib: &Calibration) -> f64 {
        let mut phase = PhaseCost {
            group_ops: self.group_ops,
            ..PhaseCost::default()
        };
        for (name, by) in &self.native {
            phase.count(name, *by);
        }
        price_phase(&mut phase, calib);
        phase.gae
    }
}

fn rho_cap(r: u64, multiple: f64) -> u64 {
    (generic_floor_ops(r as f64, 1.0) * multiple) as u64 + 4096
}

/// Trials a variant may draw: the configured multiple of the counting
/// floor, at least 4096, at most the absolute cap.
fn trial_budget<E>(cfg: &BoundaryConfig, fb: &FactorBase<E>, m: u32, space: f64) -> u64 {
    let floor = trials_floor(fb.columns as u64, fb.points.len() as u64, m, space);
    ((cfg.trial_floor_multiple * floor).ceil() as u64).clamp(4096, cfg.max_trials.max(4096))
}

// ── The prime regime ───────────────────────────────────────────────

/// Run every prime-field variant on one instance.
pub fn run_prime_instance(inst: &PrimeInstance, cfg: &BoundaryConfig) -> RegimeInstance {
    let curve = &inst.curve;
    let r = inst.r;
    let g = inst.generator_point();
    let mut calib = Calibration::default();
    let mut rng = StdRng::seed_from_u64(cfg.seed ^ r);

    // Calibration on random points of the subgroup.
    let mut ops = GroupOps::default();
    let pts: Vec<PrimePoint> = (0..64)
        .map(|_| curve.mul(&mut ops, g, rng.gen_range(1..r)))
        .collect();
    calibrate_group(curve, &pts, &mut calib);
    calibrate_row_ops(r, &mut calib);
    {
        let mut residues = Vec::new();
        while residues.len() < 2048 {
            let v = rng.gen_range(1..curve.p);
            if curve.legendre(v) == 1 {
                residues.push(v);
            }
        }
        let start = Instant::now();
        let mut acc = 0u64;
        for _ in 0..8 {
            for &v in &residues {
                acc ^= curve.sqrt(v).unwrap_or(0);
            }
        }
        calib.ns_per_sqrt = Some(start.elapsed().as_nanos() as f64 / (8 * residues.len()) as f64);
        std::hint::black_box(acc);
        let values: Vec<u64> = (0..2048).map(|_| rng.gen_range(1..curve.p)).collect();
        let start = Instant::now();
        let mut acc = 0i32;
        for _ in 0..8 {
            for &v in &values {
                acc += curve.legendre(v);
            }
        }
        calib.ns_per_legendre = Some(start.elapsed().as_nanos() as f64 / (8 * values.len()) as f64);
        std::hint::black_box(acc);
        let start = Instant::now();
        let mut acc = 0u64;
        for _ in 0..8 {
            for &v in &values {
                acc ^= invmod(v, curve.p).unwrap_or(0);
            }
        }
        calib.ns_per_inversion = Some(start.elapsed().as_nanos() as f64 / (8 * values.len()) as f64);
        std::hint::black_box(acc);
    }
    calib.ns_per_word_xor = Some(calibrate_word_xor());

    let bits = 64 - r.leading_zeros();
    let fb_size = 1usize << bits.div_ceil(3);
    let fb = prime_factor_base(inst, fb_size);
    let table = PairTable::build(curve, &fb);
    let table_neg = PairTable::build_negation_folded(curve, &fb);
    calib.ns_per_lookup = table.calibrate_lookup(1_000_000);
    let exact_m2 = exact_decomposition_ceiling(curve, &fb.points, r, 2);
    let exact_m3 = exact_decomposition_ceiling(curve, &fb.points, r, 3);

    let floor_s = generic_floor_s(2.0);
    let mut out = RegimeInstance {
        regime: "prime".into(),
        curve: serde_json::json!({
            "name": inst.name, "p": curve.p, "a": curve.a, "b": curve.b,
            "group_order": inst.group_order, "subgroup_order": r, "cofactor": inst.cofactor,
            "generator": {"x": inst.generator.0, "y": inst.generator.1},
        }),
        r,
        log2_r: (r as f64).log2(),
        group_order: inst.group_order as f64,
        cofactor: inst.cofactor,
        automorphisms_generic: 2,
        floor_s,
        floor_ops: generic_floor_ops(r as f64, 2.0),
        calibration: calib.clone(),
        rho: Vec::new(),
        rho_s_mean: 0.0,
        rho_verified_all: true,
        variants: Vec::new(),
        seeds: Vec::new(),
        targets: Vec::new(),
    };
    out.curve["factor_base"] = serde_json::json!({
        "description": fb.description,
        "signed_points": fb.points.len(),
        "abscissae": fb.abscissae,
        "columns": fb.columns,
        "full_table_entries": table.entries,
        "negation_folded_table_entries": table_neg.entries,
        "cofactor_classes": exact_m2.map(|e| e.0),
        "ceiling_uniform_m2": decomposition_probability_ceiling(fb.points.len() as u64, 2, inst.group_order as f64),
        "ceiling_exact_m2": exact_m2.map(|e| e.1),
        "ceiling_uniform_m3": decomposition_probability_ceiling(fb.points.len() as u64, 3, inst.group_order as f64),
        "ceiling_exact_m3": exact_m3.map(|e| e.1),
    });

    let space = inst.group_order as f64;
    for rep in 0..cfg.repeats {
        let seed = cfg.seed.wrapping_add(rep as u64 * 0x9E37);
        let d = rng.gen_range(1..r);
        let target = curve.mul(&mut ops, g, d);
        out.seeds.push(seed);
        out.targets.push(d);
        let mut rho_s = 0.0;
        for k in 0..cfg.rho_repeats.max(1) {
            let rho = rho_reference(curve, g, target, r, seed ^ (k as u64 * 0x5EED), rho_cap(r, cfg.rho_cap_multiple));
            out.rho_verified_all &= rho.verified && rho.recovered == Some(d);
            rho_s += rho.s / cfg.rho_repeats.max(1) as f64;
            out.rho.push(rho);
        }

        use TargetSource::{Random, Walk};
        let variants: Vec<(&str, Oracle, TargetSource)> = vec![
            ("semaev_s3_roots_m2", Oracle::SemaevS3Roots, Random),
            ("direct_subtraction_m2", Oracle::Subtract, Random),
            ("mitm_m2", Oracle::Mitm { table: &table, m: 2 }, Random),
            ("mitm_m3", Oracle::Mitm { table: &table, m: 3 }, Random),
            // Round 2: the negation-folded table, then walk targets on it.
            ("mitm_m2_negfold", Oracle::Mitm { table: &table_neg, m: 2 }, Random),
            ("mitm_m2_negfold_walk", Oracle::Mitm { table: &table_neg, m: 2 }, Walk),
            ("mitm_m3_negfold", Oracle::Mitm { table: &table_neg, m: 3 }, Random),
            ("mitm_m3_negfold_walk", Oracle::Mitm { table: &table_neg, m: 3 }, Walk),
        ];
        for (name, oracle, targets) in variants {
            let budget = trial_budget(cfg, &fb, oracle.summands(), space);
            let outcome = collect_and_solve(
                curve,
                g,
                target,
                r,
                inst.cofactor,
                &fb,
                seed,
                budget,
                targets,
                |ops, ctr, point| decompose_prime(curve, &fb, &oracle, ops, ctr, point),
            );
            let exact = if oracle.summands() == 2 { exact_m2 } else { exact_m3 };
            let mut v = assemble_variant(
                name,
                oracle.name(),
                oracle.summands(),
                targets,
                &fb.cost,
                fb.points.len() as u64,
                fb.abscissae as u64,
                fb.columns as u64,
                None,
                oracle.table_cost(),
                exact,
                outcome,
                r,
                space,
                &calib,
                rho_s,
                floor_s,
            );
            v.verified &= v.recovered == Some(d);
            out.variants.push(v);
        }
    }
    out.rho_s_mean = out.rho.iter().map(|x| x.s).sum::<f64>() / out.rho.len().max(1) as f64;
    out
}

/// One binary-regime variant on one target: the relation loop, the
/// pricing, the check against the planted logarithm.
#[allow(clippy::too_many_arguments)]
fn run_binary_variant(
    inst: &BinaryInstance,
    name: &str,
    fb: &FactorBase<FastPoint>,
    oracle: &Oracle,
    targets: TargetSource,
    exact: ExactCeiling,
    target: FastPoint,
    d: u64,
    seed: u64,
    cfg: &BoundaryConfig,
    calib: &Calibration,
    rho_s: f64,
    floor_s: f64,
) -> VariantResult {
    let g = BinaryGroup(&inst.fast);
    let space = inst.group_order as f64;
    let budget = trial_budget(cfg, fb, oracle.summands(), space);
    let outcome = collect_and_solve(
        &g,
        inst.generator,
        target,
        inst.r,
        inst.cofactor,
        fb,
        seed,
        budget,
        targets,
        |ops, ctr, point| decompose_binary(inst, fb, oracle, ops, ctr, point),
    );
    let mut v = assemble_variant(
        name,
        oracle.name(),
        oracle.summands(),
        targets,
        &fb.cost,
        fb.points.len() as u64,
        fb.abscissae as u64,
        fb.columns as u64,
        fb.dimension,
        oracle.table_cost(),
        exact,
        outcome,
        inst.r,
        space,
        calib,
        rho_s,
        floor_s,
    );
    v.verified &= v.recovered == Some(d);
    v
}

/// Whether a two-summand row is worth running on a binary base: the
/// count is admissible by the cofactor classes and its exact trials
/// floor is within `max_trials / m2_floor_divisor`, so a run that finds
/// its relations at the ceiling's rate finishes well inside the budget.
fn two_summand_row_fits(cfg: &BoundaryConfig, fb: &FactorBase<FastPoint>, space: f64, exact_m2: ExactCeiling) -> bool {
    let p = exact_m2
        .map(|e| e.1)
        .unwrap_or_else(|| decomposition_probability_ceiling(fb.points.len() as u64, 2, space));
    p > 0.0 && (fb.columns as f64 + 1.0) / p <= cfg.max_trials as f64 / cfg.m2_floor_divisor.max(1) as f64
}

// ── The binary regimes ─────────────────────────────────────────────

/// The binary-regime conversion factors for one instance: addition,
/// doubling, Artin–Schreier solve, Frobenius map, row operation, word
/// XOR.  The lookup and `S₄` factors are added by the callers that
/// build the table and the oracle.
pub fn calibrate_binary_instance(inst: &BinaryInstance) -> Calibration {
    let mut c = Calibration::default();
    calibrate_binary(inst, &mut c);
    c
}

fn calibrate_binary(inst: &BinaryInstance, calib: &mut Calibration) {
    let g = BinaryGroup(&inst.fast);
    let mut rng = StdRng::seed_from_u64(inst.r ^ 0xB1);
    let mut ops = GroupOps::default();
    let pts: Vec<FastPoint> = (0..64)
        .map(|_| g.mul(&mut ops, inst.generator, rng.gen_range(1..inst.r)))
        .collect();
    calibrate_group(&g, &pts, calib);
    calibrate_row_ops(inst.r, calib);
    let samples = 200_000u64;
    let cs: Vec<u64> = (0..1024).map(|_| rng.gen::<u64>() & inst.gf.mask).collect();
    let start = Instant::now();
    let mut acc = 0u64;
    for i in 0..samples {
        acc ^= inst.artin_schreier.solve(cs[(i % 1024) as usize]).unwrap_or(1);
    }
    calib.ns_per_as_solve = Some(start.elapsed().as_nanos() as f64 / samples as f64);
    std::hint::black_box(acc);
    let start = Instant::now();
    let mut acc = pts[0];
    for _ in 0..samples {
        acc = inst.fast.frobenius_k(acc, 1);
    }
    calib.ns_per_frobenius = Some(start.elapsed().as_nanos() as f64 / samples as f64);
    std::hint::black_box(acc);
    calib.ns_per_word_xor = Some(calibrate_word_xor());
}

/// Nanoseconds per pair of the `S₄` pairs-and-solve loop, measured on
/// random targets of this instance.
pub fn calibrate_s4(inst: &BinaryInstance, oracle: &SubspaceOracle, calib: &mut Calibration) {
    let mut rng = StdRng::seed_from_u64(inst.r ^ 0x54);
    let mut pairs = 0u64;
    let start = Instant::now();
    let mut tries = 0;
    while tries < 3 || (pairs < 200_000 && tries < 64) {
        let xr = rng.gen::<u64>() & inst.gf.mask;
        let (_, p) = oracle.decompose(xr, &inst.gf);
        pairs += p;
        tries += 1;
    }
    calib.ns_per_s4_pair = Some(start.elapsed().as_nanos() as f64 / pairs.max(1) as f64);
}

/// The Koblitz base for degree `n`: the Frobenius-invariant subspace
/// whose dimension is nearest `⌈n/3⌉` (at most 12), or, where none
/// exists, the Frobenius closure of a random seed space sized to about
/// `2^{⌈n/3⌉}` abscissae — capped by the pair-table budget.
pub fn choose_koblitz_base(
    inst: &BinaryInstance,
    seed: u64,
    max_points: usize,
) -> Option<(FrobeniusFactorBase, String)> {
    let kc = inst.koblitz.as_ref()?;
    let n = inst.n;
    let target = n.div_ceil(3).max(3);
    let max_dim = 12u32.min((max_points as f64 / 2.0).log2().floor() as u32 + 1);
    let usable_dims: Vec<u32> = available_subspace_dimensions(n)
        .into_iter()
        .filter(|&d| d >= 2 && d < n && d <= max_dim && (d as i64 - target as i64).abs() <= 2)
        .collect();
    if !usable_dims.is_empty() {
        // Every divisor of x^n − 1 whose degree is a usable dimension,
        // nearest the target first.  A Frobenius-invariant subspace can
        // hold almost no curve abscissae (the dimension-5 subspace of
        // K_0/F_2^15 holds three points), so a candidate is kept only
        // when it carries at least a quarter of the points a random set
        // of its size would.
        let factors = all_factors_of_x_n_minus_1(n);
        let degs: Vec<u32> = factors.iter().map(|&f| 63 - f.leading_zeros()).collect();
        let count = factors.len().min(16);
        let mut candidates: Vec<(i64, u32, Vec<usize>)> = Vec::new();
        for mask in 1u32..(1u32 << count) {
            let idx: Vec<usize> = (0..count).filter(|&i| (mask >> i) & 1 == 1).collect();
            let total: u32 = idx.iter().map(|&i| degs[i]).sum();
            if usable_dims.contains(&total) {
                candidates.push(((total as i64 - target as i64).abs(), total, idx));
            }
        }
        candidates.sort();
        let mut best: Option<(FrobeniusFactorBase, String)> = None;
        for (_, dim, idx) in candidates {
            if let Some(fb) = build_frobenius_factor_base_from_divisor(kc, &idx) {
                // A subspace that is a subfield F_{2^d} carries the whole
                // point group E(F_{2^d}), a subgroup that meets the target
                // subgroup only at O: no relation exists at any cost.
                let is_subfield = n % dim == 0
                    && fb.subspace_basis.iter().all(|v| {
                        v.square_k_times(dim, &kc.curve.irreducible) == *v
                    });
                let healthy = !is_subfield
                    && fb.points.len() >= (1usize << dim) / 4
                    && fb.points.len() <= max_points;
                if healthy {
                    let better = best
                        .as_ref()
                        .is_none_or(|(b, _)| b.points.len() < fb.points.len() && b.ell == dim);
                    if better {
                        best = Some((
                            fb,
                            format!("invariant subspace, divisor {idx:?}, dimension {dim}"),
                        ));
                    }
                    if best.as_ref().is_some_and(|(b, _)| b.ell != dim) {
                        break;
                    }
                }
            }
        }
        if let Some(found) = best {
            return Some(found);
        }
    }
    // Orbit union of a random seed space, sized like the subspaces: about
    // `2^{⌈n/3⌉+1}` abscissae (`n · 2^s`), within the table budget.
    let mut rng = StdRng::seed_from_u64(seed ^ (n as u64));
    let log2_n = 63 - (n as u64).leading_zeros();
    let mut s = (target + 1).saturating_sub(log2_n).clamp(1, 12);
    while s > 1 && (n as usize) * (1usize << s) > max_points {
        s -= 1;
    }
    for _ in 0..64 {
        let basis: Vec<_> = (0..s)
            .map(|_| {
                let bits: Vec<u32> = (0..n).filter(|_| rng.gen::<bool>()).collect();
                crate::binary_ecc::F2mElement::from_bit_positions(&bits, n)
            })
            .collect();
        if let Some(fb) = build_frobenius_union_factor_base(kc, &basis) {
            if fb.points.len() <= max_points && fb.points.len() >= 8 {
                return Some((fb, format!("Frobenius orbit union of a seed space of dimension {s}")));
            }
        }
    }
    None
}

/// **A Koblitz base sized to the folded table**, for the balanced rows:
/// the Frobenius orbit union of a random seed space with about
/// `1.2·(4#E)^{1/3}` signed points — the size at which a folded table of
/// `|F|²/(4n)` entries balances a two-summand walk's `#E/(n|F|)` trials
/// — within `max_folded_table_pairs`.  `None` when that is not at least
/// half again the first-round base, so the rows are only run where the
/// full table's budget had actually bitten (`n ≥ 37` on the default
/// ladder).
pub fn choose_koblitz_balanced_base(
    inst: &BinaryInstance,
    cfg: &BoundaryConfig,
    first_round_points: usize,
) -> Option<(FrobeniusFactorBase, String)> {
    let kc = inst.koblitz.as_ref()?;
    let n = inst.n;
    let by_balance = 1.2 * (4.0 * inst.group_order as f64).cbrt();
    let by_table = (4.0 * n as f64 * cfg.max_folded_table_pairs as f64).sqrt();
    let target_points = by_balance.min(by_table);
    if target_points < 1.5 * first_round_points as f64 {
        return None;
    }
    // A seed space of dimension s gives n·2^s abscissae, about half of
    // which carry two points each: about n·2^s signed points.
    let s = ((target_points / n as f64).log2().round() as i64).clamp(1, 14) as u32;
    let mut rng = StdRng::seed_from_u64(cfg.seed ^ (n as u64) ^ 0xBA1A_4CED);
    for _ in 0..64 {
        let basis: Vec<_> = (0..s)
            .map(|_| {
                let bits: Vec<u32> = (0..n).filter(|_| rng.gen::<bool>()).collect();
                crate::binary_ecc::F2mElement::from_bit_positions(&bits, n)
            })
            .collect();
        if let Some(fb) = build_frobenius_union_factor_base(kc, &basis) {
            let f = fb.points.len();
            let pairs = (f as u64) * (f as u64) / (4 * n as u64);
            if f as f64 >= 1.5 * first_round_points as f64 && pairs <= cfg.max_folded_table_pairs {
                return Some((
                    fb,
                    format!(
                        "Frobenius orbit union of a seed space of dimension {s}, sized to the folded table (target {target_points:.0} signed points)"
                    ),
                ));
            }
        }
    }
    None
}

fn binary_regime_shell(inst: &BinaryInstance, regime: &str, automorphisms: u32) -> RegimeInstance {
    RegimeInstance {
        regime: regime.into(),
        curve: inst.describe(),
        r: inst.r,
        log2_r: (inst.r as f64).log2(),
        group_order: inst.group_order as f64,
        cofactor: inst.cofactor,
        automorphisms_generic: automorphisms,
        floor_s: generic_floor_s(automorphisms as f64),
        floor_ops: generic_floor_ops(inst.r as f64, automorphisms as f64),
        calibration: Calibration::default(),
        rho: Vec::new(),
        rho_s_mean: 0.0,
        rho_verified_all: true,
        variants: Vec::new(),
        seeds: Vec::new(),
        targets: Vec::new(),
    }
}

/// Run every generic-binary variant on one instance: `S₄`
/// pairs-and-solve and meet in the middle over the low-order subspace
/// of dimension `⌈n/3⌉`, columns by abscissa.  `None` when no summand
/// count in `{2, 3}` can reach the subgroup from this base.
pub fn run_char2_instance(inst: &BinaryInstance, cfg: &BoundaryConfig) -> Option<RegimeInstance> {
    let g = BinaryGroup(&inst.fast);
    let r = inst.r;
    let mut calib = Calibration::default();
    calibrate_binary(inst, &mut calib);
    let l = inst.n.div_ceil(3);
    let basis: Vec<u64> = (0..l).map(|i| 1u64 << i).collect();
    let mut fb = binary_subspace_factor_base(inst, &basis);
    let mut class_ops = GroupOps::default();
    let admissible: Vec<u32> = [3u32, 2]
        .into_iter()
        .filter(|&m| summands_admissible(&g, &mut class_ops, &fb.points, r, m))
        .collect();
    fb.cost.group_ops.merge(class_ops);
    fb.cost.count("admissibility_scalar_mults", class_ops.scalar_mults);
    let table = PairTable::build(&g, &fb);
    let table_neg = PairTable::build_negation_folded(&g, &fb);
    calib.ns_per_lookup = table.calibrate_lookup(1_000_000);
    let census: Vec<(u32, usize)> = admissible
        .iter()
        .map(|&m| (m, census_hits(inst, &fb, &Oracle::Mitm { table: &table, m }, 64, cfg.seed)))
        .collect();
    let m_used = census.iter().find(|(_, hits)| *hits > 0).map(|(m, _)| *m)?;
    let s4 = (m_used == 3).then(|| SubspaceOracle::new(&basis, inst.b, &inst.gf));
    if let Some(o) = &s4 {
        calibrate_s4(inst, o, &mut calib);
    }
    let space = inst.group_order as f64;
    let exact_m2 = exact_decomposition_ceiling(&g, &fb.points, r, 2);
    let exact_m3 = exact_decomposition_ceiling(&g, &fb.points, r, 3);
    let exact_of = |m: u32| if m == 2 { exact_m2 } else { exact_m3 };
    // The two-summand row, where the census of 64 was too small to see
    // it but the exact floor says it is within reach.
    let m2_row = m_used == 3 && admissible.contains(&2) && two_summand_row_fits(cfg, &fb, space, exact_m2);

    let mut out = binary_regime_shell(inst, "char2", 2);
    out.calibration = calib.clone();
    out.curve["factor_base"] = serde_json::json!({
        "description": fb.description,
        "dimension": l,
        "signed_points": fb.points.len(),
        "abscissae": fb.abscissae,
        "columns": fb.columns,
        "summands_admissible": admissible,
        "census_hits_of_64": census,
        "summands_used": m_used,
        "two_summand_row": m2_row,
        "full_table_entries": table.entries,
        "negation_folded_table_entries": table_neg.entries,
        "cofactor_classes": exact_m2.map(|e| e.0),
        "ceiling_uniform_m2": decomposition_probability_ceiling(fb.points.len() as u64, 2, space),
        "ceiling_exact_m2": exact_m2.map(|e| e.1),
        "ceiling_uniform_m3": decomposition_probability_ceiling(fb.points.len() as u64, 3, space),
        "ceiling_exact_m3": exact_m3.map(|e| e.1),
    });
    let mut rng = StdRng::seed_from_u64(cfg.seed ^ r ^ 0xC2);
    let mut ops = GroupOps::default();
    for rep in 0..cfg.repeats {
        let seed = cfg.seed.wrapping_add(rep as u64 * 0x9E37);
        let d = rng.gen_range(1..r);
        let target = g.mul(&mut ops, inst.generator, d);
        out.seeds.push(seed);
        out.targets.push(d);
        let mut rho_s = 0.0;
        for k in 0..cfg.rho_repeats.max(1) {
            let rho = rho_reference(&g, inst.generator, target, r, seed ^ (k as u64 * 0x5EED), rho_cap(r, cfg.rho_cap_multiple));
            out.rho_verified_all &= rho.verified && rho.recovered == Some(d);
            rho_s += rho.s / cfg.rho_repeats.max(1) as f64;
            out.rho.push(rho);
        }

        use TargetSource::{Random, Walk};
        let mut variants: Vec<(String, Oracle, TargetSource)> = vec![(
            format!("mitm_m{m_used}"),
            Oracle::Mitm { table: &table, m: m_used },
            Random,
        )];
        if let Some(o) = &s4 {
            if inst.n <= cfg.s4_max_degree {
                variants.push(("semaev_s4_pairs_and_solve_m3".into(), Oracle::SemaevS4 { oracle: o }, Random));
            }
        }
        // Round 2: the negation-folded table, walk targets, and the
        // two-summand row where it fits.
        variants.push((
            format!("mitm_m{m_used}_negfold"),
            Oracle::Mitm { table: &table_neg, m: m_used },
            Random,
        ));
        variants.push((
            format!("mitm_m{m_used}_negfold_walk"),
            Oracle::Mitm { table: &table_neg, m: m_used },
            Walk,
        ));
        if m2_row {
            variants.push(("mitm_m2_negfold".into(), Oracle::Mitm { table: &table_neg, m: 2 }, Random));
            variants.push(("mitm_m2_negfold_walk".into(), Oracle::Mitm { table: &table_neg, m: 2 }, Walk));
        }
        for (name, oracle, targets) in variants {
            let v = run_binary_variant(
                inst,
                &name,
                &fb,
                &oracle,
                targets,
                exact_of(oracle.summands()),
                target,
                d,
                seed,
                cfg,
                &calib,
                rho_s,
                out.floor_s,
            );
            out.variants.push(v);
        }
    }
    out.rho_s_mean = out.rho.iter().map(|x| x.s).sum::<f64>() / out.rho.len().max(1) as f64;
    Some(out)
}

/// Run every Koblitz variant on one instance: meet in the middle over
/// signed-orbit columns, the same without the fold (the `char2` pipeline
/// on the Koblitz curve), and `S₄` pairs-and-solve on the invariant
/// subspace when the base is one.  The reference is the signed-Frobenius
/// rho (`A = 2n`); the plain walk is run too, for the comparison with
/// the other regimes.
pub fn run_koblitz_instance(inst: &BinaryInstance, cfg: &BoundaryConfig) -> Option<RegimeInstance> {
    let kc = inst.koblitz.as_ref()?;
    let g = BinaryGroup(&inst.fast);
    let r = inst.r;
    let n = inst.n;
    let mut calib = Calibration::default();
    calibrate_binary(inst, &mut calib);
    let (mut frob, mut description) = choose_koblitz_base(inst, cfg.seed, cfg.max_table_points)?;
    // Which summand counts actually reach the subgroup from this base?
    // The cofactor-class test is the cheap necessary filter; the census
    // on the built pair table is the real one.  When neither count
    // yields, the two-torsion saturation `B ∪ (B + T)` changes the
    // cofactor classes without adding projected points.
    let admissible_of = |fb: &FrobeniusFactorBase| -> Vec<u32> {
        [3u32, 2]
            .into_iter()
            .filter(|&m| fb.m_can_decompose(kc, m as usize))
            .collect()
    };
    let mut admissible = admissible_of(&frob);
    let mut folded = koblitz_factor_base(inst, &frob, ColumnFold::SignedFrobeniusOrbit, description.clone())?;
    let mut table = PairTable::build(&g, &folded);
    let census_of = |fb: &FactorBase<FastPoint>, table: &PairTable, adm: &[u32]| -> Vec<(u32, usize)> {
        adm.iter()
            .map(|&m| (m, census_hits(inst, fb, &Oracle::Mitm { table, m }, 64, cfg.seed)))
            .collect()
    };
    let mut census = census_of(&folded, &table, &admissible);
    if !census.iter().any(|(_, hits)| *hits > 0) {
        let saturated = saturate_factor_base_two_torsion(kc, &frob)?;
        if saturated.points.len() > cfg.max_table_points {
            return None;
        }
        admissible = admissible_of(&saturated);
        frob = saturated;
        description.push_str(" + two-torsion saturation");
        folded = koblitz_factor_base(inst, &frob, ColumnFold::SignedFrobeniusOrbit, description.clone())?;
        table = PairTable::build(&g, &folded);
        census = census_of(&folded, &table, &admissible);
    }
    let m_used = census.iter().find(|(_, hits)| *hits > 0).map(|(m, _)| *m)?;
    let unfolded = koblitz_factor_base(inst, &frob, ColumnFold::Abscissa, description.clone())?;
    calib.ns_per_lookup = table.calibrate_lookup(1_000_000);
    let s4 = folded
        .subspace_basis
        .as_ref()
        .filter(|_| n <= cfg.s4_max_degree && m_used == 3)
        .map(|basis| SubspaceOracle::new(basis, 1, &inst.gf));
    if let Some(o) = &s4 {
        calibrate_s4(inst, o, &mut calib);
    }
    let space = inst.group_order as f64;

    // Round 2 on the same base: the negation-folded table, the
    // Frobenius-folded table, the exact ceilings, the two-summand row.
    let table_neg = PairTable::build_negation_folded(&g, &folded);
    let table_frob = FrobeniusPairTable::build(inst, &folded);
    calib.ns_per_canon = table_frob.as_ref().map(|t| t.calibrate_canon(1_000_000));
    let exact_m2 = exact_decomposition_ceiling(&g, &folded.points, r, 2);
    let exact_m3 = exact_decomposition_ceiling(&g, &folded.points, r, 3);
    let exact_of = |m: u32| if m == 2 { exact_m2 } else { exact_m3 };
    let m2_row = table_frob.is_some()
        && m_used == 3
        && admissible.contains(&2)
        && two_summand_row_fits(cfg, &folded, space, exact_m2);

    // Round 2 on a base sized to the folded table (n ≥ 37 on the default
    // ladder): its own rows, its own floor.
    let balanced = choose_koblitz_balanced_base(inst, cfg, folded.points.len()).and_then(|(fbb, desc)| {
        let fb = koblitz_factor_base(inst, &fbb, ColumnFold::SignedFrobeniusOrbit, desc)?;
        let table = FrobeniusPairTable::build(inst, &fb)?;
        let adm: Vec<u32> = [3u32, 2]
            .into_iter()
            .filter(|&m| fbb.m_can_decompose(kc, m as usize))
            .collect();
        let census_m3 = adm.contains(&3).then(|| {
            census_hits(inst, &fb, &Oracle::MitmFrobenius { table: &table, m: 3 }, 64, cfg.seed)
        });
        let exact_m2 = exact_decomposition_ceiling(&g, &fb.points, r, 2);
        let exact_m3 = exact_decomposition_ceiling(&g, &fb.points, r, 3);
        let m3_row = census_m3.is_some_and(|hits| hits > 0);
        let m2_row = adm.contains(&2) && two_summand_row_fits(cfg, &fb, space, exact_m2);
        if !m3_row && !m2_row {
            return None;
        }
        Some((fbb, fb, table, adm, census_m3, exact_m2, exact_m3, m3_row, m2_row))
    });

    let mut out = binary_regime_shell(inst, "koblitz", 2 * n);
    out.calibration = calib.clone();
    out.curve["factor_base"] = serde_json::json!({
        "description": description,
        "domain": format!("{:?}", frob.domain),
        "signed_points": folded.points.len(),
        "abscissae": folded.abscissae,
        "signed_orbits": folded.columns,
        "dimension": folded.dimension,
        "lambda": kc.lambda.to_string(),
        "summands_admissible": admissible,
        "census_hits_of_64": census,
        "summands_used": m_used,
        "two_summand_row": m2_row,
        "full_table_entries": table.entries,
        "negation_folded_table_entries": table_neg.entries,
        "frobenius_folded_table_entries": table_frob.as_ref().map(|t| t.entries),
        "frobenius_folded_table_representatives": table_frob.as_ref().map(|t| t.representatives),
        "cofactor_classes": exact_m2.map(|e| e.0),
        "ceiling_uniform_m2": decomposition_probability_ceiling(folded.points.len() as u64, 2, space),
        "ceiling_exact_m2": exact_m2.map(|e| e.1),
        "ceiling_uniform_m3": decomposition_probability_ceiling(folded.points.len() as u64, 3, space),
        "ceiling_exact_m3": exact_m3.map(|e| e.1),
    });
    if let Some((fbb, fb, table, adm, census_m3, exact_m2, exact_m3, m3_row, m2_row)) = &balanced {
        out.curve["factor_base_balanced"] = serde_json::json!({
            "description": fb.description,
            "domain": format!("{:?}", fbb.domain),
            "signed_points": fb.points.len(),
            "abscissae": fb.abscissae,
            "signed_orbits": fb.columns,
            "summands_admissible": adm,
            "census_hits_of_64_m3": census_m3,
            "three_summand_row": m3_row,
            "two_summand_row": m2_row,
            "frobenius_folded_table_entries": table.entries,
            "frobenius_folded_table_representatives": table.representatives,
            "cofactor_classes": exact_m2.map(|e| e.0),
            "ceiling_uniform_m2": decomposition_probability_ceiling(fb.points.len() as u64, 2, space),
            "ceiling_exact_m2": exact_m2.map(|e| e.1),
            "ceiling_uniform_m3": decomposition_probability_ceiling(fb.points.len() as u64, 3, space),
            "ceiling_exact_m3": exact_m3.map(|e| e.1),
        });
    }
    let mut rng = StdRng::seed_from_u64(cfg.seed ^ r ^ 0x4B);
    let mut ops = GroupOps::default();
    let bits = (r as f64).log2();
    for rep in 0..cfg.repeats {
        let seed = cfg.seed.wrapping_add(rep as u64 * 0x9E37);
        let d = rng.gen_range(1..r);
        let target = g.mul(&mut ops, inst.generator, d);
        out.seeds.push(seed);
        out.targets.push(d);

        // Signed-Frobenius rho: the reference on this curve.
        let target_big = inst.fast.lower(target);
        let mut rho_s = 0.0;
        for k in 0..cfg.rho_repeats.max(1) {
            let opts = KoblitzSignedRhoOptions {
                seed: seed ^ (k as u64 * 0x5EED),
                ..Default::default()
            };
            let start = Instant::now();
            let report = koblitz_signed_frobenius_rho_reference(kc, &target_big, &opts, &mut |_| {});
            let wall = start.elapsed().as_nanos() as u64;
            let c = &report.charges;
            // Scalar multiplications are charged at 1.5·log2(r) additions
            // each, the double-and-add average; walk additions are exact.
            let scalar_adds = (c.setup_scalar_multiplications
                + c.candidate_verification_scalar_multiplications) as f64
                * 1.5
                * bits;
            let gops = GroupOps {
                adds: c.walk_group_additions + c.setup_group_additions,
                doubles: 0,
                scalar_mults: c.setup_scalar_multiplications
                    + c.candidate_verification_scalar_multiplications,
            };
            let gae = gops.gae() + scalar_adds;
            let expected = generic_floor_ops(r as f64, 2.0 * n as f64);
            let recovered = report.recovered_log.as_ref().and_then(|v| v.to_u64());
            let signed = RhoResult {
                method: "signed-Frobenius r-adding walk, distinguished points (koblitz_signed_frobenius_rho_reference)".into(),
                automorphisms: 2 * n,
                group_ops: gops,
                steps: report.iterations,
                walks: report.parallel_walks as u64 * report.restarts_attempted as u64,
                distinguished_points: c.collisions + c.failed_collisions,
                gae,
                s: gae / (r as f64).sqrt(),
                s_walk: report.iterations as f64 / (r as f64).sqrt(),
                expected_steps: expected,
                steps_over_expected: report.iterations as f64 / expected,
                wall_ns: wall,
                recovered,
                verified: report.verified && recovered == Some(d),
            };
            out.rho_verified_all &= signed.verified;
            rho_s += signed.s / cfg.rho_repeats.max(1) as f64;
            out.rho.push(signed);
            // The plain walk, for the cross-regime comparison.
            let plain = rho_reference(&g, inst.generator, target, r, seed ^ (k as u64 * 0x5EED), rho_cap(r, cfg.rho_cap_multiple));
            out.rho.push(plain);
        }

        use TargetSource::{Random, Walk};
        let mut variants: Vec<(String, &FactorBase<FastPoint>, Oracle, TargetSource, ExactCeiling)> = vec![(
            format!("mitm_m{m_used}_signed_orbit_columns"),
            &folded,
            Oracle::Mitm { table: &table, m: m_used },
            Random,
            exact_of(m_used),
        )];
        if n <= cfg.koblitz_no_fold_max_degree {
            variants.push((
                format!("mitm_m{m_used}_abscissa_columns_control"),
                &unfolded,
                Oracle::Mitm { table: &table, m: m_used },
                Random,
                exact_of(m_used),
            ));
        }
        if let Some(o) = &s4 {
            variants.push((
                "semaev_s4_pairs_and_solve_m3_signed_orbit_columns".into(),
                &folded,
                Oracle::SemaevS4 { oracle: o },
                Random,
                exact_m3,
            ));
        }
        // Round 2, cumulative: fold the negation out of the table, then
        // the Frobenius, then draw the targets by a walk; the
        // two-summand row on the folded table where it fits.
        variants.push((
            format!("mitm_m{m_used}_signed_orbit_columns_negfold"),
            &folded,
            Oracle::Mitm { table: &table_neg, m: m_used },
            Random,
            exact_of(m_used),
        ));
        if let Some(tf) = &table_frob {
            variants.push((
                format!("mitm_m{m_used}_signed_orbit_columns_frobfold"),
                &folded,
                Oracle::MitmFrobenius { table: tf, m: m_used },
                Random,
                exact_of(m_used),
            ));
            variants.push((
                format!("mitm_m{m_used}_signed_orbit_columns_frobfold_walk"),
                &folded,
                Oracle::MitmFrobenius { table: tf, m: m_used },
                Walk,
                exact_of(m_used),
            ));
            if m2_row {
                variants.push((
                    "mitm_m2_signed_orbit_columns_frobfold_walk".into(),
                    &folded,
                    Oracle::MitmFrobenius { table: tf, m: 2 },
                    Walk,
                    exact_m2,
                ));
            }
        }
        if let Some((_, fb, tf, _, _, exact_m2_b, exact_m3_b, m3_row, m2_row_b)) = &balanced {
            if *m3_row {
                variants.push((
                    "mitm_m3_signed_orbit_columns_frobfold_walk_balanced".into(),
                    fb,
                    Oracle::MitmFrobenius { table: tf, m: 3 },
                    Walk,
                    *exact_m3_b,
                ));
            }
            if *m2_row_b {
                variants.push((
                    "mitm_m2_signed_orbit_columns_frobfold_walk_balanced".into(),
                    fb,
                    Oracle::MitmFrobenius { table: tf, m: 2 },
                    Walk,
                    *exact_m2_b,
                ));
            }
        }
        for (name, fb, oracle, targets, exact) in variants {
            let v = run_binary_variant(
                inst,
                &name,
                fb,
                &oracle,
                targets,
                exact,
                target,
                d,
                seed,
                cfg,
                &calib,
                rho_s,
                out.floor_s,
            );
            out.variants.push(v);
        }
    }
    // Mean over the signed reference only.
    let signed: Vec<f64> = out
        .rho
        .iter()
        .filter(|x| x.automorphisms > 1)
        .map(|x| x.s)
        .collect();
    out.rho_s_mean = signed.iter().sum::<f64>() / signed.len().max(1) as f64;
    Some(out)
}

