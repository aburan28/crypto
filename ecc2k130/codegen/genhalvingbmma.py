"""Generate a binary-WMMA direct polynomial square-root map."""
from pathlib import Path
import argparse

from genpacked import stages
from gensigma import permutation

M = 131
MASK = (1 << M) - 1


def apply_stages(x, inverse):
    for shift, mask in stages(M, inverse):
        x ^= (x >> shift) & mask
    return x


def to_poly(x):
    sign = MASK if (x >> 130) & 1 else 0
    return apply_stages(((x << 1) ^ sign) & MASK, True)


def from_poly(x):
    v = apply_stages(x, False)
    sign = MASK if v & 1 else 0
    return ((v >> 1) ^ sign) & MASK


def permute(x, p):
    out = 0
    for i in range(M):
        if (x >> i) & 1:
            out |= 1 << p[i]
    return out


def sqrt_poly(x):
    return to_poly(permute(from_poly(x), permutation(M - 1)))


def rows(fn):
    result = [0] * M
    for col in range(M):
        value = fn(1 << col)
        for row in range(M):
            if (value >> row) & 1:
                result[row] |= 1 << col
    return result


def generate():
    for i in range(M):
        x = 1 << i
        if from_poly(to_poly(x)) != x or to_poly(from_poly(x)) != x:
            raise ValueError(("conversion mismatch", i))
    matrix = rows(sqrt_poly)
    low = []
    top = []
    for row in range(136):
        value = matrix[row] if row < M else 0
        low.extend((value >> (32 * i)) & 0xffffffff for i in range(4))
        top.append((value >> 128) & 7)
    lines = [
        "// Generated by codegen/genhalvingbmma.py; included inside eccPacked131.",
        "#pragma once",
        "#ifdef __CUDACC__",
        "static __device__ __constant__ uint32_t halvingSqrtBmmaRows[544]={",
    ]
    for i in range(0, len(low), 8):
        lines.append(" "+",".join(f"0x{x:08x}u" for x in low[i:i+8])+",")
    lines += [
        "};",
        "static __device__ __constant__ uint8_t halvingSqrtBmmaTop[136]={",
    ]
    for i in range(0, len(top), 32):
        lines.append(" "+",".join(str(x) for x in top[i:i+32])+",")
    lines += [
        "};",
        "static __device__ __forceinline__ P131 halvingSqrtPolynomialBmma131(P131 input){",
        " using namespace nvcuda;",
        " __shared__ __align__(16) uint32_t bmem[32][32];",
        " __shared__ __align__(16) int cmem[32][64];",
        " const int lane=int(threadIdx.x)&31,warp=int(threadIdx.x)>>5;",
        " P131 out={{0,0,0,0,0}};",
        " for(int group=0;group<4;++group){",
        "  if((lane>>3)==group){",
        "#pragma unroll",
        "   for(int w=0;w<4;++w)bmem[warp][(lane&7)*4+w]=input.v[w];",
        "  }",
        "  __syncwarp();",
        "#pragma unroll",
        "  for(int block=0;block<17;++block){",
        "   wmma::fragment<wmma::matrix_a,8,8,128,wmma::experimental::precision::b1,wmma::row_major> a;",
        "   wmma::fragment<wmma::matrix_b,8,8,128,wmma::experimental::precision::b1,wmma::col_major> b;",
        "   wmma::fragment<wmma::accumulator,8,8,128,int> c,d;",
        "   wmma::load_matrix_sync(a,halvingSqrtBmmaRows+block*32,128);",
        "   wmma::load_matrix_sync(b,bmem[warp],128);",
        "   wmma::fill_fragment(c,0);",
        "   wmma::bmma_sync(d,a,b,c,wmma::experimental::bmmaBitOpAND,wmma::experimental::bmmaAccumulateOpPOPC);",
        "   wmma::store_matrix_sync(cmem[warp],d,8,wmma::mem_row_major);",
        "   __syncwarp();",
        "   if((lane>>3)==group){",
        "#pragma unroll",
        "    for(int r=0;r<8;++r){",
        "     const int bit=block*8+r;",
        "     if(bit<131){",
        "      const unsigned parity=(unsigned(cmem[warp][r*8+(lane&7)])^",
        "        unsigned(__popc(input.v[4]&halvingSqrtBmmaTop[bit])))&1u;",
        "      out.v[bit>>5]|=parity<<(bit&31);",
        "     }",
        "    }",
        "   }",
        "   __syncwarp();",
        "  }",
        " }",
        " return out;",
        "}",
        "#else",
        "ECC_HD P131 halvingSqrtPolynomialBmma131(P131 input){",
        " return toPolynomial131(halvingSqrt131(fromPolynomial131(input)));",
        "}",
        "#endif",
    ]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default="../include/packedhalvingbmma131.cuh")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = generate()
    path = Path(args.out)
    if args.check:
        if path.read_text() != text:
            raise SystemExit("BMMA halving header does not match generator")
    else:
        path.write_text(text)
    print("PASS: polynomial square-root BMMA matrix on all basis vectors")
