def emit_value(prefix, d, word, mask):
    v=f'{prefix}{word}'
    out=[]
    if d in (8,16):
        mask |= mask << d
        if d == 8:
            out.append(f'    t=__byte_perm({v},{v},0x2301u);')
        else:
            out.append(f'    t=__funnelshift_r({v},{v},16);')
        out.append(f'    {v}=({v}&~0x{mask:08x}u)|(t&0x{mask:08x}u);')
    elif d < 32:
        out.append(f'    t=(({v}>>{d})^{v})&0x{mask:08x}u;')
        out.append(f'    {v}^=t^(t<<{d});')
    else:
        other=word+d//32
        out.append(f'    t=({v}^{prefix}{other})&0x{mask:08x}u;')
        out.append(f'    {v}^=t; {prefix}{other}^=t;')
    return out

def emit(k, net):
    lines=[f'static ECC_BIG SigmaWalkPair131 sigmaWalkPairImmediate{k}(P131 a,P131 b) {{',
           '#if defined(__CUDACC__) && !defined(__CUDA_ARCH__)',
           f'    for(int i=0;i<{k};++i) {{ a=sqr131(a); b=sqr131(b); }}',
           '    return SigmaWalkPair131{a,b};','#else',
           '    uint32_t a0=a.v[0],a1=a.v[1],a2=a.v[2],a3=a.v[3],a4=a.v[4];',
           '    uint32_t b0=b.v[0],b1=b.v[1],b2=b.v[2],b3=b.v[3],b4=b.v[4],t;']
    for d,bits in net:
        for word in range(5):
            mask=(bits>>(32*word))&0xffffffff
            if mask:
                lines += emit_value('a',d,word,mask)
                lines += emit_value('b',d,word,mask)
    lines += ['    return SigmaWalkPair131{P131{{a0,a1,a2,a3,a4&7u}},P131{{b0,b1,b2,b3,b4&7u}}};',
              '#endif','}']
    return lines

nets=gensigma.networks(True,gensigma.WALK_STAGE_ORDER)
lines=['// Generated by benchmarks/g7-12b-two-jump/gen_fixed_sigma.py.','#pragma once']
for k in (3,4): lines += emit(k,nets[k])
lines += ['static ECC_BIG SigmaWalkPair131 sigmaWalkPairImmediate34(P131 a,P131 b,int index) {',
          '    return index?sigmaWalkPairImmediate4(a,b):sigmaWalkPairImmediate3(a,b);','}']
(SRC/'include/packedtwosigma131.h').write_text('\n'.join(lines)+'\n')
