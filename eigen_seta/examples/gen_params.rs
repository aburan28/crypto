//! Generate the Eigen-Seta parameter sets (replaces the former SageMath
//! script tools/gen_params.py; output is byte-identical apart from the
//! header line).
//!
//!   cargo run --release --example gen_params > src/params_generated.rs
//!   cargo run --release --example gen_params -- Toy16 Toy32   # subset
//!
//! p = 2^(e+1) * 3^f3 * c - 1 prime with p = 3, 5, 6 (mod 7) (so the CM(-7)
//! curve E_D, j = -3375, is supersingular), d = 3^f3 >= 2^(2 lambda), secret
//! degree f in [lo, 2 lo) with lo = 2^kappa * floor(p / 2^e) + 1, and e minimal
//! with 2^e > 28 d^2 fmax^2 (the decapsulation chain fits:
//! c^2 + c'^2 = 2^e - 7 d^2 f^2 > 0 with margin).
use eigen_seta::ntheory::is_probable_prime;
use num_bigint::{BigInt, BigUint};
use rand_core::{CryptoRng, RngCore};

/// Deterministic bases for the extra Miller-Rabin rounds (public data only).
struct SplitMix(u64);
impl RngCore for SplitMix {
    fn next_u32(&mut self) -> u32 {
        self.next_u64() as u32
    }
    fn next_u64(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(0x9E3779B97F4A7C15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58476D1CE4E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D049BB133111EB);
        z ^ (z >> 31)
    }
    fn fill_bytes(&mut self, d: &mut [u8]) {
        for c in d.chunks_mut(8) {
            let v = self.next_u64().to_le_bytes();
            c.copy_from_slice(&v[..c.len()]);
        }
    }
    fn try_fill_bytes(&mut self, d: &mut [u8]) -> Result<(), rand_core::Error> {
        self.fill_bytes(d);
        Ok(())
    }
}
impl CryptoRng for SplitMix {}

const SETS: [(&str, usize, usize); 5] = [
    ("Toy16", 16, 8),
    ("Toy32", 32, 8),
    ("L1", 128, 12),
    ("L3", 192, 12),
    ("L5", 256, 12),
];

fn find_prime(e: usize, f3: usize, rng: &mut SplitMix) -> (BigUint, u64) {
    let base = (BigUint::from(1u32) << (e + 1)) * BigUint::from(3u32).pow(f3 as u32);
    let mut c = 1u64;
    loop {
        let p = &base * c - 1u32;
        let r7 = (&p % 7u32).to_u32_digits().first().copied().unwrap_or(0);
        if [3, 5, 6].contains(&r7) && is_probable_prime(&p, rng, 20) {
            return (p, c);
        }
        c += 1;
    }
}

struct Set {
    lam: usize,
    kappa: usize,
    f3: usize,
    e: usize,
    p: BigUint,
    c: u64,
    lo: BigUint,
}

fn pick(lam: usize, kappa: usize, rng: &mut SplitMix) -> Set {
    let f3 = (2.0 * lam as f64 / 3f64.log2()).ceil() as usize;
    let d = BigUint::from(3u32).pow(f3 as u32);
    let bound = |e: usize, p: &BigUint| {
        let lo = (p >> e) * (BigUint::from(1u32) << kappa) + 1u32;
        let fmax = &lo * 2u32;
        (
            BigUint::from(1u32) << e > BigUint::from(28u32) * &d * &d * &fmax * &fmax,
            lo,
        )
    };
    let mut e = 8usize.max((4.0 * f3 as f64 * 1.58) as usize - 10);
    loop {
        // c >= 1 only enlarges fmax: skip the prime search while even c = 1 fails
        let p1 = (BigUint::from(1u32) << (e + 1)) * &d - 1u32;
        if bound(e, &p1).0 {
            let (p, c) = find_prime(e, f3, rng);
            let (ok, lo) = bound(e, &p);
            if ok {
                return Set {
                    lam,
                    kappa,
                    f3,
                    e,
                    p,
                    c,
                    lo,
                };
            }
        }
        e += 1;
    }
}

fn hex(x: &BigUint) -> String {
    format!("{:x}", x)
}

fn main() {
    let want: Vec<String> = std::env::args().skip(1).collect();
    let mut rng = SplitMix(0x5e7a);
    let mut out = vec![
        "// @generated by examples/gen_params.rs. Do not edit by hand.".to_string(),
        "// p = 2^(e+1) * 3^f3 * c - 1;  d = 3^f3;  f in [f_lo, 2 f_lo).".to_string(),
        "use crate::params::ParamSet;".to_string(),
        "use crate::fp::FpConfig;\n".to_string(),
    ];
    for (name, lam, kappa) in SETS {
        if !want.is_empty() && !want.iter().any(|w| w == name) {
            continue;
        }
        let s = pick(lam, kappa, &mut rng);
        let p = &s.p;
        let bits = p.bits() as usize;
        let n = bits.div_ceil(64);
        // E_D: j = -3375, short model y^2 = x^3 - 3 j k x - 2 j k^2, k = j - 1728
        let j = BigInt::from(-3375);
        let k = &j - 1728;
        let pi = BigInt::from(p.clone());
        let red = |x: BigInt| -> BigUint { (((x % &pi) + &pi) % &pi).to_biguint().unwrap() };
        let a4 = red(BigInt::from(-3) * &j * &k);
        let a6 = red(BigInt::from(-2) * &j * &k * &k);
        let dbits = s.f3 as f64 * 3f64.log2();
        out.push(format!("// {name}: lambda = {}, p has {bits} bits ({n} limbs), e = {}, f3 = {} (d ~ 2^{:.1}), c = {}, kappa = {}", s.lam, s.e, s.f3, dbits, s.c, s.kappa));
        out.push(format!(
            "#[derive(Clone, Copy, Debug)]\npub struct {name}Fp;"
        ));
        out.push(format!("impl FpConfig<{n}> for {name}Fp {{\n    const MODULUS: [u64; {n}] = crate::hexlimbs!(\"{}\", {n});\n    const NAME: &'static str = \"{name}\";\n}}", hex(p)));
        out.push(format!("#[derive(Clone, Copy, Debug)]\npub struct {name};"));
        out.push(format!("impl ParamSet<{n}> for {name} {{\n    const NAME: &'static str = \"{name}\";\n    const LAMBDA: usize = {lam};\n    type Cfg = {name}Fp;\n    const E: usize = {};\n    const F3: usize = {};\n    const KAPPA: usize = {kappa};\n    const COFACTOR: u64 = {};\n    const F_LO_HEX: &'static str = \"{}\";\n    const ED_A4_HEX: &'static str = \"{}\";\n    const ED_A6_HEX: &'static str = \"{}\";\n}}\n", s.e, s.f3, s.c, hex(&s.lo), hex(&a4), hex(&a6)));
        eprintln!("{name}: p {bits} bits, e {}, f3 {}, c {}", s.e, s.f3, s.c);
    }
    println!("{}", out.join("\n"));
}
