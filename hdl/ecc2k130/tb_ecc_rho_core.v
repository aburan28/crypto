// Self-checking testbench for one ECC2K-130 rho core.
//
// Loads one start point per ring slot, lets the ring free-run, and checks that
// every retired step equals the next point of that walk's reference trajectory
// -- the trajectory computed by curves.Curve in the generator, which is the
// same oracle the CPU and CUDA clients are checked against.
//
// It also checks the two properties the throughput claim rests on: that a step
// retires on every clock once the pipeline has filled (initiation interval 1),
// and that nothing is reported as a distinguished point unless its weight
// really is within the cutoff.
`timescale 1ns/1ps
`default_nettype none

module tb_ecc_rho_core;
    localparam M = 131;
    localparam TAGW = 8;
    localparam SLOTS = 124;              // = ring latency, so the ring stays full
    localparam STEPS = 3;                // reference steps per walk
    localparam TRAJ = STEPS + 1;
    localparam [7:0] DPCUT = 8'd70;      // loose, so dp actually fires here

    reg clk = 1'b0;
    always #5 clk = ~clk;

    // ---- reference trajectories -------------------------------------------
    // generated by ecc2k130/codegen/genverilog.py; override with
    //   iverilog -Ptb_ecc_rho_core.VECFILE=...
    parameter VECFILE = "../../ecc2k130/generated/rtl/vectors_walk131.txt";
    reg [2*M-1:0] traj [0:SLOTS*TRAJ-1];
    initial $readmemh(VECFILE, traj);

    function [M-1:0] trajX;
        input integer slot;
        input integer step;
        begin
            trajX = traj[slot*TRAJ + step][2*M-1:M];
        end
    endfunction

    function [M-1:0] trajY;
        input integer slot;
        input integer step;
        begin
            trajY = traj[slot*TRAJ + step][M-1:0];
        end
    endfunction

    function integer weightOf;
        input [M-1:0] v;
        integer i;
        begin
            weightOf = 0;
            for (i = 0; i < M; i = i + 1) weightOf = weightOf + v[i];
        end
    endfunction

    // ---- the core and its shared inverter ---------------------------------
    reg  [M-1:0]    loadX = {M{1'b0}};
    reg  [M-1:0]    loadY = {M{1'b0}};
    reg  [TAGW-1:0] loadTag = {TAGW{1'b0}};
    reg             loadValid = 1'b0;

    wire [M-1:0]    dpX;
    wire [TAGW-1:0] dpTag;
    wire            dpValid;
    wire [M-1:0]    stepX;
    wire [M-1:0]    stepY;
    wire [TAGW-1:0] stepTag;
    wire            stepValid;

    wire [M-1:0]    invA;
    wire [TAGW-1:0] invTag;
    wire            invValid;
    wire [M-1:0]    invR;
    wire [TAGW-1:0] invRTag;
    wire            invRValid;

    ecc_rho_core #(.M(M), .TAGW(TAGW), .DPCUT(DPCUT)) dut (
        .clk(clk),
        .loadX(loadX), .loadY(loadY), .loadTag(loadTag), .loadValid(loadValid),
        .dpX(dpX), .dpTag(dpTag), .dpValid(dpValid),
        .stepX(stepX), .stepY(stepY), .stepTag(stepTag), .stepValid(stepValid),
        .invA(invA), .invTag(invTag), .invValid(invValid),
        .invR(invR), .invRTag(invRTag), .invRValid(invRValid));

    ecc_inv131 uInv (
        .clk(clk), .a(invA), .tagIn(invTag), .validIn(invValid),
        .r(invR), .tagOut(invRTag), .validOut(invRValid));

    // ---- load one walk per clock ------------------------------------------
    integer s;
    integer errors = 0;
    integer retired = 0;
    integer dps = 0;
    integer loaded = 0;

    initial begin
        @(negedge clk);
        for (s = 0; s < SLOTS; s = s + 1) begin
            loadX <= trajX(s, 0);
            loadY <= trajY(s, 0);
            loadTag <= s[TAGW-1:0];
            loadValid <= 1'b1;
            loaded = loaded + 1;
            @(negedge clk);
        end
        loadValid <= 1'b0;
    end

    // ---- check every retired step against the reference -------------------
    integer done [0:SLOTS-1];
    integer t;
    integer slot;
    integer gaps = 0;
    integer filled = 0;

    initial begin
        for (s = 0; s < SLOTS; s = s + 1) done[s] = 0;
        @(negedge clk);
        for (t = 0; t < SLOTS*(STEPS+2); t = t + 1) begin
            if (stepValid) begin
                slot = stepTag;
                if (slot >= SLOTS) begin
                    $display("FAIL: step retired with tag %0d, only %0d slots",
                        slot, SLOTS);
                    errors = errors + 1;
                end else if (done[slot] >= STEPS) begin
                    // walked past the reference we generated; stop checking it
                    done[slot] = done[slot] + 1;
                end else begin
                    if (stepX !== trajX(slot, done[slot] + 1) ||
                        stepY !== trajY(slot, done[slot] + 1)) begin
                        $display("FAIL: slot %0d step %0d diverged from the reference",
                            slot, done[slot] + 1);
                        $display("  got  x %h", stepX);
                        $display("  want x %h", trajX(slot, done[slot] + 1));
                        errors = errors + 1;
                    end
                    done[slot] = done[slot] + 1;
                    retired = retired + 1;
                end
                if (filled == 0) filled = t;
            end else if (filled != 0 && retired < SLOTS*STEPS) begin
                gaps = gaps + 1;
            end
            if (dpValid) begin
                dps = dps + 1;
                if (weightOf(dpX) > DPCUT) begin
                    $display("FAIL: reported a distinguished point of weight %0d, cutoff %0d",
                        weightOf(dpX), DPCUT);
                    errors = errors + 1;
                end
            end
            @(negedge clk);
        end

        if (retired != SLOTS*STEPS) begin
            $display("FAIL: %0d steps retired, expected %0d",
                retired, SLOTS*STEPS);
            errors = errors + 1;
        end
        if (gaps != 0) begin
            $display("FAIL: %0d idle clocks after the pipeline filled, II is not 1",
                gaps);
            errors = errors + 1;
        end
        if (errors == 0)
            $display("PASS: %0d walks x %0d steps retired, II=1, ring latency %0d clk, %0d distinguished points, all trajectories match curves.Curve",
                SLOTS, STEPS, filled, dps);
        else
            $display("FAIL: %0d errors", errors);
        $finish;
    end

endmodule
`default_nettype wire
