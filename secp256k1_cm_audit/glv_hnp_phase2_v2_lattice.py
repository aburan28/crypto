def norm(v):
    return math.sqrt(sum(x * x for x in v))


def recover_v1(rows, m, n, S_KAN, d_secret):
    dim = 2 * m + 2
    for row in rows:
        if abs(row[dim - 1]) != S_KAN: continue
        sign = 1 if row[dim - 1] > 0 else -1
        d_cand = (sign * row[m]) % n
        if d_cand and d_cand == d_secret:
            return d_cand
    return None


def recover_v2(rows, m, n, lam, sigs, k1_bound, k2_bound, center, d_secret):
    """Read the nonce off the Kannan row, then solve for d."""
    S_K1, _S_D, S_K2, S_KAN = scales(n, k1_bound, k2_bound)
    off1, off2 = offsets(k1_bound, k2_bound, center)
    dim = 2 * m + 1
    B0inv = modinv(sigs[0]['B'] % n, n)
    for row in rows:
        if abs(row[dim - 1]) != S_KAN: continue
        sign = 1 if row[dim - 1] > 0 else -1
        if sign * row[0] % S_K1 or sign * row[m] % S_K2:
            continue
        k1_0 = sign * row[0] // S_K1 + off1
        k2_0 = sign * row[m] // S_K2 + off2
        k_full = (k1_0 + lam * k2_0) % n
        d_cand = (k_full - sigs[0]['A']) * B0inv % n
        if d_cand and d_cand == d_secret:
            return d_cand
    return None


def run_once(variant, curve, m, d_secret, k1_bound, seed=42,
             use_bkz=False, bkz_beta=20):
    """Returns (recovered, ||planted||, ||shortest reduced row||)."""
    p, b, n, lam, G = curve
    cfg = VARIANTS[variant]
    k2_bound = math.isqrt(n) + 1
    sigs = gen_signatures(G, d_secret, m, n, lam, p, k1_bound, k2_bound, seed)
    if len(sigs) < m:
        return None
    M = build(variant, sigs, n, lam, k1_bound, k2_bound)
    dim = len(M)
    A = IntegerMatrix.from_matrix(M)
    if use_bkz:
        BKZ.reduction(A, BKZ.Param(bkz_beta))
    else:
        LLL.reduction(A)
    rows = [[A[i][j] for j in range(dim)] for i in range(dim)]
    _, _, _, S_KAN = scales(n, k1_bound, k2_bound)
    if cfg['proj']:
        ok = recover_v2(rows, m, n, lam, sigs, k1_bound, k2_bound,
                        cfg['center'], d_secret) is not None
    else:
        ok = recover_v1(rows, m, n, S_KAN, d_secret) is not None
    pv = planted(variant, sigs, d_secret, n, k1_bound, k2_bound)
    nz = [norm(r) for r in rows if any(r)]
    return (ok, norm(pv), min(nz) if nz else float('nan'))


SEEDS = [42, 1234, 9999, 555, 31337]


def success_rate(variant, curve, m, k1_bound, seeds=SEEDS,
                 use_bkz=False, bkz_beta=20):
    """Returns (wins, total, mean sv/pv)."""
    wins, ratios = 0, []
    n = curve[2]
    for seed in seeds:
        d_trial = random.Random(seed + 7777).randint(1, n - 1)
        res = run_once(variant, curve, m, d_trial, k1_bound, seed,
                       use_bkz=use_bkz, bkz_beta=bkz_beta)
        if res is None: continue
        ok, pn, sn = res
        wins += bool(ok)
        ratios.append(sn / pn if pn else float('nan'))
    return wins, len(seeds), (sum(ratios) / len(ratios) if ratios else float('nan'))


