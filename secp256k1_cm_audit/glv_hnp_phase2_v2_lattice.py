def build_curve(p, n, seed=12345):
    lam, _ = glv_roots(n)
    if lam is None: return None
    for b_try in range(1, 60):
        P = find_point(p, b_try)
        if P is None: continue
        if ec_mul(P, n, p) is None:
            G = find_generator(p, b_try, n, seed)
            if G is None: continue
            return (p, b_try, n, lam, G)
    return None

def search_curves(lo, hi, want=4):
    out = []
    p = int(sympy.nextprime(lo))
    while p < hi and len(out) < want:
        if p % 3 == 1:
            eis = eisenstein_decompose(p)
            if eis is not None:
                for t in j0_traces(*eis):
                    nc = p + 1 - t
                    if nc < 2 or not sympy.isprime(nc) or nc % 3 != 1:
                        continue
                    cur = build_curve(p, nc)
                    if cur is not None:
                        out.append(cur)
                        break
        p = int(sympy.nextprime(p))
    return out

