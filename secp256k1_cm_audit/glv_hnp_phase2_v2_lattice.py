def modinv(a, m):
    return pow(a, -1, m)

def ec_add(P, Q, p):
    if P is None: return Q
    if Q is None: return P
    x1, y1 = P; x2, y2 = Q
    if x1 == x2:
        if (y1 + y2) % p == 0: return None
        s = 3 * x1 * x1 * modinv(2 * y1, p) % p
    else:
        s = (y2 - y1) * modinv(x2 - x1, p) % p
    x3 = (s * s - x1 - x2) % p
    y3 = (s * (x1 - x3) - y1) % p
    return (x3, y3)

def ec_mul(P, k, p):
    if k == 0: return None
    R, Q = None, P
    while k > 0:
        if k & 1: R = ec_add(R, Q, p)
        Q = ec_add(Q, Q, p)
        k >>= 1
    return R

def tonelli_shanks(nn, p):
    nn %= p
    if nn == 0: return 0
    if pow(nn, (p - 1) // 2, p) != 1: return None
    if p % 4 == 3: return pow(nn, (p + 1) // 4, p)
    q, s = p - 1, 0
    while q % 2 == 0: q //= 2; s += 1
    z = 2
    while pow(z, (p - 1) // 2, p) != p - 1: z += 1
    m, c, t, r = s, pow(z, q, p), pow(nn, q, p), pow(nn, (q + 1) // 2, p)
    while True:
        if t == 0: return 0
        if t == 1: return r
        i, tmp = 0, t
        while tmp != 1: tmp = tmp * tmp % p; i += 1
        bb = pow(c, 1 << (m - i - 1), p)
        m, c, t, r = i, bb * bb % p, t * bb * bb % p, r * bb % p

def find_point(p, b, seed=42):
    rng = random.Random(seed)
    for _ in range(10000):
        x = rng.randint(0, p - 1)
        rhs = (pow(x, 3, p) + b) % p
        y = tonelli_shanks(rhs, p)
        if y is not None and y != 0:
            return (x, y)
    return None

def find_generator(p, b, n, seed=12345):
    rng = random.Random(seed)
    for _ in range(10000):
        x = rng.randint(0, p - 1)
        rhs = (pow(x, 3, p) + b) % p
        y = tonelli_shanks(rhs, p)
        if y is None or y == 0: continue
        P = (x, y)
        if ec_mul(P, n, p) is None and P is not None:
            return P
    return None

def eisenstein_decompose(p):
    """
    (a,b) with a^2 - a*b + b^2 = p, for p = 1 mod 3.

    Cornacchia-Smith on 4p = x^2 + 3y^2, then (a,b) = ((x+y)/2, y).  O(log p),
    vs the O(sqrt p) brute force in glv_hnp_phase2_20bit.py:146 (which is
    correct; this is only faster).  Verified to agree with brute force on all
    p = 1 mod 3 in 8/12/17/20/24-bit ranges -- see E0b below.
    """
    if p % 3 != 1: return None
    x0 = tonelli_shanks((p - 3) % p, p)          # sqrt(-3) mod p
    if x0 is None: return None
    if x0 % 2 == 0: x0 = p - x0                  # need x0 = D = -3 (mod 2)
    a0, b0 = 2 * p, x0
    lim = math.isqrt(4 * p)
    while b0 > lim:
        a0, b0 = b0, a0 % b0
    rem = 4 * p - b0 * b0
    if rem % 3 != 0: return None
    t = rem // 3
    s = math.isqrt(t)
    if s * s != t: return None
    x, y = b0, s
    if (x + y) % 2 != 0: return None
    a, b = (x + y) // 2, y
    if a * a - a * b + b * b != p: return None
    return (a, b)


def eisenstein_decompose_bruteforce(p):
    """Verbatim from glv_hnp_phase2_20bit.py:146 -- the reference implementation."""
    for a in range(1, 2 * math.isqrt(p // 3) + 3):
        disc = 4 * p - 3 * a * a
        if disc < 0: break
        s = math.isqrt(disc)
        if s * s != disc: continue
        for num in (a + s, a - s):
            if num % 2 == 0:
                b = num // 2
                if b >= 0 and a * a - a * b + b * b == p:
                    return (a, b)
    return None

def j0_traces(a, b):
    return [2*a - b, -2*a + b, -(a + b), a + b, 2*b - a, a - 2*b]

def glv_roots(n):
    sq = tonelli_shanks((n - 3) % n, n)
    if sq is None: return None, None
    inv2 = modinv(2, n)
    r1 = (n - 1 + sq) * inv2 % n
    r2 = (n - 1 + (n - sq)) * inv2 % n
    if (r1 * r1 + r1 + 1) % n != 0: r1, r2 = r2, r1
    if (r1 * r1 + r1 + 1) % n != 0: return None, None
    return min(r1, r2), max(r1, r2)

def lam_star(lam, n):
    return min(lam % n, n - (lam % n)) / n


