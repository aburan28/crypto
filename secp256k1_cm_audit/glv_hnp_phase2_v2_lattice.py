def offsets(k1_bound, k2_bound, center):
    return (k1_bound // 2, k2_bound // 2) if center else (0, 0)


def build_v1(sigs, n, lam, k1_bound, k2_bound, center=False):
    """Baseline (2026-06-15) lattice, dim 2m+2, optionally centered."""
    m = len(sigs)
    dim = 2 * m + 2
    S_K1, S_D, S_K2, S_KAN = scales(n, k1_bound, k2_bound)
    off1, off2 = offsets(k1_bound, k2_bound, center)
    M = [[0] * dim for _ in range(dim)]
    for i in range(m):
        M[i][i] = n * S_K1
    for i in range(m):
        M[m][i] = sigs[i]['B'] * S_K1
    M[m][m] = S_D
    for i in range(m):
        M[m + 1 + i][i] = -lam * S_K1
        M[m + 1 + i][m + 1 + i] = S_K2
    for i in range(m):
        Ap = (sigs[i]['A'] - off1 - lam * off2) % n
        M[2 * m + 1][i] = Ap * S_K1
    M[2 * m + 1][dim - 1] = S_KAN
    return M


def planted_v1(sigs, d_secret, n, k1_bound, k2_bound, center=False):
    m = len(sigs)
    S_K1, S_D, S_K2, S_KAN = scales(n, k1_bound, k2_bound)
    off1, off2 = offsets(k1_bound, k2_bound, center)
    v = [0] * (2 * m + 2)
    for i in range(m):
        v[i] = (sigs[i]['k1'] - off1) * S_K1
        v[m + 1 + i] = (sigs[i]['k2'] - off2) * S_K2
    v[m] = d_secret * S_D
    v[2 * m + 1] = S_KAN
    return v


def build_v2(sigs, n, lam, k1_bound, k2_bound, center=False):
    """Projected lattice (d-column removed), dim 2m+1, full rank."""
    m = len(sigs)
    dim = 2 * m + 1
    S_K1, _S_D, S_K2, S_KAN = scales(n, k1_bound, k2_bound)
    off1, off2 = offsets(k1_bound, k2_bound, center)
    u = modinv(sigs[0]['B'] % n, n)
    C = [sigs[i]['B'] * u % n for i in range(m)]      # C[0] == 1
    assert C[0] == 1
    M = [[0] * dim for _ in range(dim)]
    # row 0: g = (1, C_1, ..., C_{m-1})
    for i in range(m):
        M[0][i] = C[i] * S_K1
    # rows 1..m-1: n*e_j, j = 1..m-1
    for j in range(1, m):
        M[j][j] = n * S_K1
    # rows m..2m-1: the k2 rows
    for i in range(m):
        M[m + i][i] = -lam * S_K1
        M[m + i][m + i] = S_K2
    # row 2m: Kannan
    for i in range(m):
        Ap = (sigs[i]['A'] - off1 - lam * off2) % n
        M[2 * m][i] = Ap * S_K1
    M[2 * m][dim - 1] = S_KAN
    return M


def planted_v2(sigs, n, k1_bound, k2_bound, center=False):
    m = len(sigs)
    S_K1, _S_D, S_K2, S_KAN = scales(n, k1_bound, k2_bound)
    off1, off2 = offsets(k1_bound, k2_bound, center)
    v = [0] * (2 * m + 1)
    for i in range(m):
        v[i] = (sigs[i]['k1'] - off1) * S_K1
        v[m + i] = (sigs[i]['k2'] - off2) * S_K2
    v[2 * m] = S_KAN
    return v


VARIANTS = {
    'V1':  dict(proj=False, center=False),
    'V1c': dict(proj=False, center=True),
    'V2':  dict(proj=True,  center=False),
    'V2c': dict(proj=True,  center=True),
}


def build(variant, sigs, n, lam, k1_bound, k2_bound):
    cfg = VARIANTS[variant]
    f = build_v2 if cfg['proj'] else build_v1
    return f(sigs, n, lam, k1_bound, k2_bound, center=cfg['center'])


def planted(variant, sigs, d_secret, n, k1_bound, k2_bound):
    cfg = VARIANTS[variant]
    if cfg['proj']:
        return planted_v2(sigs, n, k1_bound, k2_bound, center=cfg['center'])
    return planted_v1(sigs, d_secret, n, k1_bound, k2_bound, center=cfg['center'])


