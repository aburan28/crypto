def log_det(M_rows):
    """log(covolume) of the lattice generated by M_rows (any rank)."""
    A = IntegerMatrix.from_matrix(M_rows)
    LLL.reduction(A)
    keep = [[A[i][j] for j in range(A.ncols)] for i in range(A.nrows)]
    keep = [r for r in keep if any(r)]
    B = IntegerMatrix.from_matrix(keep)
    G = GSO.Mat(B)
    G.update_gso()
    return 0.5 * sum(math.log(G.get_r(i, i)) for i in range(B.nrows)), B.nrows


def gaussian_heuristic(logdet, dim):
    return math.exp(0.5 * math.log(dim / (2 * math.pi * math.e)) + logdet / dim)


