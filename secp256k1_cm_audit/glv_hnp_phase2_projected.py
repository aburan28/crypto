def trial(curve, m, K1, seed, variant, beta=None, want_diag=False):
    p, b, n, lam, G = curve
    K2 = math.isqrt(n) + 1
    d_secret = random.Random(seed + 7777).randint(1, n - 1)
    sigs = gen_signatures(G, d_secret, m, n, lam, p, K1, K2, seed)
    if len(sigs) < m:
        return None
    S_K1, S_D, S_K2, S_KAN = scales(n, K1, K2)

    if variant == 'O':
        rows = reduce_rows(build_lattice_O(sigs, n, lam, K1, K2), beta)
        ok = recover_O(rows, m, n, S_KAN, d_secret) is not None
        pv = planted_O(sigs, d_secret, n, K1, K2)
    elif variant == 'R':
        rows = reduce_rows(build_lattice_R(sigs, n, lam, K1, K2), beta)
        ok = recover_R(rows, sigs, n, lam, K1, K2, d_secret) is not None
        pv = planted_R(sigs, n, K1, K2)
    else:
        basis = reduce_rows(build_lattice_B(sigs, n, lam, K1, K2), beta)
        ok = recover_B(basis, sigs, n, lam, K1, K2, d_secret) is not None
        pv = None
        rows = basis

    if not want_diag:
        return ok
    sv = min((r for r in rows if any(r)), key=norm)
    return ok, norm(sv), (norm(pv) if pv else float('nan')), sv, pv


def rate(curve, m, K1, seeds, variant, beta=None):
    w = 0
    for s in seeds:
        r = trial(curve, m, K1, s, variant, beta)
        if r: w += 1
    return w, len(seeds)


