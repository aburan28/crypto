def gh(dim, det):
    """Gaussian heuristic for lambda_1: sqrt(dim/(2*pi*e)) * det^(1/dim)."""
    return math.sqrt(dim / (2 * math.pi * math.e)) * math.exp(math.log(det) / dim)

def predict(variant, m, n, K1, K2):
    """(gh, E||planted||, gap = gh/||planted||).  gap > 1 => planted plausibly
    the shortest vector, i.e. LLL/BKZ has a target to find."""
    S_K1, S_D, S_K2, S_KAN = scales(n, K1, K2)
    log_det_O = (3 * m + 1) * math.log(n) - m * (math.log(K1) + math.log(K2))
    if variant == 'O':
        dim = 2 * m + 2
        ld = log_det_O
        pv2 = (m * (K1 * S_K1) ** 2 / 3.0 + (n * S_D) ** 2 / 3.0
               + m * (K2 * S_K2) ** 2 / 3.0 + S_KAN ** 2)
    elif variant == 'R':
        dim = 2 * m + 1
        ld = log_det_O - math.log(n * S_D)
        pv2 = (m * (K1 * S_K1) ** 2 / 3.0
               + m * (K2 * S_K2) ** 2 / 3.0 + S_KAN ** 2)
    else:                                            # 'B'
        dim = 2 * m
        ld = log_det_O - math.log(n * S_D) - math.log(S_KAN)
        pv2 = (m * (K1 * S_K1) ** 2 / 3.0 + m * (K2 * S_K2) ** 2 / 3.0)
    g = math.sqrt(dim / (2 * math.pi * math.e)) * math.exp(ld / dim)
    pv = math.sqrt(pv2)
    return g, pv, g / pv

def eff_wall(variant, m, n, K2):
    """Largest real K1 with gap >= 1, by bisection on K1."# noqa"""
    lo, hi = 1.0, float(n)
    if predict(variant, m, n, max(1, int(lo)), K2)[2] < 1.0:
        return 0.0
    for _ in range(60):
        mid = (lo + hi) / 2
        S = max(1, int(mid))
        if predict(variant, m, n, S, K2)[2] >= 1.0:
            lo = mid
        else:
            hi = mid
    return lo


