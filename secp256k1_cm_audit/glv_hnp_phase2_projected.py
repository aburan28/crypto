def build_projected_lattice(sigs, n, lam, k1_bound, k2_bound):
    """R1.  Columns: 0..m-1 = k1 (scale S_K1), m..2m-1 = k2 (scale S_K2),
    2m = Kannan.  Rows: m modular, 1 d-row, m k2-rows, 1 A-row = 2m+2 rows in
    2m+1 columns (rank 2m+1; the dependency is exactly the image of the
    trivial vector, which projects to 0)."""
    m = len(sigs)
    S_K1, S_D, S_K2, S_KAN = scales(n, k1_bound, k2_bound)
    dim = 2 * m + 1
    M = []
    for i in range(m):                       # modular rows
        r = [0] * dim; r[i] = n * S_K1; M.append(r)
    r = [0] * dim                            # d-row (its S_D entry is deleted)
    for i in range(m):
        r[i] = sigs[i]['B'] * S_K1
    M.append(r)
    for i in range(m):                       # k2-rows
        r = [0] * dim; r[i] = -lam * S_K1; r[m + i] = S_K2; M.append(r)
    r = [0] * dim                            # A-row + Kannan
    for i in range(m):
        r[i] = sigs[i]['A'] * S_K1
    r[2 * m] = S_KAN
    M.append(r)
    return M


def planted_vector_proj(sigs, n, k1_bound, k2_bound):
    """(k1_i*S_K1, k2_i*S_K2, S_KANNAN) — the R0 planted vector with the
    d-coordinate dropped."""
    m = len(sigs)
    S_K1, S_D, S_K2, S_KAN = scales(n, k1_bound, k2_bound)
    v = [0] * (2 * m + 1)
    for i in range(m):
        v[i] = sigs[i]['k1'] * S_K1
        v[m + i] = sigs[i]['k2'] * S_K2
    v[2 * m] = S_KAN
    return v


def recover_d_proj(rows, sigs, n, lam, k1_bound, k2_bound, d_secret):
    """R1 recovery.  d is not a lattice coordinate any more: read (k1_0, k2_0)
    off a row whose Kannan coordinate is +-S_KANNAN and solve the congruence
    A_0 + B_0*d = k1_0 + lam*k2_0 (mod n) for d."""
    m = len(sigs)
    S_K1, S_D, S_K2, S_KAN = scales(n, k1_bound, k2_bound)
    for row in rows:
        last = row[2 * m]
        if abs(last) != S_KAN:
            continue
        sign = 1 if last > 0 else -1
        for i in range(m):
            a, b = sign * row[i], sign * row[m + i]
            if a % S_K1 or b % S_K2:
                continue
            k1_i, k2_i = a // S_K1, b // S_K2
            B = sigs[i]['B']
            if B % n == 0:
                continue
            d_cand = (k1_i + lam * k2_i - sigs[i]['A']) * modinv(B, n) % n
            if d_cand == d_secret:
                return d_cand
    return None


