# R2 — explicit BDD, no Kannan embedding
# ===========================================================================

def build_bdd_lattice(sigs, n, lam, k1_bound, k2_bound):
    """L2 in the 2m-dim (k1|k2) space: modular rows, d-row, k2-rows."""
    m = len(sigs)
    S_K1, S_D, S_K2, S_KAN = scales(n, k1_bound, k2_bound)
    dim = 2 * m
    M = []
    for i in range(m):
        r = [0] * dim; r[i] = n * S_K1; M.append(r)
    r = [0] * dim
    for i in range(m):
        r[i] = sigs[i]['B'] * S_K1
    M.append(r)
    for i in range(m):
        r = [0] * dim; r[i] = -lam * S_K1; r[m + i] = S_K2; M.append(r)
    return M


def bdd_target(sigs, n, k1_bound, k2_bound):
    """t = (-A_i*S_K1, 0, ..., 0).  The lattice vector w = d*row_d + sum k2_i
    row_k2i - sum c_i row_i has k1-block (k1_i - A_i)*S_K1 and k2-block
    k2_i*S_K2, so w is within ~||(k1*S_K1, k2*S_K2)|| of t."""
    m = len(sigs)
    S_K1, S_D, S_K2, S_KAN = scales(n, k1_bound, k2_bound)
    t = [0] * (2 * m)
    for i in range(m):
        t[i] = -sigs[i]['A'] * S_K1
    return t


def recover_d_bdd(w, sigs, n, lam, k1_bound, k2_bound, d_secret):
    m = len(sigs)
    S_K1, S_D, S_K2, S_KAN = scales(n, k1_bound, k2_bound)
    for i in range(m):
        if w[i] % S_K1 or w[m + i] % S_K2:
            continue
        k1_i = w[i] // S_K1 + sigs[i]['A']
        k2_i = w[m + i] // S_K2
        B = sigs[i]['B']
        if B % n == 0:
            continue
        d_cand = (k1_i + lam * k2_i - sigs[i]['A']) * modinv(B, n) % n
        if d_cand == d_secret:
            return d_cand
    return None


def babai_nearest_plane(M_rows, target):
    """Babai nearest-plane on an LLL-reduced copy of M_rows.  Returns the
    lattice vector closest to `target` found by the algorithm."""
    A = IntegerMatrix.from_matrix(M_rows)
    LLL.reduction(A)
    rows = [[A[i][j] for j in range(A.ncols)] for i in range(A.nrows)]
    keep = [r for r in rows if any(r)]
    B = IntegerMatrix.from_matrix(keep)
    G = GSO.Mat(B)
    G.update_gso()
    coeffs = G.babai([int(x) for x in target])
    w = [0] * B.ncols
    for i, c in enumerate(coeffs):
        if c:
            for j in range(B.ncols):
                w[j] += c * keep[i][j]
    return w


