# Variant B — projected lattice (d-column deleted)
# ---------------------------------------------------------------------------

def build_projected_lattice(sigs, n, lam, k1_bound, k2_bound):
    """The (2m+2) x (2m+1) generator matrix of pi(L), column m deleted.

    Rank is 2m+1, not 2m+2: n*row_m - sum_i B_i*row_i = 0 after the deletion.
    fpylll's LLL tolerates the rank deficiency and emits a zero row.
    Column layout: [0, m) = k1 block, [m, 2m) = k2 block, 2m = Kannan.
    """
    m = len(sigs)
    dim = 2 * m + 1
    S_K1, _S_D, S_K2, S_KANNAN = scales(n, k1_bound, k2_bound)
    M = [[0] * dim for _ in range(2 * m + 2)]
    for i in range(m):                                  # modular rows
        M[i][i] = n * S_K1
    for i in range(m):                                  # d row (d-column gone)
        M[m][i] = sigs[i]['B'] * S_K1
    for i in range(m):                                  # GLV rows
        M[m + 1 + i][i] = -lam * S_K1
        M[m + 1 + i][m + i] = S_K2
    for i in range(m):                                  # Kannan / target row
        M[2 * m + 1][i] = sigs[i]['A'] * S_K1
    M[2 * m + 1][dim - 1] = S_KANNAN
    return M


def projected_planted(sigs, n, k1_bound, k2_bound):
    """pi(v_planted) = (k1_i*S_K1, k2_i*S_K2, S_KANNAN)."""
    m = len(sigs)
    S_K1, _S_D, S_K2, S_KAN = scales(n, k1_bound, k2_bound)
    v = [0] * (2 * m + 1)
    for i in range(m):
        v[i] = sigs[i]['k1'] * S_K1
        v[m + i] = sigs[i]['k2'] * S_K2
    v[2 * m] = S_KAN
    return v


def d_from_k(k1_i, k2_i, sig, n, lam):
    """A + d*B = k1 + lam*k2 (mod n)  =>  d."""
    B = sig['B'] % n
    if B == 0:
        return None
    return (k1_i + lam * k2_i - sig['A']) * modinv(B, n) % n


def recover_d_projected(rows, sigs, n, lam, k1_bound, k2_bound):
    """Scan reduced rows for one with |last| = S_KANNAN, then solve for d.

    Consistency-checked: the same d must come out of every index i, which makes a
    false positive vanishingly unlikely.  Returns d or None.  Does NOT look at
    d_secret, so this is an honest attack, not an oracle.
    """
    m = len(sigs)
    S_K1, _S_D, S_K2, S_KAN = scales(n, k1_bound, k2_bound)
    for row in rows:
        last = row[2 * m]
        if abs(last) != S_KAN:
            continue
        sign = 1 if last > 0 else -1
        k1s, k2s, ok = [], [], True
        for i in range(m):
            a, b = sign * row[i], sign * row[m + i]
            if a % S_K1 or b % S_K2:
                ok = False
                break
            k1s.append(a // S_K1)
            k2s.append(b // S_K2)
        if not ok:
            continue
        cands = {d_from_k(k1s[i], k2s[i], sigs[i], n, lam) for i in range(m)}
        cands.discard(None)
        if len(cands) == 1:
            d = cands.pop()
            if d:
                return d
    return None


# ---------------------------------------------------------------------------
# Variant C — explicit CVP (Babai nearest-plane), no Kannan embedding
# ---------------------------------------------------------------------------

def build_homogeneous_lattice(sigs, n, lam, k1_bound, k2_bound):
    """L0 subset Z^{2m}: rank 2m from 2m+1 generators.  Columns [0,m)=k1, [m,2m)=k2."""
    m = len(sigs)
    dim = 2 * m
    S_K1, _S_D, S_K2, _S_KAN = scales(n, k1_bound, k2_bound)
    M = [[0] * dim for _ in range(2 * m + 1)]
    for i in range(m):
        M[i][i] = n * S_K1
    for i in range(m):
        M[m][i] = sigs[i]['B'] * S_K1
    for i in range(m):
        M[m + 1 + i][i] = -lam * S_K1
        M[m + 1 + i][m + i] = S_K2
    return M


def babai_nearest_plane(basis_rows, target):
    """Babai nearest plane against an LLL-reduced basis (exact rational GS in floats).

    basis_rows: list of independent integer rows.  Returns the lattice vector.
    """
    k = len(basis_rows)
    dim = len(basis_rows[0])
    # Gram-Schmidt in floating point (dimensions here are small: 2m <= 64).
    bstar = []
    mu = [[0.0] * k for _ in range(k)]
    for i in range(k):
        v = [float(x) for x in basis_rows[i]]
        for j in range(i):
            nj = sum(y * y for y in bstar[j])
            if nj == 0.0:
                mu[i][j] = 0.0
                continue
            mu[i][j] = sum(float(basis_rows[i][t]) * bstar[j][t]
                           for t in range(dim)) / nj
            for t in range(dim):
                v[t] -= mu[i][j] * bstar[j][t]
        bstar.append(v)
    w = [float(x) for x in target]
    coeffs = [0] * k
    for i in range(k - 1, -1, -1):
        nb = sum(y * y for y in bstar[i])
        if nb == 0.0:
            continue
        c = sum(w[t] * bstar[i][t] for t in range(dim)) / nb
        ci = int(math.floor(c + 0.5))
        coeffs[i] = ci
        if ci:
            for t in range(dim):
                w[t] -= ci * float(basis_rows[i][t])
    out = [0] * dim
    for i in range(k):
        if coeffs[i]:
            for t in range(dim):
                out[t] += coeffs[i] * basis_rows[i][t]
    return out


def run_cvp(sigs, n, lam, k1_bound, k2_bound):
    """Variant C.  Returns recovered d or None."""
    m = len(sigs)
    S_K1, _S_D, S_K2, _S_KAN = scales(n, k1_bound, k2_bound)
    M = build_homogeneous_lattice(sigs, n, lam, k1_bound, k2_bound)
    A = IntegerMatrix.from_matrix(M)
    LLL.reduction(A)
    rows = [[A[i][j] for j in range(2 * m)] for i in range(A.nrows)]
    rows = [r for r in rows if any(r)]                  # drop the zero row
    t = [0] * (2 * m)
    for i in range(m):
        t[i] = -(sigs[i]['A'] % n) * S_K1               # target is -t (see docstring)
    u = babai_nearest_plane(rows, t)
    v = [t[j] - u[j] for j in range(2 * m)]             # v = t_pos + u' ; sign folded
    v = [-x for x in v]
    cands = set()
    for i in range(m):
        if v[i] % S_K1 or v[m + i] % S_K2:
            return None
        d = d_from_k(v[i] // S_K1, v[m + i] // S_K2, sigs[i], n, lam)
        if d is None:
            return None
        cands.add(d)
    if len(cands) == 1:
        d = cands.pop()
        return d or None
    return None


