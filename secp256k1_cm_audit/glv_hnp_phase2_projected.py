def run_R0(curve, m, d_secret, k1_bound, seed, algo='LLL', beta=20):
    p, b, n, lam, G = curve
    k2b = math.isqrt(n) + 1
    sigs = gen_signatures(G, d_secret, m, n, lam, p, k1_bound, k2b, seed)
    if len(sigs) < m:
        return None
    M = build_glv_lattice(sigs, n, lam, k1_bound, k2b)
    A = IntegerMatrix.from_matrix(M)
    if algo == 'LLL':
        LLL.reduction(A)
    else:
        BKZ.reduction(A, BKZ.Param(beta))
    rows = [[A[i][j] for j in range(A.ncols)] for i in range(A.nrows)]
    _, _, _, S_KAN = scales(n, k1_bound, k2b)
    ok = recover_d(rows, m, n, S_KAN, d_secret) is not None
    pv = norm(planted_vector(sigs, d_secret, n, k1_bound, k2b))
    sv = min(norm(r) for r in rows if any(r))
    return ok, pv, sv, sigs


def run_R1(curve, m, d_secret, k1_bound, seed, algo='LLL', beta=20):
    p, b, n, lam, G = curve
    k2b = math.isqrt(n) + 1
    sigs = gen_signatures(G, d_secret, m, n, lam, p, k1_bound, k2b, seed)
    if len(sigs) < m:
        return None
    M = build_projected_lattice(sigs, n, lam, k1_bound, k2b)
    A = IntegerMatrix.from_matrix(M)
    if algo == 'LLL':
        LLL.reduction(A)
    else:
        BKZ.reduction(A, BKZ.Param(beta))
    rows = [[A[i][j] for j in range(A.ncols)] for i in range(A.nrows)]
    ok = recover_d_proj(rows, sigs, n, lam, k1_bound, k2b, d_secret) is not None
    pv = norm(planted_vector_proj(sigs, n, k1_bound, k2b))
    nz = [r for r in rows if any(r)]
    sv = min(norm(r) for r in nz) if nz else float('nan')
    return ok, pv, sv, sigs


def run_R2(curve, m, d_secret, k1_bound, seed):
    p, b, n, lam, G = curve
    k2b = math.isqrt(n) + 1
    sigs = gen_signatures(G, d_secret, m, n, lam, p, k1_bound, k2b, seed)
    if len(sigs) < m:
        return None
    M = build_bdd_lattice(sigs, n, lam, k1_bound, k2b)
    t = bdd_target(sigs, n, k1_bound, k2b)
    w = babai_nearest_plane(M, t)
    ok = recover_d_bdd(w, sigs, n, lam, k1_bound, k2b, d_secret) is not None
    return ok, 0.0, 0.0, sigs


RUNNERS = {'R0': run_R0, 'R1': run_R1, 'R2': run_R2}


def success_rate(kind, curve, m, k1_bound, seeds, **kw):
    n = curve[2]
    wins, ratios = 0, []
    for seed in seeds:
        d_trial = random.Random(seed + 7777).randint(1, n - 1)
        res = RUNNERS[kind](curve, m, d_trial, k1_bound, seed, **kw)
        if res is None:
            continue
        ok, pv, sv, _ = res
        wins += bool(ok)
        if pv:
            ratios.append(sv / pv)
    return wins, len(seeds), (sum(ratios) / len(ratios) if ratios else float('nan'))


