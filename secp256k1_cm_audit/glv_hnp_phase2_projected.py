def trial(curve, m, k1_bound, seed, variant):
    """One (curve, m, K1, seed) instance.  Returns (recovered, pn, sv, sigs_ok)."""
    p, b, n, lam, G = curve
    k2_bound = math.isqrt(n) + 1
    d_secret = random.Random(seed + 7777).randint(1, n - 1)
    sigs = gen_signatures(G, d_secret, m, n, lam, p, k1_bound, k2_bound, seed)
    if len(sigs) < m:
        return None
    _S_K1, _S_D, _S_K2, S_KAN = scales(n, k1_bound, k2_bound)

    if variant == 'A':
        M = build_glv_lattice(sigs, n, lam, k1_bound, k2_bound)
        dim = 2 * m + 2
        A = IntegerMatrix.from_matrix(M)
        LLL.reduction(A)
        rows = [[A[i][j] for j in range(dim)] for i in range(dim)]
        got = recover_d(rows, m, n, S_KAN, d_secret)
        pn = norm(planted_vector(sigs, d_secret, n, k1_bound, k2_bound))
        sv = min(norm(r) for r in rows if any(r))
        return (got is not None, pn, sv)

    if variant == 'B':
        M = build_projected_lattice(sigs, n, lam, k1_bound, k2_bound)
        dim = 2 * m + 1
        A = IntegerMatrix.from_matrix(M)
        LLL.reduction(A)
        rows = [[A[i][j] for j in range(dim)] for i in range(A.nrows)]
        got = recover_d_projected(rows, sigs, n, lam, k1_bound, k2_bound)
        pn = norm(projected_planted(sigs, n, k1_bound, k2_bound))
        nz = [r for r in rows if any(r)]
        sv = min(norm(r) for r in nz) if nz else float('nan')
        return (got == d_secret, pn, sv)

    if variant == 'C':
        got = run_cvp(sigs, n, lam, k1_bound, k2_bound)
        pn = norm(projected_planted(sigs, n, k1_bound, k2_bound))
        return (got == d_secret, pn, float('nan'))

    raise ValueError(variant)


def rate(curve, m, k1_bound, seeds, variant):
    wins, ratios = 0, []
    for s in seeds:
        r = trial(curve, m, k1_bound, s, variant)
        if r is None:
            continue
        ok, pn, sv = r
        wins += bool(ok)
        if pn and not math.isnan(sv):
            ratios.append(sv / pn)
    mr = sum(ratios) / len(ratios) if ratios else float('nan')
    return wins, len(seeds), mr


