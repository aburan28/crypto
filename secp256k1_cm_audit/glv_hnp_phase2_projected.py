"""
GLV-HNP Phase 2 — Thread 23: make the planted vector the target of the search.

Background (2026-07-29 log, EXP T5)
-----------------------------------
In the (2m+2)-dimensional Phase-2 lattice built by
`glv_hnp_phase2_lambda_threshold.py:254 build_glv_lattice()`, the vector

    v_triv = n * S_D * e_m                          (the d-column axis vector)

is ALWAYS in the lattice, because  n*row_m - sum_i B_i*row_i  =  (0,...,0, n*S_D, 0,...,0).
With S_D = 1 its norm is exactly n, while

    ||v_planted||^2 ~ n^2 * (2m/3 + 4/3)     =>   ||v_planted|| ~ 3.05 n   at m=12.

So v_triv is ~3x shorter than the planted vector on EVERY instance: LLL's shortest
output row is v_triv with 100% of its energy in the d-column (measured: |sv[m]|/n =
1.0000 on all curves tested).  The planted vector is never lambda_1, and no choice of
S_D changes this (both vectors scale linearly in S_D).  Recovery is therefore a BDD /
coset condition, not an SVP condition.

v_triv carries no information: d is only defined mod n, so "d -> d + n" is the trivial
symmetry of the problem and v_triv is exactly that symmetry sitting inside the lattice.

Thread 23 — the reformulation
-----------------------------
Quotient the symmetry out.  Two ways, both implemented here:

  VARIANT B ("projected"): delete column m.  The kernel of the coordinate projection
    pi: Z^{2m+2} -> Z^{2m+1} intersected with L is exactly <v_triv>, so pi(L) is a rank
    (2m+1) lattice with det = det(L)/(n*S_D) and v_triv |-> 0.  The planted vector
    projects to (k1_i*S_K1, k2_i*S_K2, S_KANNAN), which still identifies the secret:
    from any single k1_i, k2_i we get d algebraically via
        A_i + d*B_i = k1_i + lam*k2_i  (mod n)   =>   d = (k1_i + lam*k2_i - A_i)/B_i.

  VARIANT C ("CVP"): drop the d-column AND the Kannan embedding, and solve the
    inhomogeneous problem directly.  Let L0 subset Z^{2m} be generated by
        n*S_K1*e_i                       (i < m)          [modular rows]
        (-lam*S_K1 @ col i, S_K2 @ col m+i)                [GLV rows]
        (B_0*S_K1, ..., B_{m-1}*S_K1, 0, ..., 0)           [the d row]
    and t = (A_0*S_K1, ..., A_{m-1}*S_K1, 0, ..., 0).  Then
        v = (k1_i*S_K1, k2_i*S_K2) = t + u  with  u in L0,
    so u is (heuristically) the closest lattice vector to -t.  Babai nearest-plane on
    an LLL-reduced basis of L0 gives u; v = t + u; read off k1, k2; solve for d.
    rank(L0) = 2m, det(L0) = n^{m-1} * S_K1^m * S_K2^m.

VARIANT A is the unmodified 2026-07-29 baseline, replicated verbatim for comparison.

Falsifier (stated in the 2026-07-29 log entry, quoted verbatim)
--------------------------------------------------------------
  "if sv/pv rises above 1 after the reformulation and the K1 wall in T4 moves outward
   on the lam*=0.07 curve (currently K1~4-6), the reformulation is a real improvement;
   if the wall stays at K1~4-6, then the wall is information-theoretic and Phase 2 is
   at its ceiling."

Experiments
-----------
  X1  correctness: does the algebraic d-recovery from (k1,k2) reproduce d_secret?
  X2  is the planted vector lambda_1 now?  (sv/pv for A vs B)
  X3  the T4 K1 grid, all three variants, on the historical success/failure pair.
  X4  T4b analogue: does more data (m) rescue variant B/C at the wall?

Run: python3 glv_hnp_phase2_projected.py
"""

