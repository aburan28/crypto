def scales(n, k1_bound, k2_bound):
    return (n // k1_bound, 1, max(1, n // k2_bound), n)

def gen_signatures(G, d_secret, m, n, lam, p, k1_bound, k2_bound, seed=42):
    rng = random.Random(seed)
    sigs = []
    attempts = 0
    while len(sigs) < m and attempts < 200000:
        attempts += 1
        k1 = rng.randint(0, k1_bound - 1)
        k2 = rng.randint(0, k2_bound - 1)
        k_full = (k1 + lam * k2) % n
        if k_full == 0: continue
        R = ec_mul(G, k_full, p)
        if R is None: continue
        r = R[0] % n
        if r == 0: continue
        h = rng.randint(0, n - 1)
        s = modinv(k_full, n) * (h + d_secret * r) % n
        if s == 0: continue
        s_inv = modinv(s, n)
        A = h * s_inv % n
        B = r * s_inv % n
        assert (A + B * d_secret) % n == k_full
        sigs.append({'A': A, 'B': B, 'k1': k1, 'k2': k2})
    return sigs


# ---------------------------------------------------------------------------
# L_O -- the original Phase-2 lattice (verbatim, dim 2m+2)
# ---------------------------------------------------------------------------

def build_lattice_O(sigs, n, lam, k1_bound, k2_bound):
    m = len(sigs)
    dim = 2 * m + 2
    S_K1, S_D, S_K2, S_KAN = scales(n, k1_bound, k2_bound)
    M = [[0] * dim for _ in range(dim)]
    for i in range(m):
        M[i][i] = n * S_K1
    for i in range(m):
        M[m][i] = sigs[i]['B'] * S_K1
    M[m][m] = S_D
    for i in range(m):
        M[m + 1 + i][i] = -lam * S_K1
        M[m + 1 + i][m + 1 + i] = S_K2
    for i in range(m):
        M[2 * m + 1][i] = sigs[i]['A'] * S_K1
    M[2 * m + 1][dim - 1] = S_KAN
    return M

def planted_O(sigs, d_secret, n, k1_bound, k2_bound):
    m = len(sigs)
    S_K1, S_D, S_K2, S_KAN = scales(n, k1_bound, k2_bound)
    v = [0] * (2 * m + 2)
    for i in range(m):
        v[i] = sigs[i]['k1'] * S_K1
        v[m + 1 + i] = sigs[i]['k2'] * S_K2
    v[m] = d_secret * S_D
    v[2 * m + 1] = S_KAN
    return v

def recover_O(rows, m, n, S_KAN, d_secret):
    dim = 2 * m + 2
    for row in rows:
        last = row[dim - 1]
        if abs(last) != S_KAN: continue
        sign = 1 if last > 0 else -1
        d_cand = (sign * row[m]) % n
        if d_cand == 0: continue
        if d_cand == d_secret:
            return d_cand
    return None


# ---------------------------------------------------------------------------
# L_R -- d-column deleted (dim 2m+1); d recovered algebraically
# ---------------------------------------------------------------------------

def build_lattice_R(sigs, n, lam, k1_bound, k2_bound):
    """2m+2 generating rows spanning a rank-(2m+1) lattice.  Column layout:
       [0..m-1] = k1 columns, [m..2m-1] = k2 columns, [2m] = Kannan."""
    m = len(sigs)
    dim = 2 * m + 1
    S_K1, S_D, S_K2, S_KAN = scales(n, k1_bound, k2_bound)
    rows = []
    for i in range(m):                              # n*S_K1*e_i
        r = [0] * dim; r[i] = n * S_K1; rows.append(r)
    r = [0] * dim                                   # d-row (no d column now)
    for i in range(m):
        r[i] = sigs[i]['B'] * S_K1
    rows.append(r)
    for i in range(m):                              # k2 rows
        r = [0] * dim
        r[i] = -lam * S_K1
        r[m + i] = S_K2
        rows.append(r)
    r = [0] * dim                                   # Kannan row
    for i in range(m):
        r[i] = sigs[i]['A'] * S_K1
    r[dim - 1] = S_KAN
    rows.append(r)
    return rows

def planted_R(sigs, n, k1_bound, k2_bound):
    m = len(sigs)
    S_K1, S_D, S_K2, S_KAN = scales(n, k1_bound, k2_bound)
    v = [0] * (2 * m + 1)
    for i in range(m):
        v[i] = sigs[i]['k1'] * S_K1
        v[m + i] = sigs[i]['k2'] * S_K2
    v[2 * m] = S_KAN
    return v

def d_from_k(sigs, k1s, k2s, n, lam):
    """d = (k1_i + lam*k2_i - A_i) * B_i^{-1} mod n, required consistent for all i."""
    d0 = None
    for i, sg in enumerate(sigs):
        try:
            binv = modinv(sg['B'], n)
        except ValueError:
            return None
        d_i = (k1s[i] + lam * k2s[i] - sg['A']) * binv % n
        if d0 is None:
            d0 = d_i
        elif d_i != d0:
            return None
    return d0

def recover_R(rows, sigs, n, lam, k1_bound, k2_bound, d_secret):
    """Read (k1,k2) off any row whose Kannan entry is +-S_KAN, then solve for d."""
    m = len(sigs)
    dim = 2 * m + 1
    S_K1, S_D, S_K2, S_KAN = scales(n, k1_bound, k2_bound)
    for row in rows:
        last = row[dim - 1]
        if abs(last) != S_KAN: continue
        sign = 1 if last > 0 else -1
        k1s, k2s, ok = [], [], True
        for i in range(m):
            a, b = sign * row[i], sign * row[m + i]
            if a % S_K1 or b % S_K2:
                ok = False; break
            k1s.append(a // S_K1); k2s.append(b // S_K2)
        if not ok:
            continue
        d_cand = d_from_k(sigs, k1s, k2s, n, lam)
        if d_cand is not None and d_cand == d_secret:
            return d_cand
    return None


# ---------------------------------------------------------------------------
# L_B -- explicit CVP (dim 2m), Babai nearest-plane
# ---------------------------------------------------------------------------

def build_lattice_B(sigs, n, lam, k1_bound, k2_bound):
    m = len(sigs)
    dim = 2 * m
    S_K1, S_D, S_K2, S_KAN = scales(n, k1_bound, k2_bound)
    rows = []
    for i in range(m):
        r = [0] * dim; r[i] = n * S_K1; rows.append(r)
    r = [0] * dim
    for i in range(m):
        r[i] = sigs[i]['B'] * S_K1
    rows.append(r)
    for i in range(m):
        r = [0] * dim
        r[i] = -lam * S_K1
        r[m + i] = S_K2
        rows.append(r)
    return rows

def babai_nearest_plane(basis_rows, target):
    """Exact-rational Babai nearest-plane; basis_rows must be LLL-reduced and
    linearly independent.  Returns the lattice vector closest to `target`."""
    from fractions import Fraction
    k = len(basis_rows)
    # Gram-Schmidt over Q (exact)
    gs, mu = [], []
    for i in range(k):
        v = [Fraction(x) for x in basis_rows[i]]
        coeffs = []
        for j in range(i):
            gj = gs[j]
            den = sum(x * x for x in gj)
            c = Fraction(0) if den == 0 else sum(a * b for a, b in zip(basis_rows[i], gj)) / den
            coeffs.append(c)
            v = [a - c * b for a, b in zip(v, gj)]
        gs.append(v); mu.append(coeffs)
    b = [Fraction(x) for x in target]
    coef = [0] * k
    for i in range(k - 1, -1, -1):
        gi = gs[i]
        den = sum(x * x for x in gi)
        if den == 0:
            continue
        c = sum(a * bb for a, bb in zip(b, gi)) / den
        ci = int(c + Fraction(1, 2)) if c >= 0 else -int(-c + Fraction(1, 2))
        coef[i] = ci
        b = [a - ci * Fraction(x) for a, x in zip(b, basis_rows[i])]
    out = [0] * len(target)
    for i in range(k):
        if coef[i]:
            for j in range(len(target)):
                out[j] += coef[i] * basis_rows[i][j]
    return out

def recover_B(basis_rows, sigs, n, lam, k1_bound, k2_bound, d_secret):
    m = len(sigs)
    S_K1, S_D, S_K2, S_KAN = scales(n, k1_bound, k2_bound)
    target = [sigs[i]['A'] * S_K1 for i in range(m)] + [0] * m
    w = babai_nearest_plane(basis_rows, [-t for t in target])
    cand = [t + x for t, x in zip(target, w)]
    for sign in (1, -1):
        k1s, k2s, ok = [], [], True
        for i in range(m):
            a, b = sign * cand[i], sign * cand[m + i]
            if a % S_K1 or b % S_K2:
                ok = False; break
            k1s.append(a // S_K1); k2s.append(b // S_K2)
        if not ok:
            continue
        d_cand = d_from_k(sigs, k1s, k2s, n, lam)
        if d_cand is not None and d_cand == d_secret:
            return d_cand
    return None


# ---------------------------------------------------------------------------
# fpylll driver: reduce a (possibly rank-deficient) generating set
# ---------------------------------------------------------------------------

def reduce_rows(rows, beta=None):
    """LLL (or BKZ if beta given) a list of integer rows.  Drops zero rows that
    fplll emits for rank-deficient generating sets.  Returns list of rows."""
    ncols = len(rows[0])
    A = IntegerMatrix(len(rows), ncols)
    for i, r in enumerate(rows):
        for j, x in enumerate(r):
            A[i, j] = x
    LLL.reduction(A)
    if beta is not None:
        BKZ.reduction(A, BKZ.Param(beta))
    out = [[A[i][j] for j in range(ncols)] for i in range(A.nrows)]
    return [r for r in out if any(r)]


