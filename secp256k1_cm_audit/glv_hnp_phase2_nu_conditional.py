"""
GLV-HNP Phase 2, Thread 25: is mu a second coordinate, or is its apparent
power mediated by NU after all?

Pre-registered by the 2026-08-07 (Thread 24) log entry:

  H25: within the ambiguous band 1.04 <= NU <= 2.20 (where the nearest-plane
       guarantee gives no answer), AUC(-mu -> Kannan-LLL recovery) stays
       >= 0.8.
  If yes, mu is a genuine second coordinate and the pair (NU, mu) is the
  2-parameter viability test Phase 2 has been missing; the deliverable is a
  logistic fit on (log NU, log mu) with its decision boundary.
  If no -- if mu's apparent power is entirely mediated by NU after all --
  then the W5 result is a stratification artifact and the closed form should
  be retired.

Why it matters.  Thread 24 established two things that do not sit together:
NU = max_i 2|<e,b*_i>|/||b*_i||^2 is an exact, sound nearest-plane certificate
(96 TP / 0 FP over 410 instances at NU <= 1), yet at fixed bias strength it is
a WORSE ranker of actual Kannan-LLL recovery than nu_hat = mu/sqrt(det L2),
which needs no lattice reduction at all -- and the two are mutually
uncorrelated inside every eff stratum (Spearman -0.28..+0.16).  Two
uncorrelated predictors of the same event means two mechanisms.  Thread 25
asks whether the second one survives conditioning on the first.

Three confounds this script has to kill before H25 can be believed:

  C1  scale.  mu = lambda_1(L2) carries an absolute scale that moves with
      (n, K1, K2).  Conditioning on a NU band pools across eff strata, so a
      raw-mu AUC can be re-reading the bias strength.  nu_hat = mu/sqrt(det2)
      is the size-free version; both are reported, and `eff` itself is
      carried as a control column throughout.
  C2  composition.  If NU-band membership correlates with eff, then ANY
      eff-correlated score separates inside a band for free.  A2 therefore
      re-does the test inside (NU band x eff stratum) cells, where neither
      NU nor eff can vary much.
  C3  the reverse direction.  If mu is a real second coordinate then NU must
      also separate at fixed mu.  A1b runs the transpose: condition on
      nu_hat bands and measure AUC(-NU).

Data: the 500-instance 17-bit table of Thread 24's W5/W6, regenerated by
  python3 glv_hnp_phase2_gsprofile_strat.py --dump-json strat17.jsonl
(20 j=0 GLV curves x 5 eff strata x 5 seeds, dim 24, m = 12).

Run: python3 glv_hnp_phase2_nu_conditional.py [strat17.jsonl]
"""

