def auc_split(rows, key):
    """AUC of the score -key over rows, or nan if a class is empty."""
    pos = [r[key] for r in rows if r['ok']]
    neg = [r[key] for r in rows if not r['ok']]
    return auc(pos, neg)


def auc_perm_p(rows, key, trials=2000, seed=20250807):
    """One-sided permutation p-value for AUC > 0.5 (label shuffle)."""
    pos = [r[key] for r in rows if r['ok']]
    neg = [r[key] for r in rows if not r['ok']]
    if not pos or not neg:
        return float('nan')
    obs = auc(pos, neg)
    vals = pos + neg
    npos = len(pos)
    rng = random.Random(seed)
    hits = 0
    for _ in range(trials):
        rng.shuffle(vals)
        if auc(vals[:npos], vals[npos:]) >= obs:
            hits += 1
    return (hits + 1.0) / (trials + 1.0)


def logistic_irls(X, y, ridge=1e-6, iters=60):
    """IRLS logistic fit.  X includes no intercept column; one is prepended."""
    n = len(X)
    d = len(X[0]) + 1
    A = [[1.0] + list(row) for row in X]
    w = [0.0] * d
    for _ in range(iters):
        # gradient and Hessian of the ridge-penalised log-likelihood
        g = [0.0] * d
        H = [[ridge if i == j else 0.0 for j in range(d)] for i in range(d)]
        for i in range(n):
            z = sum(w[j] * A[i][j] for j in range(d))
            z = max(-30.0, min(30.0, z))
            pi = 1.0 / (1.0 + math.exp(-z))
            r = y[i] - pi
            s = max(pi * (1.0 - pi), 1e-9)
            for j in range(d):
                g[j] += r * A[i][j]
                for k in range(d):
                    H[j][k] += s * A[i][j] * A[i][k]
        for j in range(d):
            g[j] -= ridge * w[j]
        step = solve(H, g)
        if step is None:
            break
        w = [w[j] + step[j] for j in range(d)]
        if max(abs(s) for s in step) < 1e-10:
            break
    return w


def solve(M, b):
    """Gaussian elimination with partial pivoting."""
    d = len(b)
    A = [row[:] + [b[i]] for i, row in enumerate(M)]
    for c in range(d):
        piv = max(range(c, d), key=lambda r: abs(A[r][c]))
        if abs(A[piv][c]) < 1e-14:
            return None
        A[c], A[piv] = A[piv], A[c]
        for r in range(d):
            if r == c:
                continue
            f = A[r][c] / A[c][c]
            for k in range(c, d + 1):
                A[r][k] -= f * A[c][k]
    return [A[i][d] / A[i][i] for i in range(d)]


def loglik(X, y, w):
    tot = 0.0
    for i, row in enumerate(X):
        z = w[0] + sum(w[j + 1] * row[j] for j in range(len(row)))
        z = max(-30.0, min(30.0, z))
        p = 1.0 / (1.0 + math.exp(-z))
        tot += math.log(p if y[i] else 1.0 - p + 1e-300)
    return tot


def model_auc(X, y, w):
    sc = []
    for row in X:
        sc.append(w[0] + sum(w[j + 1] * row[j] for j in range(len(row))))
    # higher score -> more likely to recover, and auc() scores -x, so negate
    pos = [-s for s, t in zip(sc, y) if t]
    neg = [-s for s, t in zip(sc, y) if not t]
    return auc(pos, neg)


def fmt(x, w=8, p=4):
    return f"{'   n/a':>{w}}" if x != x else f"{x:>{w}.{p}f}"


