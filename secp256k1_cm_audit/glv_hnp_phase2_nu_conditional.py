def load(path):
    rows = []
    with open(path) as fh:
        for line in fh:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    for r in rows:
        # W1b's two-block step: head of the profile is m copies of lambda_1(L2),
        # the second block sits at lambda_2 and collapses onto the head as the
        # K1 wall is crossed.  step -> 0 is the collapse.
        p = r['prof']
        head = sum(math.log2(v) for v in p[:M17] if v > 0) / M17
        tail = sum(math.log2(v) for v in p[M17:] if v > 0) / (len(p) - M17)
        r['step'] = tail - head
        r['step1'] = (math.log2(p[M17]) - math.log2(p[0])) if p[0] > 0 else 0.0
        # sign-corrected: the empirical direction is LARGER step -> recovery,
        # so -step is the score to compare fairly against nu_hat.
        r['mstep'] = -r['step']
        r['logNU'] = math.log(r['NU'])
        r['lognuhat'] = math.log(r['nuhat'])
        r['logmu'] = math.log(r['mu'])
    return rows


