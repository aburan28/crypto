C_P, C_PC = 0.2096, 0.4192

def predicted_k1_max(n, m, k2_bound, C):
    """K1 < C^2 * n^(1/2-1/m) / kappa,  kappa = K2/sqrt(n)."""
    kappa = k2_bound / math.sqrt(n)
    return C * C * n ** (0.5 - 1.0 / m) / kappa

def gh_lambda1(n, m, k1_bound, k2_bound):
    S_K1, _, S_K2, _ = scales(n, k1_bound, k2_bound)
    logdet = (m - 1) * math.log(n) + m * math.log(S_K1) + m * math.log(S_K2)
    return math.sqrt(2 * m / (2 * math.pi * math.e)) * math.exp(logdet / (2 * m))

