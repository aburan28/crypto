# Formulations P / PC -- projected CVP
# ---------------------------------------------------------------------------

def build_projected(sigs, n, lam, k1_bound, k2_bound):
    """(2m+1) x 2m generating matrix of L' (rank 2m) and the target."""
    m = len(sigs)
    S_K1, _, S_K2, _ = scales(n, k1_bound, k2_bound)
    cols = 2 * m
    rows = []
    for i in range(m):                       # r_i
        r = [0] * cols; r[i] = n * S_K1; rows.append(r)
    r = [sigs[i]['B'] * S_K1 for i in range(m)] + [0] * m     # r_d
    rows.append(r)
    for i in range(m):                       # r_{2,i}
        r = [0] * cols
        r[i] = -(lam % n) * S_K1
        r[m + i] = S_K2
        rows.append(r)
    target = [-sigs[i]['A'] * S_K1 for i in range(m)] + [0] * m
    return rows, target

def projected_basis(rows, cols):
    """LLL-reduce the rank-deficient generating set, drop zero rows,
    return a full-rank (cols x cols) IntegerMatrix basis of L'."""
    A = IntegerMatrix.from_matrix(rows)
    LLL.reduction(A)
    keep = [i for i in range(A.nrows) if any(A[i][j] != 0 for j in range(cols))]
    assert len(keep) == cols, f"rank {len(keep)} != {cols}"
    return IntegerMatrix.from_matrix([[A[i][j] for j in range(cols)] for i in keep])

def run_P(sigs, n, lam, k1_bound, k2_bound, d_secret, centered, babai=False):
    """Returns (ok, info).  info carries geometry for E2/E3.
    babai=True replaces exact CVP by Babai nearest-plane on the LLL basis,
    isolating how much of the gain needs exact CVP."""
    m = len(sigs)
    S_K1, _, S_K2, _ = scales(n, k1_bound, k2_bound)
    cols = 2 * m
    rows, target = build_projected(sigs, n, lam, k1_bound, k2_bound)
    c1 = k1_bound // 2 if centered else 0
    c2 = k2_bound // 2 if centered else 0
    t = list(target)
    for i in range(m):
        t[i] += c1 * S_K1
        t[m + i] += c2 * S_K2

    B = projected_basis(rows, cols)
    lam1 = norm([B[0][j] for j in range(cols)])       # LLL b_1 (upper bd on l_1)

    e_planted = [(sigs[i]['k1'] - c1) * S_K1 for i in range(m)] + \
                [(sigs[i]['k2'] - c2) * S_K2 for i in range(m)]
    e_norm = norm(e_planted)

    if babai:
        gso = GSO.Mat(B, float_type='mpfr' if n.bit_length() > 40 else 'd')
        gso.update_gso()
        coef = gso.babai([int(x) for x in t])
        v = [sum(coef[i] * B[i][j] for i in range(cols)) for j in range(cols)]
    else:
        v = CVP.closest_vector(B, tuple(t))
    e = [v[j] - t[j] for j in range(cols)]

    # read (k1_i, k2_i) back out of the error vector
    k1s, k2s = [], []
    ok_shape = True
    for i in range(m):
        if e[i] % S_K1 or e[m + i] % S_K2:
            ok_shape = False; break
        k1s.append(e[i] // S_K1 + c1)
        k2s.append(e[m + i] // S_K2 + c2)
    d_cand = None
    if ok_shape:
        # A_i + B_i*d - lam*k2_i = k1_i (mod n)  ->  d = (k1_i + lam*k2_i - A_i)/B_i
        for i in range(m):
            try:
                cand = (k1s[i] + lam * k2s[i] - sigs[i]['A']) * modinv(sigs[i]['B'], n) % n
            except ValueError:
                continue
            hits = sum(1 for j in range(m)
                       if (sigs[j]['A'] + sigs[j]['B'] * cand - lam * k2s[j]) % n == k1s[j] % n)
            if hits == m:
                d_cand = cand
                break
    info = {'lam1': lam1, 'e_norm': e_norm, 'found_norm': norm(e),
            'margin': lam1 / (2.0 * e_norm) if e_norm else float('inf')}
    return (d_cand == d_secret and d_cand is not None), info

