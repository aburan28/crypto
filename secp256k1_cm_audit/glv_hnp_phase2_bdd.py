def trial(curve, m, k1_bound, seed, variant):
    p, b, n, lam, G = curve
    k2_bound = math.isqrt(n) + 1
    d = random.Random(seed + 7777).randint(1, n - 1)
    sigs = gen_signatures(G, d, m, n, lam, p, k1_bound, k2_bound, seed)
    if len(sigs) < m:
        return False, None
    if variant in ('K', 'KC'):
        return run_K(sigs, n, lam, k1_bound, k2_bound, d, centered=(variant == 'KC'))
    return run_P(sigs, n, lam, k1_bound, k2_bound, d,
                 centered=(variant in ('PC', 'PCb')), babai=(variant == 'PCb'))

def rate(curve, m, k1_bound, variant, seeds=SEEDS):
    wins, infos = 0, []
    for s in seeds:
        ok, info = trial(curve, m, k1_bound, s, variant)
        wins += ok
        if info: infos.append(info)
    return wins, infos

def wall(curve, m, variant, grid, seeds=SEEDS, thresh=0.6):
    """Largest K1 in `grid` with success rate >= thresh (0 if none)."""
    best = 0
    for k1 in grid:
        w, _ = rate(curve, m, k1, variant, seeds)
        if w / len(seeds) >= thresh:
            best = k1
        else:
            break
    return best


