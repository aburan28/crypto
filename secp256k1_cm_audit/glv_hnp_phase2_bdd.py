def modinv(a, m):
    return pow(a, -1, m)

def ec_add(P, Q, p):
    if P is None: return Q
    if Q is None: return P
    x1, y1 = P; x2, y2 = Q
    if x1 == x2:
        if (y1 + y2) % p == 0: return None
        s = 3 * x1 * x1 * modinv(2 * y1, p) % p
    else:
        s = (y2 - y1) * modinv(x2 - x1, p) % p
    x3 = (s * s - x1 - x2) % p
    y3 = (s * (x1 - x3) - y1) % p
    return (x3, y3)

def ec_mul(P, k, p):
    if k == 0: return None
    R, Q = None, P
    while k > 0:
        if k & 1: R = ec_add(R, Q, p)
        Q = ec_add(Q, Q, p)
        k >>= 1
    return R

def tonelli_shanks(a, p):
    a %= p
    if a == 0: return 0
    if pow(a, (p - 1) // 2, p) != 1: return None
    if p % 4 == 3: return pow(a, (p + 1) // 4, p)
    q, s = p - 1, 0
    while q % 2 == 0: q //= 2; s += 1
    z = 2
    while pow(z, (p - 1) // 2, p) != p - 1: z += 1
    mm, c, t, r = s, pow(z, q, p), pow(a, q, p), pow(a, (q + 1) // 2, p)
    while True:
        if t == 0: return 0
        if t == 1: return r
        i, tmp = 0, t
        while tmp != 1: tmp = tmp * tmp % p; i += 1
        b = pow(c, 1 << (mm - i - 1), p)
        mm, c, t, r = i, b * b % p, t * b * b % p, r * b % p

def find_generator(p, b, n, seed=12345):
    rng = random.Random(seed)
    for _ in range(20000):
        x = rng.randint(0, p - 1)
        rhs = (pow(x, 3, p) + b) % p
        y = tonelli_shanks(rhs, p)
        if y is None or y == 0: continue
        P = (x, y)
        if ec_mul(P, n, p) is None and P is not None:
            return P
    return None

# ---------------------------------------------------------------------------
# j=0 CM curve search (Eisenstein)
# ---------------------------------------------------------------------------

def eisenstein_decompose(p):
    """p = a^2 - a*b + b^2 with p = 1 mod 3 (norm form of Z[omega])."""
    if p % 3 != 1: return None
    sq = tonelli_shanks(p - 3, p)          # sqrt(-3) mod p
    if sq is None: return None
    # Cornacchia on x^2 + 3 y^2 = 4p
    a, b = 2 * p, (sq if sq % 2 == 1 else p - sq) % (2 * p)
    if b % 2 == 0: b = 2 * p - b
    lim = math.isqrt(4 * p)
    while b > lim:
        a, b = b, a % b
    r = 4 * p - b * b
    if r % 3 != 0: return None
    c2 = r // 3
    c = math.isqrt(c2)
    if c * c != c2: return None
    # 4p = b^2 + 3c^2  ->  (a_e, b_e) with p = a^2-ab+b^2
    for (u, v) in (((b + 3 * c) // 2, c), ((b - 3 * c) // 2, -c),
                   ((-b + 3 * c) // 2, c), ((b + c) // 2, (b - c) // 2)):
        if u * u - u * v + v * v == p:
            return (u, v)
    return None

def j0_traces(a, b):
    return [2 * a - b, -2 * a + b, -(a + b), a + b, 2 * b - a, a - 2 * b]

def glv_roots(n):
    """The two roots of x^2+x+1 = 0 mod n (n = 1 mod 3), or None."""
    sq = tonelli_shanks((n - 3) % n, n)
    if sq is None: return None
    inv2 = modinv(2, n)
    r1 = (n - 1 + sq) * inv2 % n
    r2 = (n - 1 + (n - sq)) * inv2 % n
    if (r1 * r1 + r1 + 1) % n != 0: r1, r2 = r2, r1
    if (r1 * r1 + r1 + 1) % n != 0: return None
    return (min(r1, r2), max(r1, r2))

def lam_star(lam, n):
    return min(lam, n - lam) / n

def build_curve(p, n, seed=12345):
    rng = random.Random(seed)
    for _ in range(400):
        b = rng.randint(1, p - 1)
        x = rng.randint(0, p - 1)
        rhs = (pow(x, 3, p) + b) % p
        y = tonelli_shanks(rhs, p)
        if y is None or y == 0: continue
        if ec_mul((x, y), n, p) is None:
            G = find_generator(p, b, n, seed=seed)
            if G is not None:
                return (b, G)
    return None

def search_curves(lo, hi, want, seed=12345):
    """j=0 GLV curves with p in [lo,hi), n prime, n = 1 mod 3."""
    out = []
    p = int(sympy.nextprime(lo))
    while p < hi and len(out) < want:
        if p % 3 == 1:
            eis = eisenstein_decompose(p)
            if eis is not None:
                for t in j0_traces(*eis):
                    nc = p + 1 - t
                    if nc < 8 or nc % 3 != 1 or not sympy.isprime(nc):
                        continue
                    roots = glv_roots(nc)
                    if roots is None: continue
                    cur = build_curve(p, nc, seed)
                    if cur is None: continue
                    out.append((p, cur[0], nc, roots[0], cur[1]))
                    break
        p = int(sympy.nextprime(p))
    return out

